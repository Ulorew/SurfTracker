# --- демпфирование экстраполяции (тикет "счёт кандидата", п.1) -----------
# На такте БЕЗ принятого кандидата модуль скорости затухает: v <- v*exp(-dt/tau).
# При принятом кандидате — штатное обновление, затухания нет. Ковариацию это
# не трогает: неопределённость обязана расти, сжимается только скорость.
#
# Смысл — ограничение по построению: экстраполяция при вечной потере уходит
# от точки исчезновения не дальше v0*tau, а не в бесконечность.
#
# ВНИМАНИЕ, дискретная поправка. Тикет предписывает домножать ПОСЛЕ predict
# (F не менять), поэтому первый шаг делается полной скоростью, и сумма
# смещений равна v0*dt/(1-exp(-dt/tau)), а не v0*tau. При dt=1/3 с и tau=1.5 с
# это 1.11*v0*tau — на 11% больше заявленного предела. Точный предел v0*tau
# дало бы интегрирование по непрерывному решению (сдвиг на v*tau*(1-exp(-dt/tau))),
# но это уже другая формула шага, чем задана в тикете.
EXTRAPOLATION_TAU_SEC = 1.5

