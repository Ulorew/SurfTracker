"""Все константы тикета "трекинг, офлайн на видео" — одним файлом, крутить
по результатам теста (см. докстринг тикета, п.6). Ничего из этого не
захардкожено в track_filters.py/track_logic.py/track_run.py.
"""

import config

# --- такт -------------------------------------------------------------
# Частоты детекции (Гц), симулируются прореживанием кадров видео. Базовая —
# первая в списке; остальные — для строк чувствительности к частоте
# (только на видео с достаточной нативной частотой, см. тикет п. "Такт").
TICK_HZ_BASE = 3.0
TICK_HZ_SENSITIVITY = []  # напр. [4.0, 6.0] на 60fps-материале — пока нет

# --- окно слежения ------------------------------------------------------
TRACK_WINDOW_K = 3.5  # тот же k, что в track_window.py/config.py

# Пол стороны окна. crop.py по правилу "без паддинга" НИКОГДА не берёт меньше
# config.WINDOW_SIZE реальных пикселей кадра, поэтому окно с номинальной
# стороной меньше — фикция: модель всё равно видит WINDOW_SIZE. Пока этого
# пола не было, порог выбора цели (доля стороны) оказывался втрое строже
# задуманного, расширение окна на пропуск ниже 640 не делало ничего, а в
# оверлей рисовалась не та рамка, которую видела модель.
#
# Величина ПИКСЕЛЬНАЯ и остаётся такой: она свойство crop(), а не петли.
# track_run переводит её в угловой пол окна через intrinsics клипа
# (px_size_to_angle) — сама петля живёт в углах и о пикселях не знает.
DETECT_MIN_WINDOW_PX = config.WINDOW_SIZE

# медленный фильтр РАЗМЕРА цели (не путать с фильтром положения/скорости):
# асимметрия — растёт быстро, падает медленно (тикет п.1: большое окно стоит
# точности, маленькое — потери цели, поэтому ошибаться в сторону "больше").
SIZE_FILTER_GROW_RATE = 0.5    # доля разницы (new-filtered), применяемая при росте
SIZE_FILTER_SHRINK_RATE = 0.1  # то же при уменьшении — заметно медленнее

# --- выбор цели среди детекций (тикет п.2) -------------------------------
# порог отсечения: доля СТОРОНЫ ОКНА, дальше которой детекция не принимается
# как цель, даже если это ближайшая из найденных. НЕ по уверенности.
TARGET_SELECT_MAX_DIST_FRAC = 0.30

# --- механизмы против подмены цели (тикет "подмены v2") -------------------
# Включаются по отдельности, чтобы вклад каждого был виден в таблице прогонов.

# А: размер кандидата участвует в счёте. Счёт = расстояние + SIZE_LAMBDA *
# |log(размер_кандидата / размер_предсказанный)| * сторона_окна (домножение на
# сторону приводит безразмерный лог-член к пикселям, иначе слагаемые
# несопоставимы). Вето: отношение размеров вне [1/R, R] — кандидат не
# принимается вовсе, трекер уходит в пропуск/экстраполяцию.
ENABLE_SIZE_SCORING = False
SIZE_LAMBDA = 0.5
SIZE_VETO_RATIO = 1.8

# Б: правило окклюзии. Если >= 2 кандидатов, прошедших вето, оказались ближе
# OCCLUSION_PROXIMITY_FRAC стороны окна друг к другу — не выбирать никого
# OCCLUSION_HOLD_TICKS тактов, идти чистой экстраполяцией, окно НЕ расширять.
# Смысл: на пересечении сёрферов любой выбор — монетка, а ошибка необратима.
ENABLE_OCCLUSION_HOLD = False
OCCLUSION_PROXIMITY_FRAC = 0.25
OCCLUSION_HOLD_TICKS = 4

# В: гейт по скорости. Кандидат, принятие которого требует мгновенной
# скорости, отличающейся от текущей оценки больше чем на
# VELOCITY_GATE_FACTOR * |v| + VELOCITY_GATE_NOISE_ANG_PER_SEC, штрафуется
# третьим слагаемым счёта; при VELOCITY_VETO_MULT-кратном превышении — вето.
# Осмысленно только вместе с А: при нулевой скорости первых тактов слеп.
ENABLE_VELOCITY_GATE = False
VELOCITY_GATE_FACTOR = 2.0
# Шумовой пол в УГЛОВЫХ единицах (рад/с): петля перешла в углы (тикет
# "ночь", п.2.0), и пиксельный порог здесь был бы несопоставим со скоростью
# состояния. 0.048 рад/с ~ 2.75 град/с — это прежние 60 px/с при типичном
# f_x ~ 1250 (кадр 1920, поле зрения 75 град), то есть смысл константы не
# изменился, изменились только единицы.
VELOCITY_GATE_NOISE_ANG_PER_SEC = 0.048
VELOCITY_LAMBDA = 0.5
VELOCITY_VETO_MULT = 3.0

# --- фильтр (тикет п.3) --------------------------------------------------
FILTER_LEVEL = 1  # 0 = последняя детекция + разностная скорость; 1 = alpha-beta
ALPHA_BETA_ALPHA = 0.6  # вес невязки в позиции
ALPHA_BETA_BETA = 0.3   # вес невязки в скорости

# --- пропуски и расширение окна (тикет п.3) ------------------------------
WINDOW_EXPAND_PER_MISS = 1.15  # множитель стороны окна на КАЖДЫЙ подряд идущий пропуск

# --- потеря и повторный захват (тикет п.4) --------------------------------
MISS_TO_LOST_N = 5  # столько подряд пропусков -> режим потери
# порог близости для повторного захвата — та же логика, что выбор цели, но
# считается от ПОСЛЕДНЕЙ ИЗВЕСТНОЙ (дотрековой) стороны окна, не от текущей
# раздувшейся lost-стороны: иначе порог растёт вместе с окном и перестаёт
# что-либо отсекать.
REACQUIRE_MAX_DIST_FRAC = 0.30

# --- детекция -------------------------------------------------------------
# низкий порог на самом инференсе — финальная приёмка цели идёт через
# select_target (по расстоянию), не через уверенность; будет резаться
# TARGET_SELECT_MAX_DIST_FRAC, а не conf (см. видео-демо на "1. Петля":
# на реальном видео уверенность модели занижена из-за разрыва домена).
DETECT_LOW_CONF = 0.08

# --- истина (тикет "Материал и истина") ------------------------------------
GT_LABEL_FPS = 2.0       # строго 2 fps, грубые рамки
GT_HIT_BOX_SCALE = 1.2   # критерий попадания: центр предсказания внутри рамки x1.2
# Вторая, НЕэквивалентная формулировка того же критерия из тикета
# ("расстояние центров < ~0.6 размера рамки"). Совпадает с первой только на
# квадратной рамке; у паруса рамка вытянутая, поэтому считаются обе — какую
# считать основной, решает человек (см. докстринг is_hit в track_eval.py).
GT_HIT_RADIAL_FRAC = 0.6

# Максимальный разрыв между соседними ОПОРНЫМИ кадрами, который ещё считается
# интерполируемым. Разметка идёт с шагом ~0.5 с; если цель не размечена
# несколько кадров подряд, интерполяция через такую дыру не восстанавливает
# траекторию, а выдумывает её — и метрика начинает оценивать прогон по
# несуществующей истине. За порогом истины просто нет (такт не засчитывается).
GT_MAX_GAP_SEC = 1.5
