// ЧАСЫ СТЕНДА. Живость тракта различима только по времени, поэтому время
// здесь — управляемая величина, а не системная: замершие регистры от
// неподвижного вала отличает лишь то, сколько его прошло.
unsigned long host_now_us = 0;


// ---- числа замера, выписанные из reports/ЭНКОДЕР_PWM.md -------------------
//
// ТРИ ПРЕЖНИЕ ПРОВЕРКИ БЫЛИ ОДНИМ ФАКТОМ, ПОКАЗАННЫМ ТРИЖДЫ. Наклон, размах и
// мёртвый участок связаны тождественно: размах = 360/наклон, мёртвый участок =
// 1 - размах. Проверять все три — значит трижды спросить одно и то же и
// принять это за тройное подтверждение.
//
// РАЗБОР ПРОТИВОРЕЧИЯ 362.07 против 362.6..362.8 (23.08). Числа разошлись не
// потому, что один из замеров неверен, а потому, что это ДВЕ ОЦЕНКИ ОДНОЙ
// величины: по полному размаху скважности и по обрезанному. Пересчитано из
// сырых регистров трёх записанных прогонов (runs/v2_spin, ladder_open,
// ladder_load):
//
//   оценка по полному min..max   размах 0.99394..0.99420  ->  наклон 362.10..362.20
//   оценка с обрезкой 0.1%       размах 0.99056..0.99273  ->  наклон 362.64..363.43
//
// Полный размах согласуется на трёх прогонах в пределах 0.03%, обрезанный
// гуляет на 0.8% и зависит от доли обрезки — то есть первая оценка и есть
// измерение, а вторая измеряет выбор порога. Прежняя полоса 362.6..362.8 и
// «мёртвый участок 0.7..1.1%» получены обрезкой, поэтому и согласовывались
// между собой: это одно решение, увиденное дважды.
//
// СВЕРКА ШВОМ, независимая от всего вышесказанного: за оборот угол обязан
// набрать ровно 360. При наклоне 362.07 измеренный размах даёт 359.87 (недобор
// 0.13 градуса), при 362.7 — 360.50 (перебор 0.50). Меньше ошибка у 362.07.
static const double MEAS_SLOPE_LO = 362.0;   // полный размах, три прогона
static const double MEAS_SLOPE_HI = 362.3;
// Размах и мёртвый участок ВЫВОДЯТСЯ из наклона тождественно, поэтому
// отдельными проверками больше не притворяются. Здесь — ИЗМЕРЕННЫЙ размах из
// записей, и сверяется с ним именно он: это единственное сравнение с железом.
static const double DATA_SPAN_LO  = 0.9935;  // 0.99394..0.99420 на трёх прогонах
static const double DATA_SPAN_HI  = 0.9948;
// ГЕНЕРИМ ТЕМ ЖЕ НАКЛОНОМ, КОТОРЫМ КЛАСС РАЗБИРАЕТ. Прежде тут стояло 362.7
// намертво, и после смены константы класса тест начал мерить не разбор, а
// разницу двух чисел — то есть проверял бы совпадение фикстуры с кодом, а не
// верность кода. Проверка «угол отвечает доле оборота» осмысленна только
// когда обе стороны говорят об одной шкале.
static const double SIM_SLOPE     = CAPSENS_DEG_PER_DUTY;
static const double SIM_SPAN      = 360.0 / SIM_SLOPE;
static const double SIM_DUTY_MIN  = 3.0 / 921.0;   // SENS_MIN_US / кадр
static const uint32_t SIM_PERIOD  = 156700;        // 922 мкс при 170 МГц

static const double TWO_PI = 6.283185307179586;
static const double DEG = 360.0 / TWO_PI;          // радианы -> градусы

static int failed = 0;
static const char *cur = "";
static void ok(bool cond, const char *what) {
  if (!cond) { failed++; printf("  СБОЙ  %s: %s\n", cur, what); }
}

// Доступ к getSensorAngle(): в бою его дёргает SimpleFOC через update(),
// стенду он нужен напрямую.
struct Probe : public CaptureSensor {
  explicit Probe(TIM_TypeDef *t) : CaptureSensor(t) {}
  using CaptureSensor::getSensorAngle;
};

// ---------------------------------------------------------------- подложка
//
// Модель кадра. Нарастающие фронты R0, R1...; кадр k = [Rk, Rk+1). В CCR1
// период кадра k, в CNT возраст текущего кадра k+1, в CCR2 — ширина импульса
// кадра k, пока не пришёл спад кадра k+1, и кадра k+1 после него.
struct Sim {
  TIM_TypeDef t;
  uint32_t period = SIM_PERIOD;

  // ЧАСЫ ДВИГАЕТ ПОДЛОЖКА, А НЕ ТЕСТ. Пороги годности заданы во времени, и
  // если время не идёт, годность не наступает никогда — тесты мерили бы не
  // класс, а неподвижность часов. Такт по умолчанию 30 мкс: это измеренный
  // полный такт разомкнутого контура (stm/looprate_g431), то есть частота, с
  // которой класс и будут опрашивать.
  unsigned long tick_us = 30;
  void tick() { host_now_us += tick_us; фаза++; }

  // СЧЁТЧИК ИДЁТ, А НЕ СТОИТ. TIM2 в режиме PWM input сбрасывается каждым
  // нарастающим фронтом и считает до следующего, то есть CNT — это возраст
  // внутри кадра, и он МЕНЯЕТСЯ непрерывно. Прежняя подложка ставила CNT
  // одним и тем же числом при повторных опросах, и класс справедливо называл
  // такой тракт замершим: при опросе раз в 30 мкс и кадре 922 мкс счётчик
  // успевает уйти на 5100 тиков, повторить значение он может только при
  // патологическом совпадении периодов.
  //
  // Тесты по-прежнему выбирают ПОЛОВИНУ кадра (высокую или низкую), а внутри
  // неё возраст гуляет — как оно и есть на железе.
  unsigned long фаза = 0;
  uint32_t возраст_в(uint32_t lo, uint32_t hi) const {
    if (hi <= lo + 1) return lo;
    return lo + (uint32_t)((фаза * 5107UL) % (hi - lo));   // 30 мкс * 170 МГц
  }

  static double duty_of(double turn) { return SIM_DUTY_MIN + turn * SIM_SPAN; }
  uint32_t high_of(double turn) const {
    return (uint32_t)llround(duty_of(turn) * (double)period);
  }
  void clear_sr() { t.SR.set(0); }
  /** Опрос в ВЫСОКОЙ фазе: CCR2 ещё от ПРЕДЫДУЩЕГО кадра.
   *  Пара согласована, но отсчёт старше на целый кадр. */
  void poll_stale(double turn, bool cc2if_set = true) {
    uint32_t h = high_of(turn);
    tick();
    t.CCR1.set(period); t.CCR2.set(h); t.CNT.set(возраст_в(1, h));
    t.SR.set(cc2if_set ? TIM_SR_CC2IF : 0);
  }
  /** Опрос в НИЗКОЙ фазе: ширина уже ТЕКУЩЕГО кадра, период с прошлого.
   *  Отсчёт СВЕЖИЙ; период датчика стабилен (дрейф 0.02%), так что годен. */
  void poll_fresh(double turn_next, bool cc2if_set = true) {
    uint32_t h = high_of(turn_next);
    tick();
    t.CCR1.set(period); t.CCR2.set(h); t.CNT.set(возраст_в(h + 1, period));
    t.SR.set(cc2if_set ? TIM_SR_CC2IF : 0);
  }
  /** Датчик молчит, НО ТАЙМЕР ЖИВ: фронтов нет, возраст непрерывно растёт.
   *  Это другой отказ, чем замирание таймера, и различать их обязательно. */
  void poll_dead(uint32_t age) {
    tick();
    uint32_t h = high_of(0.3);
    t.CCR1.set(period); t.CCR2.set(h); t.CNT.set(age + (uint32_t)(фаза * 5107UL));
    t.SR.set(TIM_SR_CC2IF);
  }
  /** ТАЙМЕР ЗАМЕР ЦЕЛИКОМ: регистры не меняются вовсе, включая счётчик.
   *  По регистрам это неотличимо от исправного тракта на неподвижном валу —
   *  различает только то, что время идёт, а CNT нет. */
  void poll_frozen() { tick(); }
};

static double wrap_deg(double d) {
  while (d < -180.0) d += 360.0;
  while (d >= 180.0) d -= 360.0;
  return d;
}

// =================================================== 1. перевод скважности
//
// Известные значения: доля оборота -> угол. Допуск 0.05 град — на порядок
// больше кванта захвата (0.026 шага энкодера) и на порядок меньше любой
// ошибки масштаба, которую стоит ловить.
static void test_scale() {
  cur = "перевод скважности";
  Sim s; Probe p(&s.t);
  const double turns[] = {0.0, 0.125, 0.25, 0.5, 0.75, 0.999};
  for (double u : turns) {
    s.poll_stale(u);
    double a = p.getSensorAngle() * DEG;      // градусы
    double want = u * 360.0;
    if (fabs(wrap_deg(a - want)) > 0.05) {
      printf("        доля %.3f: получено %.4f°, ожидалось %.4f°\n", u, a, want);
      ok(false, "угол не отвечает известной доле оборота");
    }
    ok(a >= 0.0 && a < 360.0, "угол обязан лежать в [0, 360)");
  }
}

// ============================================== 2. сверка наклона и размаха
//
// Та же независимая сверка, что в diag_metrics.py, только в обратную сторону:
// наклон обязан лежать в измеренной полосе, выведенный из него размах — в
// своей, а произведение обязано дать ровно 360. Это ловит подстановку
// наивного наклона и любую «round number» правку констант.
static void test_bridge_constants() {
  cur = "сверка наклона и размаха";
  ok(CAPSENS_DEG_PER_DUTY >= MEAS_SLOPE_LO && CAPSENS_DEG_PER_DUTY <= MEAS_SLOPE_HI,
     "наклон вне измеренной полосы 362.0..362.8 град на единицу скважности");
  // НАКЛОН ОБЯЗАН СОВПАДАТЬ С ПИТОНОВОЙ СТОРОНОЙ. Он жил в трёх местах и
  // разошёлся: 362.7 здесь, 362.4 в smoothness.py, замер 362.066. Импорт
  // межъязыковую границу не пересекает, поэтому число туда подставляет
  // check.sh, вытаскивая его из питона. Без этой проверки «одно правило —
  // одно место» кончается на границе языков.
#ifdef CAPSENS_PY_SLOPE
  ok(fabs((double)CAPSENS_DEG_PER_DUTY - (double)CAPSENS_PY_SLOPE) < 0.01,
     "наклон в классе разошёлся с наклоном в питоновом разборщике");
#else
  ok(false, "наклон питоновой стороны не подан: check.sh обязан его извлечь");
#endif
  // ЕДИНСТВЕННОЕ СРАВНЕНИЕ С ЖЕЛЕЗОМ: выведенный из константы размах против
  // размаха, ИЗМЕРЕННОГО по сырым регистрам записанных прогонов. Прежние
  // проверки размаха и мёртвого участка сверяли константу с производными той
  // же константы и пройти могли только всегда.
  ok(CAPSENS_DUTY_SPAN >= DATA_SPAN_LO && CAPSENS_DUTY_SPAN <= DATA_SPAN_HI,
     "размах из константы разошёлся с измеренным по записям 0.9939..0.9942");
  // Тождество, а не измерение: держится ради того, чтобы размах не завели
  // вторым независимым числом. Ровно 360 — иначе разрыв на шве кадра.
  double prod = (double)CAPSENS_DEG_PER_DUTY * (double)CAPSENS_DUTY_SPAN;
  ok(fabs(prod - 360.0) < 1e-3, "наклон x размах обязано быть ровно 360");
}

// ============================================================== 3. шов кадра
//
// На шве скважность падает с верхней границы диапазона на нижнюю. Угол обязан
// пройти через 360->0 БЕЗ РАЗРЫВА: шаг по углу такой же, как вне шва. Именно
// здесь ошибка наклона видна, а внутри кадра она размазана и мала.
static void test_seam() {
  cur = "шов кадра";
  Sim s; Probe p(&s.t);
  const double du = 0.002;
  double prev = 0.0; bool have = false;
  for (int i = -6; i <= 6; i++) {
    double u = i * du; while (u < 0.0) u += 1.0;
    s.poll_stale(u);
    double a = p.getSensorAngle() * DEG;
    ok(a >= 0.0 && a < 360.0, "угол на шве вышел из [0, 360)");
    if (have) {
      double step = wrap_deg(a - prev);
      if (fabs(step - du * 360.0) > 0.05) {
        printf("        доля %.4f: шаг %.4f°, ожидался %.4f°\n",
               u, step, du * 360.0);
        ok(false, "разрыв угла на шве кадра — наклон не сходится с размахом");
      }
    }
    prev = a; have = true;
  }
}

// ============================================ 4. два режима защёлкивания
//
// ОБА ГОДНЫ, и различаются только возрастом. Прежняя редакция класса браковала
// СВЕЖИЙ случай и принимала УСТАРЕВШИЙ — для контура управления выбор ровно
// наоборот. Доля брака при этом равнялась (1 - скважность), то есть зависела
// от УГЛА: на нижней части оборота тракт слеп почти всегда.
//
// Отказ воспроизведён на железе 22.08 (looprate_g431): скважность 0.156,
// paired=0, четыре негодных чтения подряд на полностью исправном тракте.
static void test_two_latch_modes() {
  cur = "два режима защёлкивания";
  Sim s; Probe p(&s.t);
  CaptureStatus st;

  s.poll_fresh(0.4);
  p.readRaw(st);
  ok(st.ok, "свежее чтение (ширина текущего кадра) обязано быть годным");
  ok(!st.prev_frame, "свежее чтение не должно помечаться как устаревшее");

  s.poll_stale(0.4);
  p.readRaw(st);
  ok(st.ok, "устаревшее на кадр чтение тоже годно");
  ok(st.prev_frame, "устаревшее чтение обязано быть ПОМЕЧЕНО");

  // ВОЗРАСТ ОБЯЗАН БЫТЬ ПОПРАВЛЕН. Без поправки потребитель решит, что
  // отсчёт свежее, чем он есть, ровно на кадр — а на этом возрасте стоит и
  // экстраполяция угла, и оценка скорости.
  // Сверяемся с ТЕМ CNT, который подложка выставила на последнем опросе:
  // счётчик кадра идёт непрерывно, и вписывать сюда его значение числом
  // значило бы проверять совпадение с копией, а не поправку на кадр.
  uint32_t cnt = s.t.CNT.get();
  ok(st.age >= s.period, "возраст устаревшего чтения обязан включать целый кадр");
  ok(st.age == cnt + s.period, "возраст обязан быть ровно CNT + период кадра");
}

// ================================= 4b. НЕ СЛЕПНУТЬ НА МАЛОЙ СКВАЖНОСТИ
//
// Регрессия на воспроизведённый отказ. При малой скважности почти все опросы
// попадают в низкую фазу кадра; если класс их бракует, годность рушится
// именно там, где вал стоит в нижней части оборота.
static void test_low_duty_not_blind() {
  cur = "малая скважность";
  Sim s; Probe p(&s.t);
  CaptureStatus st;

  int good = 0;
  const int N = 200;
  for (int i = 0; i < N; i++) {
    // Скважность 0.156 — ровно та, на которой отказало железо.
    if (i % 10 == 0) s.poll_stale(0.13);   // редкие попадания в высокую фазу
    else             s.poll_fresh(0.13);
    if (p.readRaw(st)) good++;
    p.getSensorAngle();
  }
  ok(good == N, "при малой скважности годными обязаны быть ВСЕ чтения");
  ok(p.isHealthy(), "годность не должна падать из-за положения вала");
}

// ==================================================== 5. частота опроса
//
// ПОЧЕМУ ПРОВЕРКА ПО CC2IF НЕ ГОДИЛАСЬ. Флаг отвечает на вопрос «был ли спад
// с моего прошлого чтения», то есть зависит от ЧАСТОТЫ ОПРОСА, а не от
// данных: при редком опросе взведён всегда, при частом почти никогда.
// Приговор класса обязан от него не зависеть вовсе.
static void test_poll_rate_independence() {
  cur = "частота опроса";
  Sim s; Probe p(&s.t);
  CaptureStatus a, b;

  // Одни и те же данные, разное состояние CC2IF -> одинаковый приговор.
  s.poll_fresh(0.6, /*cc2if_set=*/true);   p.readRaw(a);
  s.poll_fresh(0.6, /*cc2if_set=*/false);  p.readRaw(b);
  ok(a.ok == b.ok, "приговор не должен зависеть от CC2IF (свежее чтение)");
  ok(a.ok, "свежее чтение годно при любом CC2IF");

  s.poll_stale(0.6, /*cc2if_set=*/true);   p.readRaw(a);
  s.poll_stale(0.6, /*cc2if_set=*/false);  p.readRaw(b);
  ok(a.ok == b.ok, "приговор не должен зависеть от CC2IF (устаревшее чтение)");
  ok(a.prev_frame && b.prev_frame, "пометка устаревшего тоже не зависит от CC2IF");
}

// ==================================================== 6. период вне границ
static void test_period_bounds() {
  cur = "период вне границ";
  Sim s; Probe p(&s.t);
  CaptureStatus st;

  s.period = 100000;   // 588 мкс — ниже нижней границы 136000 тиков
  s.poll_stale(0.3);
  p.readRaw(st);
  ok(!st.period_ok, "короткий период обязан быть назван негодным");
  ok(!st.ok, "чтение с коротким периодом обязано быть негодным");

  s.period = 300000;   // 1765 мкс — выше верхней границы 212500 тиков
  s.poll_stale(0.3);
  p.readRaw(st);
  ok(!st.period_ok, "длинный период обязан быть назван негодным");
  ok(!st.ok, "чтение с длинным периодом обязано быть негодным");

  s.period = SIM_PERIOD;
  s.poll_stale(0.3);
  p.readRaw(st);
  ok(st.period_ok, "нормальный период обязан приниматься");

  // Вырожденная ширина: импульса нет вовсе и импульс шире кадра.
  s.t.CCR1.set(SIM_PERIOD); s.t.CCR2.set(0); s.t.CNT.set(0); s.t.SR.set(0);
  p.readRaw(st);
  ok(!st.width_ok && !st.ok, "нулевая ширина импульса обязана быть негодной");
  s.t.CCR2.set(SIM_PERIOD + 10); s.t.CNT.set(0);
  p.readRaw(st);
  ok(!st.width_ok && !st.ok, "импульс шире кадра обязан быть негодным");
}

// ======================================================== 7. фронтов нет
//
// Датчик замолчал: регистры замерли на последних значениях, а CNT растёт,
// потому что обнулять его больше нечему. Это ЕДИНСТВЕННЫЙ способ отличить
// замерший датчик от неподвижного вала — по числам они одинаковы.
static void test_no_edges() {
  cur = "фронтов нет";
  Sim s; Probe p(&s.t);
  CaptureStatus st;

  s.poll_dead(CAPSENS_AGE_MAX_TICKS + 1);
  p.readRaw(st);
  ok(!st.edges, "отсутствие фронтов обязано быть НАЗВАНО, а не свалено в общий отказ");
  ok(!st.ok, "чтение без фронтов обязано быть негодным");

  s.poll_dead(CAPSENS_AGE_MAX_TICKS * 4);
  p.readRaw(st);
  ok(!st.edges && !st.ok, "долгое молчание обязано оставаться негодным");

  // Живой датчик: возраст меньше кадра, фронты есть.
  s.poll_stale(0.3);
  p.readRaw(st);
  ok(st.edges, "на живом датчике признак фронтов обязан быть истинным");
}

// ============================================ 8. годность не тождественна
//
// Признак, который всегда истинен, бесполезен; признак, который всегда ложен,
// будет отключён на второй день. Проверяется ОБА края и переходы между ними.
// Крутить опрос ЗАДАННОЕ ВРЕМЯ, а не заданное число раз. Пороги годности
// теперь во времени, и тест обязан говорить на том же языке: счётом он молча
// превратился бы в проверку частоты опроса — ровно того, от чего уходили.
template <class F>
static void крутить(unsigned long us, F опрос) {
  const unsigned long до = host_now_us;
  while ((unsigned long)(host_now_us - до) < us) опрос();
}

static void test_health() {
  cur = "годность не тождественна";
  Sim s; Probe p(&s.t);

  ok(!p.isHealthy(), "до первого чтения датчик обязан считаться негодным");

  крутить(2 * CAPSENS_GOOD_US, [&]{ s.poll_stale(0.3); p.getSensorAngle(); });
  ok(p.isHealthy(), "на исправных данных годность обязана быть ИСТИННОЙ");
  ok(p.badStreak() == 0, "счётчик негодных обязан обнуляться исправным чтением");

  // Одиночный провал (попадание в мёртвый участок кадра) годность НЕ роняет:
  // при частом опросе такое случается сотни раз в секунду и на исправном
  // железе, а выключение контура от каждого — это ложная тревога.
  s.poll_fresh(0.5); p.getSensorAngle();
  ok(p.isHealthy(), "одиночное негодное чтение не должно ронять годность");
  s.poll_stale(0.5); p.getSensorAngle();

  // Молчащий датчик: годность обязана упасть — но не раньше порога.
  крутить(CAPSENS_BAD_US / 2, [&]{ s.poll_dead(CAPSENS_AGE_MAX_TICKS + 7); p.getSensorAngle(); });
  ok(p.isHealthy(), "до порога годность падать не должна: это ложная тревога");
  крутить(CAPSENS_BAD_US, [&]{ s.poll_dead(CAPSENS_AGE_MAX_TICKS + 7); p.getSensorAngle(); });
  ok(!p.isHealthy(), "после порога негодности годность обязана быть ЛОЖНОЙ");

  // Возврат требует времени, а не одного чтения: одиночное правдоподобное
  // чтение бывает и у мёртвого датчика (CNT 32-битный и раз в 25.3 с проходит
  // через ноль).
  s.poll_stale(0.5); p.getSensorAngle();
  ok(!p.isHealthy(), "одно годное чтение не должно возвращать годность");
  крутить(2 * CAPSENS_GOOD_US, [&]{ s.poll_stale(0.5); p.getSensorAngle(); });
  ok(p.isHealthy(), "после порога возврата годность обязана вернуться");

  // Порог во ВРЕМЕНИ обязан не зависеть от частоты опроса. Гоняем ту же
  // поломку вдесятеро реже: время до потери годности обязано совпасть.
  {
    Sim s2; Probe p2(&s2.t); s2.tick_us = 300;   // в десять раз реже
    крутить(2 * CAPSENS_GOOD_US, [&]{ s2.poll_stale(0.3); p2.getSensorAngle(); });
    ok(p2.isHealthy(), "на редком опросе годность обязана наступать так же");
    const unsigned long t0 = host_now_us;
    while (p2.isHealthy() && (unsigned long)(host_now_us - t0) < 20 * CAPSENS_BAD_US) {
      s2.poll_dead(CAPSENS_AGE_MAX_TICKS + 7); p2.getSensorAngle();
    }
    const unsigned long ушло = host_now_us - t0;
    ok(ушло < 2 * CAPSENS_BAD_US,
       "время до потери годности зависит от частоты опроса — порог не во времени");
  }

  // Удержание угла: на негодном чтении отдаётся ПОСЛЕДНИЙ ГОДНЫЙ, не ноль.
  s.poll_stale(0.25);
  float good = p.getSensorAngle();
  s.poll_dead(CAPSENS_AGE_MAX_TICKS + 7);
  float held = p.getSensorAngle();
  ok(fabs(held - good) < 1e-6f, "на негодном чтении обязан отдаваться последний годный угол");
}

// ============================================== 9. цена чтения (без ожидания)
//
// В контуре управления getSensorAngle() зовётся сотни-тысячи раз в секунду.
// Любой цикл ожидания «сейчас придёт хороший захват» останавливает контур с
// включёнными ключами. Проверяется не «быстро», а ФИКСИРОВАННОСТЬ: столько же
// обращений к регистрам на негодных данных, сколько на годных.
static void test_no_waiting() {
  cur = "цена чтения";
  Sim s; Probe p(&s.t);

  s.poll_stale(0.3);
  HostReg::reads = 0; HostReg::writes = 0;
  p.getSensorAngle();
  unsigned long r_good = HostReg::reads, w_good = HostReg::writes;
  ok(r_good == 4, "годное чтение обязано стоить ровно 4 чтения регистров (SR, CCR2, CCR1, CNT)");
  ok(w_good == 1, "годное чтение обязано стоить ровно 1 запись (сброс CC1OF)");

  s.poll_dead(CAPSENS_AGE_MAX_TICKS * 3);
  HostReg::reads = 0; HostReg::writes = 0;
  p.getSensorAngle();
  ok(HostReg::reads == r_good && HostReg::writes == w_good,
     "негодное чтение обязано стоить столько же — значит цикла ожидания нет");
}

// ======================================================= 10. настройка таймера
//
// Настроечные слова сверяются с captureBegin() из phone_link.ino побитно.
// Это не косметика: перепутанный CC2P ловил бы не тот фронт, снятый SMS
// оставил бы CNT свободно бегущим, и «возраст кадра» перестал бы быть
// возрастом кадра — а по числам это заметно не сразу.
static void test_timer_setup() {
  cur = "настройка таймера";
  Sim s; CaptureSensor c(&s.t);
  c.configureTimer();
  ok(s.t.CCMR1.get() == 0x2221u, "CCMR1: CC1S=01, CC2S=10, фильтры по 2");
  ok(s.t.CCER.get() == (TIM_CCER_CC1E | TIM_CCER_CC2E | TIM_CCER_CC2P),
     "CCER: оба канала включены, второй ловит СПАД");
  ok(s.t.SMCR.get() == ((5u << TIM_SMCR_TS_Pos) | (4u << TIM_SMCR_SMS_Pos)),
     "SMCR: TS=TI1FP1, SMS=reset — иначе CNT не возраст кадра");
  ok(s.t.PSC.get() == 0u, "PSC=0: тик TIM2 равен такту 170 МГц");
  ok(s.t.ARR.get() == 0xFFFFFFFFu, "ARR на максимум: TIM2 32-битный");
  ok((s.t.CR1.get() & TIM_CR1_CEN) != 0u, "таймер обязан быть запущен");
}

// ================================================= замирание таймера целиком
//
// БЛОКЕР ЗАМЫКАНИЯ, названный в reports/ЗАМКНУТЫЙ_КОНТУР.md пунктом 0. Если
// TIM2 останавливается весь (снято тактирование, сброс периферии, остановка
// отладчиком), регистры замирают ВМЕСТЕ со счётчиком. Возраст остаётся
// маленьким, все прежние проверки проходят, угол не меняется — и класс вечно
// докладывает исправность. Регулятор при этом видит стоящий вал при ненулевой
// уставке и упирает напряжение в потолок.
//
// Отличить это от законного случая «вал стоит, тракт жив» можно ТОЛЬКО по
// времени: ширина у неподвижного вала постоянна законно, период постоянен
// всегда, а счётчик на 170 МГц обязан меняться каждые 5.9 нс.
static void test_frozen_timer() {
  cur = "замирание таймера";
  Sim s; Probe p(&s.t);
  крутить(2 * CAPSENS_GOOD_US, [&]{ s.poll_stale(0.3); p.getSensorAngle(); });
  ok(p.isHealthy(), "предпосылка: на исправных данных датчик годен");

  // Вал СТОИТ, но тракт жив: регистры те же, счётчик идёт. Годность обязана
  // сохраниться — это рабочий режим стенда, и ложная тревога тут хуже дефекта.
  крутить(4 * CAPSENS_BAD_US, [&]{ s.poll_stale(0.3); p.getSensorAngle(); });
  ok(p.isHealthy(), "неподвижный вал при живом тракте объявлен неисправным");

  // Теперь замирает сам таймер: не меняется ничего, включая счётчик.
  const unsigned long t0 = host_now_us;
  while (p.isHealthy() && (unsigned long)(host_now_us - t0) < 20 * CAPSENS_BAD_US) {
    s.poll_frozen(); p.getSensorAngle();
  }
  ok(!p.isHealthy(), "замерший таймер класс считает исправным — это блокер");
  ok((unsigned long)(host_now_us - t0) < 2 * (CAPSENS_FROZEN_US + CAPSENS_BAD_US),
     "замирание распознано слишком поздно");
}

// ============================================ метка времени угла — по фронту
//
// Отсчёт защёлкнут железом в момент фронта, а опрашивается когда придётся.
// Если метку ставить по опросу, транспортная задержка гуляет от нуля до
// полутора кадров И ЗАВИСИТ ОТ САМОГО УГЛА (ширина импульса — это и есть
// угол), то есть вносит помеху раз на оборот прямо в измеряемую плавность.
static void test_angle_timestamp() {
  cur = "метка времени по фронту";
  Sim s; Probe p(&s.t);
  крутить(2 * CAPSENS_GOOD_US, [&]{ s.poll_stale(0.3); p.getSensorAngle(); });

  // Годное чтение: метка обязана быть СДВИНУТА НАЗАД на возраст отсчёта.
  s.poll_stale(0.6);
  p.update();
  const long ожидание = (long)host_now_us
                      - (long)(p.lastStatus().age / CAPSENS_TICKS_PER_US);
  ok(labs(p.angleTs() - ожидание) <= 1,
     "метка не поправлена на возраст отсчёта — стоит по моменту опроса");
  ok(p.lastStatus().age > 0, "предпосылка: возраст ненулевой, иначе тест пуст");

  // НЕГОДНОЕ чтение: поправку применять НЕЛЬЗЯ. Возраст у забракованного
  // отсчёта произволен, и на севшем датчике метка уехала бы назад на секунды —
  // getVelocity() попадает в ветку переполнения micros() и выдаёт околонулевую
  // скорость при ненулевой уставке. Занижение доходило до 5300 раз.
  const long до = p.angleTs();
  s.poll_dead(CAPSENS_AGE_MAX_TICKS + 7);
  p.update();
  ok(p.angleTs() >= до,
     "на негодном чтении метка уехала назад: поправка применена без гейта");
}

