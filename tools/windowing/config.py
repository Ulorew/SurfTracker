"""Все числовые параметры конвейера окон разметки/обучения в одном месте.

Ничего не хардкодить в других модулях — если нужна константа, она должна
появиться здесь. Цель: любое число можно посмотреть и поменять, не читая
логику, и один и тот же файл можно взять за спецификацию при переносе
арифметики (crop) на Kotlin.
"""

import cv2

# --- crop() -----------------------------------------------------------------

# Итоговый размер окна на выходе crop().
WINDOW_SIZE = 640

# Интерполяция ТОЛЬКО для уменьшения (сторона исходного квадрата > WINDOW_SIZE).
DOWNSCALE_INTERPOLATION = cv2.INTER_AREA

# Паддинга нет (тикет "пробные прогоны", правка 1, было по-другому в исходном
# тикете конвейера): если реальной области меньше WINDOW_SIZE, geometry.py
# расширяет область захвата вместо докрашивания серым — см. resolve_placement.

# --- sample_window() (позитивы, обучение) ------------------------------------

# Целевое распределение видимого размера цели (px) после вырезки в WINDOW_SIZE.
# (низ_корзины_px, верх_корзины_px, доля)
#
# Корзина 320-480 из первой версии тикета убрана (правка 2, "пробные
# прогоны"): при WINDOW_SIZE=640/K_MIN=2.5 она недостижима СТРУКТУРНО (ни
# ресайзом — не хватает k, ни натурой — K_MIN*base уже больше WINDOW_SIZE
# для base>256), а не потому что где-то отстаёт фильтр. Её 10% раздали
# поровну между соседними 120-200 и 200-320. Вернуть отдельным механизмом
# позже (снизить K_MIN или поднять WINDOW_SIZE).
#
# Нижняя граница по умолчанию — 30 ("база"). "Немедленные действия" п.4
# пробовали опустить до 12 без разбора качества — оказалось, что часть
# мелких боксов (<20px, MIN_TARGET_SIZE ниже) слишком шумная разметка, чтобы
# быть целью; тикет "подготовка ночи" вводит явный ignore-порог вместо
# слепого снижения. Нижнюю границу теперь можно переопределить флагом
# --size-bins-floor в dataset_gen.py (ночная серия использует 30 для "базы"
# и 20 для варианта "+боксы 20-30px" — см. MIN_TARGET_SIZE).
SIZE_BINS = [
    (30, 60, 0.15),
    (60, 120, 0.25),
    (120, 200, 0.35),
    (200, 320, 0.25),
]

# Боксы мельче этого порога (px, натуральный размер в кадре) — не цель и не
# фон, а зона неопределённости ("ignore"): не идут в позитивы, не участвуют
# в проверке "кадр пуст" для негативов (сами по себе блокируют то место под
# негатив, как обычный бокс), в оценке детекция на них не штрафуется как
# ложная. Разметку руками при этом не трогаем — фильтр чисто программный.
MIN_TARGET_SIZE = 20

# Допустимый диапазон k (S = k * размер_цели). Если для целевой корзины k
# выходит за диапазон — бокс эту корзину не закрывает (пропустить).
K_MIN = 2.5
K_MAX = 5.0

# Случайное смещение центра окна относительно центра бокса, доля от S.
CENTER_JITTER_FRAC = 0.15

# Сколько окон максимум снимать с одного бокса.
MAX_WINDOWS_PER_BOX = 4
# ...и увеличенный лимит для мелких боксов (испытывают нехватку корзин).
SMALL_BOX_MAX_WINDOWS = 8
SMALL_BOX_THRESHOLD_PX = 60  # сторона бокса меньше — считается мелким

# --- track_window() (боевой режим, пока только интерфейс) -------------------

TRACK_WINDOW_K = 3.5  # фиксированный k, без подбора по корзине

# --- негативы -----------------------------------------------------------------

# Расширение рамки (доля стороны) перед проверкой пересечения с окном-негативом.
NEGATIVE_BOX_EXPAND_FRAC = 0.15

# Целевое соотношение негативов к позитивам задаётся --neg-ratio в
# dataset_gen.py (по умолчанию 1.0) — там же, где оно реально считается.

# Сторона окна-негатива берётся из того же распределения SIZE_BINS, что и
# позитивы (чтобы фон был сопоставимого масштаба), но абсолютный размер S
# считается напрямую в px (нет привязки к размеру цели, т.к. цели нет).

# Линия горизонта: доля высоты кадра по умолчанию (камера на штативе — почти
# константа на видео); переопределяется per-video через horizon_overrides
# (video_name -> доля) в dataset_gen.
DEFAULT_HORIZON_Y_FRAC = 0.5

# Вероятность тянуть центр негатива к полосе горизонта, а не равномерно по кадру.
HORIZON_PREFERENCE_PROB = 0.7
# Полуширина полосы вокруг горизонта, в долях стороны окна S.
HORIZON_BAND_HALF_HEIGHT_FRAC_OF_S = 0.5

# Сколько раз пробовать случайный кандидат на негатив, прежде чем сдаться
# (кадр может быть слишком плотно занят рамками).
NEGATIVE_MAX_ATTEMPTS_PER_SAMPLE = 200

# --- аугментации (поверх готового окна) --------------------------------------

# Яркость: аддитивная доля от 255, диапазон.
BRIGHTNESS_DELTA_RANGE = (-0.20, 0.20)
# Контраст: множитель вокруг среднего.
CONTRAST_FACTOR_RANGE = (0.80, 1.20)
# Гамма-коррекция.
GAMMA_RANGE = (0.80, 1.20)
# Гауссов шум, std в шкале 0-255.
NOISE_STD_RANGE = (0.0, 8.0)
# Повторное JPEG-сжатие, качество.
JPEG_QUALITY_RANGE = (40, 90)
# Лёгкое размытие: ядро Гаусса (0 = без размытия), только нечётные >0 или 0.
BLUR_KERNEL_CHOICES = (0, 0, 0, 3)  # чаще без размытия, изредка k=3
# Отражение по горизонтали.
HFLIP_PROB = 0.5
# Баланс белого: независимый мягкий множитель на R/B каналы.
WHITE_BALANCE_GAIN_RANGE = (0.95, 1.05)
# Оттенок: сдвиг в градусах (0-360), несколько градусов, не сильно.
HUE_SHIFT_DEGREES_RANGE = (-3.0, 3.0)

# Явно НЕ делаем (см. тикет п.5): вертикальный флип, повороты > 5°, сильный
# сдвиг оттенка. Констант для них нет намеренно — это не "выключено", а
# "не реализовано".

# --- боевое разрешение обучения ----------------------------------------------

TRAIN_IMGSZ = 640  # боевой режим, не предразметка (там был 1280)

# --- eval_640 -----------------------------------------------------------------

# Корзины для полноты по размеру (тикет п.7, "как в v1") — своё разбиение,
# мельче, чем SIZE_BINS генератора (тот управляет составом трейна, этот —
# просто отчётность по размеру целей).
#
# Нижняя корзина 12-16 убрана (тикет "подготовка ночи", патч 1): всё, что
# мельче MIN_TARGET_SIZE=20, теперь ignore-зона — не цель для оценки вообще
# (не считается ни найденной, ни пропущенной), а не отдельная корзина с
# заведомо низкой полнотой. Нижняя корзина стала 20-32.
EVAL_SIZE_BINS_PX = [(20, 32), (32, 60), (60, 120), (120, float("inf"))]

# Порог "выровненных ложных" (патч 3): целевая частота ложных срабатываний
# на окно слежения, под которую подбирается порог уверенности; полнота при
# этом пороге — основная метрика сравнения прогонов.
EVAL_TARGET_FP_PER_WINDOW = 0.05

# IoU-порог, при котором предсказание считается совпавшим с истиной (как в v1).
EVAL_IOU_MATCH_THR = 0.3

# Порог "попадания по центру": |center_pred - center_true| / size_true.
EVAL_CENTER_HIT_THRESHOLD = 0.5

# Полоса вокруг горизонта, которая считается "берегом" (в долях высоты
# кадра) при разбивке ложных срабатываний по фону; выше — небо, ниже — вода.
EVAL_COAST_BAND_FRAC_OF_FRAME_H = 0.08

# Сколько независимых окон (разный джиттер) строить на один бокс при оценке
# в режиме слежения (патч 4, "подготовка ночи") — полнота усредняется по
# реализациям, конкретное случайное смещение перестаёт влиять на сравнение
# прогонов. Разброс между реализациями логируется отдельно как чувствительность.
EVAL_REALIZATIONS_PER_BOX = 8

# --- dataset_gen --------------------------------------------------------------

# Бокс, обрезанный краем окна, включается в разметку окна только если после
# обрезки его сторона (в пикселях итогового холста) не меньше этого порога
# по обеим осям — иначе это неразличимая полоска, а не цель.
MIN_VISIBLE_BOX_PX = 4

# Имя сплита по умолчанию, если --split-file не передан (списки будут позже).
DEFAULT_SPLIT_NAME = "train"

# На кадре без единого бокса (подтверждённый пустой кадр-негатив) 1:1 не от
# чего считать — берём это число негативов вместо нуля. Было 4, снижено до 2
# (тикет "пробные прогоны", правка 3) — с 4 общий баланс негативы:позитивы
# заметно перекашивался за счёт пустых кадров; --neg-ratio в dataset_gen.py
# умножает и это число тоже.
EMPTY_FRAME_NEGATIVE_COUNT = 2

