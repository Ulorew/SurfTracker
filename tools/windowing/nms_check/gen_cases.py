#!/usr/bin/env python3
"""Сырые тензоры для сличения Tracker.nms с независимым эталоном.

Случайные случаи дают массовость, именованные — те углы, где ошибка не
случайна: переполнение с вытеснением, равные уверенности (порядок при
равенстве решает, какая рамка выживет), вырожденные рамки нулевой площади,
полное совпадение боксов, ровно пороговые значения.

Числа записываются через repr, чтобы обе стороны читали ОДИН И ТОТ ЖЕ float.
"""
import random, os, struct

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, 'cases.txt')
MAX_DET = 16


def f32(x):
    """Округление до float32: Java читает float, питон считает double."""
    return struct.unpack('f', struct.pack('f', x))[0]


def emit(f, name, cols, max_det=MAX_DET):
    n = len(cols)
    f.write(f'CASE {name} {n} {max_det}\n')
    for row in range(5):
        f.write(' '.join(repr(f32(c[row])) for c in cols) + '\n')


def rnd_box(rng, conf=None):
    w = rng.uniform(2, 300); h = rng.uniform(2, 300)
    return [rng.uniform(0, 640), rng.uniform(0, 640), w, h,
            rng.uniform(0.0, 1.0) if conf is None else conf]


def main():
    rng = random.Random(20260818)
    with open(OUT, 'w') as f:
        # --- именованные углы ---
        emit(f, 'empty', [])
        emit(f, 'all_below', [[100, 100, 50, 50, 0.05] for _ in range(20)])
        # ровно на пороге: 0.08 проходит (условие «меньше — пропустить»),
        # чуть ниже — нет. Ошибка в знаке сравнения ловится только здесь.
        emit(f, 'at_thresh', [[100, 100, 50, 50, 0.08],
                              [300, 300, 50, 50, 0.0799999],
                              [500, 500, 50, 50, 0.0800001]])
        # одинаковые рамки: IoU = 1, выжить обязана ровно одна
        emit(f, 'identical', [[300, 300, 100, 100, 0.9] for _ in range(6)])
        # равные уверенности при разных рамках: решает порядок сортировки
        emit(f, 'conf_ties', [[50 * i, 300, 40, 40, 0.5] for i in range(12)])
        # вырожденные: нулевая ширина или высота -> площадь ноль, IoU 0/0
        emit(f, 'degenerate', [[100, 100, 0, 50, 0.9], [100, 100, 50, 0, 0.8],
                               [100, 100, 0, 0, 0.7], [100, 100, 50, 50, 0.6]])
        # IoU РОВНО 0.45 — граница строгая, и без этого случая подмена «>» на
        # «>=» проходила стенд молча. Квадраты 290 со сдвигом 110:
        # IoU = (w-d)/(w+d) = 180/400 = 0.45 в точности, без ошибки округления.
        emit(f, 'iou_exact', [[300, 300, 290, 290, 0.9], [410, 300, 290, 290, 0.8]])
        # IoU ровно около порога 0.45: два квадрата 100x100 со сдвигом
        for d, nm in ((31.0, 'iou_just_over'), (32.0, 'iou_just_under')):
            emit(f, nm, [[300, 300, 100, 100, 0.9], [300 + d, 300, 100, 100, 0.8]])
        # ПЕРЕПОЛНЕНИЕ буфера кандидатов (max*8 = 128): 400 надпороговых.
        # Сильнейшие стоят В КОНЦЕ — при обрыве прохода вместо вытеснения они
        # были бы потеряны, и стенд обязан это увидеть.
        cols = [[rng.uniform(0, 640), rng.uniform(0, 640), 30, 60,
                 0.10 + 0.0005 * i] for i in range(400)]
        emit(f, 'overflow_tail', cols)
        # то же, но сильнейшие в НАЧАЛЕ: вытеснение не должно их трогать
        emit(f, 'overflow_head', list(reversed(cols)))
        # больше max выживших: проверка обрезки по max
        emit(f, 'many_survivors',
             [[20 + 40 * i, 20 + 37 * (i % 13), 20, 20, 0.3 + 0.001 * i]
              for i in range(60)])
        # размер = наибольшая сторона: широкие и высокие вперемешку
        emit(f, 'wide_tall', [[100, 100, 200, 20, 0.9], [400, 400, 20, 200, 0.8],
                              [600, 100, 77, 77, 0.7]])
        # --- случайные ---
        for k in range(160):
            n = rng.choice([1, 2, 3, 5, 8, 20, 60, 150, 500, 8400])
            cols = [rnd_box(rng) for _ in range(n)]
            # в трети случаев сгустить рамки, чтобы IoU действительно срабатывал
            if k % 3 == 0:
                cx, cy = rng.uniform(100, 500), rng.uniform(100, 500)
                for c in cols:
                    c[0] = cx + rng.gauss(0, 25); c[1] = cy + rng.gauss(0, 25)
                    c[2] = rng.uniform(60, 120); c[3] = rng.uniform(60, 120)
            emit(f, f'rnd{k:03d}', cols)
    print(f'случаев записано -> {OUT}')


if __name__ == '__main__':
    main()
