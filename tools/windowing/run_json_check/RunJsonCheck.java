import com.surftracker.camfps.RunJson;

/**
 * Проверка разбора прогон.json и сводки для карточки прогона.
 *
 * Стенд нужен ровно потому, что разбор написан вручную по подстроке. Такой
 * разбор ошибается тихо: возвращает 0 вместо числа, находит не тот ключ,
 * обрезает значение — и на экране появляется правдоподобное число, которое
 * никто не перепроверит.
 *
 * Образец json здесь не выдуман: ключи и порядок повторяют то, что пишет
 * TrackActivity, включая ЛОВУШКУ — ключ «секунд» встречается в настройках
 * ДО итога, а фактическая длительность лежит в итоге под другим именем.
 * Пока имена совпадали, карточка показывала заказанную длительность вместо
 * случившейся, и выглядело это совершенно нормально.
 */
public class RunJsonCheck {

    static int failed = 0;

    static void eq(String what, Object got, Object want) {
        boolean ok = String.valueOf(got).equals(String.valueOf(want));
        if (!ok) failed++;
        System.out.println((ok ? "  ok   " : "  ПЛОХО ") + what
                + ": " + got + (ok ? "" : "   ожидалось " + want));
    }

    /** Как пишет TrackActivity: настройки, потом диагностика, потом итог. */
    static final String SAMPLE =
        "{\"tag\":\"260816_1422_потерь_нет\",\"модель\":\"person_w8a32.tflite\","
      + "\"сенсор\":\"3840x2160\",\"поле_зрения_град\":72.5000,"
      + "\"град_на_пиксель\":0.01888,\"K\":1.2000,\"знак\":-1,"
      + "\"окно\":1280,\"секунд\":180,\"выбег\":0.3000,"
      + "\"запись\":\"3840x2160@24\",\"потоков\":4,\"xnnpack\":true,"
      + "\"кадров\":412,\"с_целью\":361,\"без_цели\":51,\"доля_с_целью\":0.8762,"
      + "\"телеметрии\":1804,\"протухших_нулей\":0,"
      + "\"биты\":{\"watchdog\":0,\"потолок\":3,\"рампа\":11,\"энкодер\":412,"
      + "\"кламп\":0,\"срыв\":0},"
      + "\"rtt_ms\":{\"p50\":18.4000,\"p95\":41.2000},"
      + "\"итог\":{\"тактов\":412,\"доля_на_цели\":0.8762,\"потерь\":1,"
      + "\"повторных_захватов\":1,\"промахов_подряд_макс\":7,"
      + "\"окно_медиана\":1440.0000,\"инференс_мс_медиана\":83.0000,"
      + "\"такт_мс_медиана\":124.0000,\"длительность_с\":51.1000,"
      + "\"батарея_нагрев\":38.4000},\"ok\":true}";

    public static void main(String[] args) {
        System.out.println("== чтение значений ==");
        eq("тактов", RunJson.num(SAMPLE, "тактов"), 412.0);
        eq("доля на цели", RunJson.num(SAMPLE, "доля_на_цели"), 0.8762);
        eq("потерь", RunJson.num(SAMPLE, "потерь"), 1.0);
        eq("окно_медиана", RunJson.num(SAMPLE, "окно_медиана"), 1440.0);
        eq("модель", RunJson.str(SAMPLE, "модель"), "person_w8a32.tflite");
        // Метка прогона задаётся человеком и может содержать слово-ключ. Поиск
        // без кавычек нашёл бы «потерь» ВНУТРИ метки, до настоящего ключа, и
        // вернул бы ноль — то есть «потерь не было» на прогоне, где они были.
        eq("метка со словом-ключом", RunJson.str(SAMPLE, "tag"), "260816_1422_потерь_нет");
        eq("запись", RunJson.str(SAMPLE, "запись"), "3840x2160@24");
        eq("ok", RunJson.bool(SAMPLE, "ok"), true);

        System.out.println("== ловушки ==");
        // Заказанная длительность и фактическая — РАЗНЫЕ числа под разными
        // именами. Если кто-то вернёт итогу имя «секунд», этот пункт упадёт.
        eq("секунд (заказ)", RunJson.num(SAMPLE, "секунд"), 180.0);
        eq("длительность_с (факт)", RunJson.num(SAMPLE, "длительность_с"), 51.1);
        // «окно» не должно совпасть с «окно_медиана»
        eq("окно (настройка)", RunJson.num(SAMPLE, "окно"), 1280.0);
        // отрицательное значение
        eq("знак", RunJson.num(SAMPLE, "знак"), -1.0);
        // вложенный ключ достаётся
        eq("rtt p50", RunJson.num(SAMPLE, "p50"), 18.4);
        // несуществующий ключ — ноль и «нет ключа», а не выдумка
        eq("нет такого ключа", RunJson.num(SAMPLE, "выдуманный"), 0.0);
        eq("has(выдуманный)", RunJson.has(SAMPLE, "выдуманный"), false);
        eq("has(потерь)", RunJson.has(SAMPLE, "потерь"), true);

        System.out.println("== сводка карточки ==");
        String s = RunJson.summary(SAMPLE, true);
        System.out.println(indent(s));
        eq("доля показана", s.contains("на цели 88%"), true);
        eq("потери показаны", s.contains("потерь 1"), true);
        eq("возврат показан", s.contains("вернулась 1"), true);
        eq("длительность фактическая", s.contains("0:51"), true);
        eq("частота такта", s.contains("8.1 Гц"), true);
        eq("нет ложного 'без видео'", s.contains("без видео"), false);

        System.out.println("== прогон, который не состоялся ==");
        String bad = "{\"tag\":\"260816_1500\",\"секунд\":180,"
                   + "\"ok\":false,\"ошибка\":\"camera in use\"}";
        String bs = RunJson.summary(bad, false);
        System.out.println(indent(bs));
        eq("назван несостоявшимся", bs.startsWith("ПРОГОН НЕ СОСТОЯЛСЯ"), true);
        eq("причина показана", bs.contains("camera in use"), true);

        System.out.println("== мусор на входе ==");
        eq("null", RunJson.summary(null, false), "прогон.json не читается");
        eq("обрезанный json", RunJson.num("{\"тактов\":", "тактов"), 0.0);
        eq("пустой", RunJson.num("", "тактов"), 0.0);

        System.out.println();
        if (failed == 0) System.out.println("ИТОГ: разбор прогон.json исправен");
        else { System.out.println("ИТОГ: " + failed + " ПРОВЕРОК ПРОВАЛЕНО"); System.exit(1); }
    }

    static String indent(String s) {
        return "    " + s.replace("\n", "\n    ");
    }
}
