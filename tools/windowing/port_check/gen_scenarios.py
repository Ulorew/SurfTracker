#!/usr/bin/env python3
"""Сценарии для сличения телефонного переноса с офлайновым трекером.

Почему сценарии, а не только запись: в записи frozen_track.jsonl нет ни одной
ДОЛГОЙ потери с возвратом и ни одного такта с крупной целью у края кадра —
то есть ровно те места, где перенос и офлайн могут разойтись, записью не
покрыты вовсе. Проверка, которая гоняет только запись, объявит согласие, ни
разу не тронув механизм расширения окна и повторного захвата.

Координаты — ПИКСЕЛИ сенсора 3840x2160. Питоновская сторона переводит их в
свою систему вычитанием центра: логика масштабно-инвариантна (всё меряется
долями стороны окна), поэтому такой перевод точен, а не приблизителен.
"""
import json, math, os

W, H = 3840, 2160
DT = 1.0 / 12.0          # такт инференса, как на телефоне
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), 'scenarios.json')


def det(cx, cy, size):
    return [round(cx, 4), round(cy, 4), round(size, 4)]


def sc_straight():
    """Ровный проход поперёк кадра, одна цель. База: должно совпасть точно."""
    ticks = []
    for i in range(60):
        ticks.append([det(400 + i * 50, 1080 + 40 * math.sin(i / 6.0), 300)])
    return ticks


def sc_two_cross():
    """Две цели, встречное пересечение. Здесь решает выбор ближайшего."""
    ticks = []
    for i in range(60):
        a = det(600 + i * 45, 1100, 300)
        b = det(3200 - i * 45, 1060, 280)
        ticks.append([a, b] if i % 2 == 0 else [b, a])   # порядок скачет: перенос
    return ticks                                          # не должен зависеть от него


def sc_loss_return():
    """Шесть промахов подряд и возврат — сценарий, названный в тикете.

    Шесть больше MISS_TO_LOST=5, значит трек обязан пройти в LOST, расширить
    окно и принять цель обратно. Возврат ставится на 380 пикселей в стороне:
    внутри раздувшегося окна, но вне нераздутого.
    """
    ticks = [[det(1900, 1080, 300)] for _ in range(10)]
    ticks += [[] for _ in range(6)]
    ticks += [[det(2280, 1080, 300)] for _ in range(10)]
    return ticks


def sc_long_loss():
    """Двадцать промахов: расширение упирается в короткую сторону кадра."""
    ticks = [[det(1900, 1080, 300)] for _ in range(8)]
    ticks += [[] for _ in range(20)]
    ticks += [[det(1500, 900, 300)] for _ in range(6)]
    return ticks


def sc_big_target():
    """Крупная цель (filteredSize >= 411, тикет) у края кадра.

    Здесь окно упирается в потолок и в прижатие к кадру одновременно — место,
    где расходятся два режима прижатия центра.
    """
    ticks = []
    for i in range(40):
        s = 300 + i * 12                      # растёт: цель приближается
        x = 3400 - i * 10
        ticks.append([det(x, 300 + i * 5, s)])
    return ticks


def sc_edge():
    """Цель уходит в самый угол и возвращается: проверка прижатия убеждения."""
    ticks = []
    for i in range(30):
        ticks.append([det(max(60, 1900 - i * 130), max(60, 1080 - i * 70), 260)])
    for i in range(20):
        ticks.append([det(60 + i * 120, 60 + i * 60, 260)])
    return ticks


def sc_shrink():
    """Цель уходит вдаль: размер падает с 900 до 200.

    Добавлен не для полноты. Без него стенд не ловил подмену
    SIZE_FILTER_SHRINK_RATE (0.1 -> 0.5): ни в одном сценарии размер не
    убывал, а именно на убывании асимметричная EMA и отличается от обычной.
    Скорость спада решает, как быстро сжимается окно за уходящим сёрфером —
    ошибиться тут значит потерять цель на дальнем галсе.
    """
    ticks = []
    for i in range(35):
        s = max(200.0, 900.0 - i * 25.0)
        ticks.append([det(1900 + i * 20, 1080 - i * 8, s)])
    return ticks


def sc_loss_moving():
    """Потеря НА ХОДУ: цель идёт 150 px/такт и пропадает на шесть тактов.

    Добавлен потому, что без него не ловилась подмена EXTRAPOLATION_TAU_SEC:
    оба прежних сценария потери держали цель НЕПОДВИЖНОЙ перед пропаданием,
    поэтому скорость альфа-беты к моменту потери была нулевой, и затухание
    экстраполяции — механизм, ради которого её и заводили, — в сравнении не
    участвовало вовсе. Ровно там, где трекер и нужен: цель ушла за волну на
    ходу.

    Скорость выбрана так, чтобы предсказание за все пять тактов ведения в
    промахах НЕ упёрлось в край кадра НИ В ОДНОМ из режимов прижатия. Первая
    редакция гнала цель 600 px/такт, она улетала за кадр, и разницу съедало
    прижатие: подмена τ по-прежнему не ловилась, а сценарий выглядел годным.
    """
    ticks = []
    x = 800.0
    for _ in range(10):
        ticks.append([det(x, 1080, 300)]); x += 150
    ticks += [[] for _ in range(6)]
    for _ in range(6):
        ticks.append([det(x, 1080, 300)]); x += 150
    return ticks


def sc_gate_only_far():
    """Единственный кандидат на 0.36 стороны окна от предсказания.

    Добавлен потому, что подмена TARGET_SELECT_MAX_DIST_FRAC (0.30 -> 0.45) не
    ловилась ни одним сценарием: константа решает, ПРИМЕТЬ ли далёкого
    кандидата, а выбор идёт по БЛИЖАЙШЕМУ — пока рядом есть настоящая цель,
    порог ни на что не влияет. Первая редакция ставила соперника рядом с
    целью и потому тоже ничего не проверяла.

    Здесь цель ПРОПАДАЕТ, и остаётся только далёкий кандидат: при пороге 0.30
    он отвергается (промах, дальше потеря), при 0.45 — принимается и уводит
    трек. Это и есть «перепрыгнет ли камера на соседнего сёрфера».
    """
    ticks = [[det(1600, 1080, 300)] for _ in range(10)]
    # окно 3.5*300 = 1050; 0.30 -> 315 px, 0.45 -> 472 px. Ставим 378.
    ticks += [[det(1600 + 378, 1080, 300)] for _ in range(8)]
    ticks += [[det(1600, 1080, 300)] for _ in range(6)]
    return ticks


def sc_decoy_size():
    """Соперник НЕ ТОГО РАЗМЕРА и БЛИЖЕ цели — решает вето.

    Прежняя редакция была пустой, и это выяснилось проверкой стенда, а не
    чтением: соперник стоял на 120 px ЛЕВЕЕ цели, а цель шла ВПРАВО, поэтому
    ближе он не оказывался никогда. И питон, и телефон выбирали цель на всех
    28 тактах одинаково — и с механизмом А, и без него. Докстринг при этом
    уверенно сообщал «без механизма А выбор уходит на него».

    Теперь цель ОТСКАКИВАЕТ на 300 px, а мелкий соперник остаётся у самого
    предсказания:
      окно 3.5*600 = 2100, радиус приёма 0.30*2100 = 630 — оба внутри
      цель:     размер 600, расстояние 300
      соперник: размер 200, расстояние  20   -> без А выбирают ЕГО
      отношение 200/600 = 0.333 при пороге 1/1.8 = 0.556 -> с А вето
    """
    ticks = [[det(1600, 1080, 600)] for _ in range(8)]
    for _ in range(14):
        ticks.append([det(1900, 1080, 600), det(1620, 1080, 200)])
    ticks += [[det(1900, 1080, 600)] for _ in range(6)]
    return ticks


def sc_big_decoy():
    """Кандидат ВТРОЕ КРУПНЕЕ ведомого: верхняя половина вето.

    Заведён потому, что верхняя половина условия вето не исполнялась НИ РАЗУ:
    во всех прежних сценариях соперник был мельче цели, и на 1519 сравнениях
    максимальное отношение вышло 1.575 при пороге 1.8. Порча «выбросить
    верхнюю половину вето» проходила стенд молча.

      цель 400 -> окно max(3.5*400, 640) = 1400, радиус приёма 420
      чужой предмет 1400 на 100..240 px — внутри радиуса
      отношение 1400/400 = 3.5 > 1.8 -> с А вето, без А трек уезжает на него

    Это зеркало тактов 433 и 719 прогона 18 августа, где камера села на
    предмет впятеро мельче цели: здесь тот же промах в другую сторону.
    """
    ticks = [[det(1600, 1080, 400)] for _ in range(10)]
    for i in range(8):
        ticks.append([det(1700 + i * 20, 1080, 1400)])
    ticks += [[det(1600, 1080, 400)] for _ in range(6)]
    return ticks


def sc_small_target():
    """Мелкая цель, теряемая на ходу: ПОЛ ОКНА связывает.

    Заведён потому, что во всех десяти прогонах матрицы минимальная сторона
    окна была 840 px, то есть пол MIN_WINDOW_PX = 640 не связывал ни на одном
    из 422 тактов. Перестановка пола после расширения — задокументированная
    прошлая поломка — проходила стенд десять клеток из десяти.

    Здесь цель 120 px: 3.5*120 = 420 < 640, пол связывает на каждом такте
    ведения, а шесть промахов подряд заставляют расширение работать ИМЕННО
    от пола. В офлайновых прогонах по настоящему сёрфингу пол связывает 57%
    тактов — то есть это не искусственный угол, а рабочий режим дальнего
    галса.
    """
    ticks = []
    x = 800.0
    for _ in range(10):
        ticks.append([det(x, 1080, 120)]); x += 60
    ticks += [[] for _ in range(6)]
    for _ in range(8):
        ticks.append([det(x, 1080, 120)]); x += 60
    return ticks


def sc_decoy_lambda():
    """Соперник ВНУТРИ полосы вето, но с другим размером — решает штраф.

    Сценарий decoy_size проверяет только ВЕТО: там отношение 0.33 при пороге
    0.56, кандидат отсекается, не доходя до счёта, и подмена самого
    коэффициента SIZE_LAMBDA ничего не меняла — стенд честно сказал, что слеп
    к ней.

    Здесь отношение 0.667: вето молчит, решает величина штрафа.

    Числа считаны от РЕАЛЬНОЙ стороны окна. Первая редакция брала 3.5*900 =
    3150, но окно упирается в потолок min(кадр) = 2160, радиус приёма выходит
    648, и «цель» на 900 пикселей просто вылетала за приём — соперник
    оставался единственным кандидатом, и никакой штраф уже ничего не решал.

      окно 2160, радиус приёма 648, штраф |log(2/3)|*2160 = 876
      цель:     размер 900, расстояние 620 -> счёт 620
      соперник: размер 600, расстояние 100 -> счёт 100 + 0.5*876 = 538 (λ=0.5)
                                                    100 + 2*876 = 1852 (λ=2.0)
    То есть при λ=0.5 побеждает соперник, при λ=2.0 — цель.
    """
    ticks = [[det(1200, 1080, 900)] for _ in range(8)]
    for _ in range(12):
        ticks.append([det(1820, 1080, 900), det(1300, 1080, 600)])
    return ticks


def sc_decoy_lambda_low():
    """Порог по λ ниже боевого значения: проверка «есть ли штраф ВООБЩЕ».

    Сценарий decoy_lam ловит только РОСТ коэффициента: его порог лежит около
    λ = 0.594, а боевое значение 0.5, и при нём побеждает соперник — ровно
    как при λ = 0. Проверено сплошняком: питон с λ=0.5 и питон с λ=0.0 дают
    побайтово одинаковые прогоны по всем прежним сценариям и обоим режимам
    прижатия. То есть штраф можно было снести целиком, лишить множителя на
    сторону окна, лишить модуля и даже перевернуть ему знак — стенд печатал
    «перенос совпадает во ВСЕХ сочетаниях режимов».

    Здесь порог лежит МЕЖДУ нулём и боевым значением:
      окно 2160, штраф |log(2/3)|*2160 = 876
      цель:     размер 900, расстояние 400 -> счёт 400
      соперник: размер 600, расстояние 100 -> счёт 100 + λ*876
      перелом при λ = 300/876 = 0.342
    При λ=0 побеждает соперник, при боевом λ=0.5 — цель. Вместе с decoy_lam
    боевое значение зажато с двух сторон: 0.0 < 0.342 < 0.5 < 0.594 < 2.0.
    """
    ticks = [[det(1200, 1080, 900)] for _ in range(8)]
    for _ in range(12):
        ticks.append([det(1600, 1080, 900), det(1300, 1080, 600)])
    return ticks


def sc_gate_small_cand():
    """Единственный кандидат ВДВОЕ мельче цели, близко: решает, откуда взят допуск.

    Заведён потому, что правку «допуск от предсказанного размера» ловил лишь
    decoy_size и лишь в половине клеток матрицы. Здесь механизм А не мешает:
    отношение 0.6 лежит внутри полосы вето [0.56, 1.8], то есть кандидат
    доходит до гейта во всех режимах.

      цель 600 -> окно 2100, радиус приёма 630, допуск гейта ~1.0 размера
      кандидат 360 на расстоянии 480:
        допуск от ПРЕДСКАЗАННОГО размера (600) -> ~600, принимается
        допуск от размера КАНДИДАТА    (360) -> ~330, отвергается
    То есть ровно та поблажка наоборот: мелкой рамке доставался узкий допуск,
    крупной — широкий.
    """
    ticks = [[det(1920, 1080, 600)] for _ in range(12)]
    ticks += [[det(1920 + 480, 1080, 360)] for _ in range(10)]
    ticks += [[det(1920, 1080, 600)] for _ in range(6)]
    return ticks


def sc_gate_capped():
    """Окно упирается в потолок кадра: гейт становится ШИРЕ радиуса.

    Это и есть случай, ради которого заведено «гейт может только сужать».
    Пока окно не упирается в потолок, радиус приёма (1.05 размера) шире
    сошедшегося гейта (~1.0), и сужать нечего — правка невидима. Прежние
    сценарии ловили её только в режиме прижатия true и только на краю кадра.

      цель 900 -> окно 3.5*900 = 3150, потолок min(кадр) = 2160
      радиус приёма 0.30*2160 = 648, допуск гейта ~900
      кандидат того же размера на 750: внутри гейта, ЗА радиусом
    Размер тот же, поэтому механизм А на решение не влияет.
    """
    ticks = [[det(1920, 1080, 900)] for _ in range(12)]
    ticks += [[det(1920 + 750, 1080, 900)] for _ in range(10)]
    return ticks


def sc_gate_early():
    """Далёкий кандидат на ПЕРВЫХ тактах после затравки: проверка прогрева.

    Заведён потому, что порча прогрева не менялa ничего даже при снятом
    правиле «только сужать» — и это выглядело как доказательство, что ветка
    мертва. Ветка не мертва, просто ни один сценарий не подставлял кандидата
    в те такты, когда ковариация ещё не сошлась.

      цель 900 в центре -> окно 3150, потолок 2160, радиус приёма 648
      со второго такта цель пропадает, остаётся кандидат на 900 пикселей:
        радиус (то есть режим прогрева) — отвергает
        сырая ковариация первых тактов (допуск ~21.8 размера) — принимает
    Фильтр при этом не обновляется, значит прогрев не кончается никогда, и
    расхождение держится весь сценарий.
    """
    ticks = [[det(1920, 1080, 900)] for _ in range(2)]
    ticks += [[det(1920 + 900, 1080, 900)] for _ in range(8)]
    return ticks


def sc_empty_start():
    """Пусто на старте, потом цель. Затравка обязана открыться одинаково."""
    return [[] for _ in range(3)] + [[det(1000, 800, 240)] for _ in range(20)]


SCENARIOS = {
    'straight':    sc_straight(),
    'two_cross':   sc_two_cross(),
    'loss_return': sc_loss_return(),
    'long_loss':   sc_long_loss(),
    'big_target':  sc_big_target(),
    'edge':        sc_edge(),
    'shrink':      sc_shrink(),
    'loss_moving': sc_loss_moving(),
    'gate_far':    sc_gate_only_far(),
    'decoy_size':  sc_decoy_size(),
    'decoy_lam':   sc_decoy_lambda(),
    'decoy_lam0':  sc_decoy_lambda_low(),
    'big_decoy':   sc_big_decoy(),
    'small_targ':  sc_small_target(),
    'gate_small':  sc_gate_small_cand(),
    'gate_capped': sc_gate_capped(),
    'gate_early':  sc_gate_early(),
    'empty_start': sc_empty_start(),
}

TXT = os.path.join(os.path.dirname(os.path.abspath(__file__)), 'scenarios.txt')


def write_txt(path):
    """Плоский формат: обе стороны читают ОДИН файл.

    JSON тут был бы обузой — на телефонной стороне нет разбора JSON, и писать
    его пришлось бы вручную, то есть завести второй источник расхождения в
    самой проверке.
    """
    with open(path, 'w') as f:
        f.write(f'FRAME {W} {H} {DT!r} 640\n')
        for name, ticks in SCENARIOS.items():
            f.write(f'SCENARIO {name} {len(ticks)}\n')
            for t in ticks:
                parts = [str(len(t))]
                for d in t:
                    parts += [repr(d[0]), repr(d[1]), repr(d[2])]
                f.write(' '.join(parts) + '\n')


if __name__ == '__main__':
    write_txt(TXT)
    n = sum(len(v) for v in SCENARIOS.values())
    print(f'сценариев {len(SCENARIOS)}, тактов всего {n} -> {TXT}')
