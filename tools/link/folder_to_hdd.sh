#!/bin/bash
# Схлопнуть каталог в симлинк на HDD: перенести содержимое целиком и оставить
# на месте ссылку.
#
#   folder_to_hdd.sh --проба <каталог> [...]
#   folder_to_hdd.sh <каталог> [...]
#
# ЗАЧЕМ ОТДЕЛЬНО ОТ video_to_hdd.sh. Тот переносит ФАЙЛЫ и оставляет симлинк
# на каждый — 71 ссылка вместо 71 файла. Это защищает метрики рядом с видео,
# но даёт две неприятности: листинги забиты ссылками, и НОВЫЕ файлы в тех же
# каталогах снова оседают на системном диске, пока перенос не запустят заново.
#
# Здесь наоборот: одна ссылка на каталог, и всё, что в него положат потом,
# автоматически оказывается на HDD. Годится для АРХИВА — каталогов, которые
# читают редко и целиком (old/, старые прогоны). Для рабочих каталогов, где
# рядом с тяжёлым лежит часто читаемое, по-прежнему верен пофайловый перенос.
#
# УЖЕ ПЕРЕНЕСЁННОЕ ВИДЕО ПОДХВАТЫВАЕТСЯ. Внутри могут быть симлинки от
# video_to_hdd.sh — они разыменовываются, файл встаёт на своё место в новой
# структуре, а ссылка-на-ссылку не создаётся.
set -eu

DEST="${ARCHIVE_HDD:-/mnt/sda3/Projects/SurfTracker/media_lm}"
ROOT="$(cd "$(dirname "$0")/../.." && pwd)"

DRY=0
if [ "${1:-}" = "--проба" ]; then DRY=1; shift; fi
[ $# -gt 0 ] || { echo "укажите каталоги"; exit 1; }

cd "$ROOT"
for target in "$@"; do
    rel="${target#./}"; rel="${rel%/}"
    if [ -L "$rel" ]; then echo "  уже симлинк: $rel"; continue; fi
    [ -d "$rel" ] || { echo "  нет каталога: $rel"; continue; }

    size=$(du -sLh "$rel" 2>/dev/null | cut -f1)
    files=$(find "$rel" -type f -o -type l 2>/dev/null | wc -l)
    dst="$DEST/$rel"
    if [ "$DRY" = "1" ]; then
        echo "  $rel  ($size, $files файлов)  ->  $dst"
        continue
    fi

    echo "== $rel ($size, $files файлов)"
    mkdir -p "$(dirname "$dst")"
    # rsync, а не cp: часть содержимого могла уехать на HDD раньше пофайловым
    # переносом, и копировать её второй раз значило бы гонять гигабайты внутри
    # медленного диска. --ignore-existing докладывает только недостающее.
    #
    # -L разыменовывает симлинки: видео, уже лежащее на HDD, встаёт на место
    # файлом, а ссылка-на-ссылку не создаётся.
    if ! rsync -aL --ignore-existing "$rel/" "$dst/" 2>/dev/null; then
        echo "  ОТКАЗ копирования, оригинал НЕ тронут"; continue
    fi

    # СВЕРКА ЧИСЛА ФАЙЛОВ И БАЙТ до удаления. NTFS через fuseblk обрывает
    # запись на переполнении молча; удалять оригинал по факту «команда не
    # упала» значило бы терять архив.
    was_b=$(du -sLb "$rel" 2>/dev/null | cut -f1)
    now_b=$(du -sb "$dst" 2>/dev/null | cut -f1)
    was_f=$(find "$rel" -type f -o -type l 2>/dev/null | wc -l)
    now_f=$(find "$dst" -type f 2>/dev/null | wc -l)
    if [ "$now_f" -lt "$was_f" ] || [ "$now_b" -lt "$((was_b * 95 / 100))" ]; then
        echo "  ОТКАЗ СВЕРКИ, оригинал НЕ тронут:"
        echo "    файлов было $was_f, стало $now_f; байт было $was_b, стало $now_b"
        continue
    fi

    rm -rf "$rel"
    ln -s "$dst" "$rel"
    echo "  готово: $rel -> $dst"
done

if [ "$DRY" = "1" ]; then echo; echo "назначение: $DEST"; fi
