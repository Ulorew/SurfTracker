def из_java(файл, шаблон, имя):
    путь = os.path.join(SRC, файл)
    m = re.search(шаблон, open(путь, encoding="utf-8").read())
    if not m:
        sys.exit(f"ОТКАЗ: в {файл} не найдено значение «{имя}». Снимок, "
                 f"подставляющий умолчание вместо настоящего значения, хуже "
                 f"отсутствия снимка.")
    return m.group(1)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", required=True)
    ap.add_argument("--версия", required=True)
    args = ap.parse_args()

    # Две формы объявления, и обе надо знать: it(...) со ЗНАЧКОМ ТИПА между
    # ключом и подписью, ch(...) без него (тип подразумевается CHOICE).
    ФОРМЫ = [r'"{k}"\s*,\s*[A-Z]+\s*,\s*"[^"]*"\s*,\s*"([^"]*)"',
             r'"{k}"\s*,\s*"[^"]*"\s*,\s*"([^"]*)"']
    умолчания = {}
    for ключ in ПРИЧИНЫ:
        зн = None
        for ф in ФОРМЫ:
            m = re.search(ф.format(k=ключ),
                          open(os.path.join(SRC, "RunSettings.java"),
                               encoding="utf-8").read())
            if m:
                зн = m.group(1); break
        if зн is None:
            sys.exit(f"ОТКАЗ: в RunSettings.java не найдено умолчание «{ключ}». "
                     f"Снимок, подставляющий умолчание вместо настоящего "
                     f"значения, хуже отсутствия снимка.")
        умолчания[ключ] = {"значение": зн, "причина": ПРИЧИНЫ[ключ]}

    константы = {}
    for имя in КОНСТАНТЫ:
        зн = из_java("TrackActivity.java",
                     r"static final float " + имя + r"\s*=\s*([0-9.]+)f", имя)
        константы[имя] = {"значение": float(зн), "причина": КОНСТАНТЫ[имя]}

    def git(*a):
        return subprocess.run(["git", "-C", ROOT, *a],
                              capture_output=True, text=True).stdout.strip()

    снимок = {
        "версия": args.версия,
        "коммит": git("rev-parse", "HEAD"),
        "ветка": git("rev-parse", "--abbrev-ref", "HEAD"),
        "дерево_чистое": git("status", "--porcelain") == "",
        "аппарат": "Redmi Note 14 Pro 5G (24090RA29G), камера 0 s5khp3, "
                   "активная матрица 4080x3060",
        "умолчания": умолчания,
        "константы": константы,
        "измерено": ИЗМЕРЕНО,
        "не_проверено": [
            "аспект 16:9 на железе",
            "механизм переменного зума (четвёрка из СОСТОЯНИЕ.md 3.6)",
            "смаз при панораме (тест на движении)",
            "поведение при тусклом свете",
        ],
    }
    with open(args.out, "w", encoding="utf-8") as f:
        json.dump(снимок, f, ensure_ascii=False, indent=1)
        f.write("\n")
    print(f"снимок записан: {args.out}")
    print(f"  дерево чистое: {снимок['дерево_чистое']}, коммит {снимок['коммит'][:12]}")
    for k, v in умолчания.items():
        print(f"  {k} = {v['значение']}")
    for k, v in константы.items():
        print(f"  {k} = {v['значение']}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
