#!/usr/bin/env python3
"""Метрики обоих трактов энкодера по сырому DIAG-логу.

ДВА ТРАКТА, ДВЕ ШКАЛЫ. Боевой тракт (micros в обработчике прерывания) уже
откалиброван: SENS_MIN/MAX подобраны на этом железе. Тракт захвата даёт
скважность, и во что она переводится — вопрос, а не данность.

ПОЭТОМУ МОСТ МЕЖДУ ШКАЛАМИ МЕРЯЕТСЯ ЯВНО. Наклон и смещение берутся
подгонкой по данным вращения, а не подставляются из даташита. Проверка «а
похоже на правду» такой мост не проверяет: она одинаково довольна и верным
переводом, и сдвинутым на постоянную.

И МОСТ ОБЯЗАН БЫТЬ ПРИНЯТ ИЛИ ОТВЕРГНУТ, А НЕ ПРОСТО НАПЕЧАТАН. Сверка
«наклон x размах = 360°» раньше печаталась рядом с подогнанным наклоном и ни
на что не влияла: на замершем боевом тракте наклон выходил 0.000, расхождение
-360°, и этот ноль молча уезжал дальше как рабочий перевод. Теперь сверка —
гейт: не сошлось, значит моста нет, и дальше идёт ЯВНО ПОМЕЧЕННОЕ допущение.

ТРЕТЬЯ ШКАЛА — ВРЕМЯ, и она тоже двойная. t_host — время ПРИЁМА пакета на
ноутбуке, общее на всю пачку и с джиттером доставки Bluetooth. На плате есть
свои часы (t_us + cap_age), и ход снимается по ним; мост между часами меряется
и печатается ровно так же явно, как мост между шкалами угла.

МЕТРИКИ РАЗНЫЕ ДЛЯ РАЗНЫХ ТРАКТОВ. «Минимальный интервал между уровнями»
осмыслен только там, где уровней мало: у захвата их почти столько же, сколько
проб, и интервал вырождается в ноль. Он оставлен как ПРИЗНАК КВАНТОВАНИЯ, а
сравниваются тракты по СКО и робастной оценке.
"""
import argparse, csv, math, sys
from collections import defaultdict

SENS_MIN_US, SENS_MAX_US = 3.0, 919.0
CPR_ISR = SENS_MAX_US - SENS_MIN_US + 1.0       # 917, как в MagneticSensorPWM
QUANT_ISR = 360.0 / CPR_ISR                     # 0.39258 град на тик micros()
TIM2_HZ = 170e6
MICROS_WRAP_S = 2 ** 32 / 1e6                   # micros() 32-бит: 4294.97 с

# Ниже трёх квантов боевого тракта его колонка вырождается: уровней один-два,
# и любое «разрешение», посчитанное по такой выборке, — не измерение, а
# деление шума на ноль (docs/journal/энкодер_журнал/ВАЛИДАЦИЯ_ПРОШИВКИ.md:114).
MIN_SPAN_QUANTS = 3
MIN_SPAN_DEG = MIN_SPAN_QUANTS * QUANT_ISR      # 1.1777 град

BRIDGE_TOL_DEG = 5.0        # допуск сверки «наклон x размах = 360°»
BRIDGE_SPREAD_FRAC = 0.01   # разброс наклона по участкам: 1% => ещё прямая
CLOCK_TOL = 0.01            # допуск на ход часов ноутбука к часам платы

# ---- ПРИЗНАКИ В БАЙТЕ flags -----------------------------------------------
#
# Биты РАЗДЕЛЕНЫ НА ДВА СПИСКА, потому что они разного рода. Пока все четыре
# лежали в одном словаре с заголовком «признаки негодности», бит 2 читался как
# авария — а он стоял в 98.4-98.6% пакетов во всех прогонах 21.08 и означал
# ровно противоположное: что датчик исправно сыпал кадрами.
#
# ПОЧЕМУ ТАК ВЫХОДИТ. Бит 2 — аппаратный CC1OF таймера захвата: он взводится,
# когда нарастающий фронт пришёл раньше, чем прошивка прочитала предыдущий.
# Кадр датчика 921 мкс (1086 Гц), DIAG опрашивается на 50 Гц — между чтениями
# проходит около двадцати кадров, и переполнение НЕИЗБЕЖНО. Тревожен здесь
# СНЯТЫЙ бит, а не поставленный.
# ЗНАЧЕНИЯ БИТОВ БЕРУТСЯ ИЗ ПРОТОКОЛА, а не выписываются числами. Здесь
# стояли литералы 1/2/8/16, то есть третья копия того же правила: прошивка,
# протокол и разборщик. Правят обычно не ту копию.
from proto_v2 import (DF_CAP_BAD, DF_ISR_BAD, DF_CAP_SKIP, DF_NO_EDGES,
                      DF_CAP_STALL, DF_CAP_PREV, DF_BAD_MASK)

BAD_FLAGS = {
    DF_CAP_BAD:   ("cap_bad", "захват не дал годного кадра"),
    DF_ISR_BAD:   ("isr_bad", "импульс вне границ датчика"),
    DF_NO_EDGES:  ("no_edges", "ISR-тракт: фронтов не было"),
    DF_CAP_STALL: ("cap_stall", "ПОТОК КАДРОВ ЗАХВАТА ВСТАЛ — датчик молчит"),
}
# Описательные: говорят о ТЕМПЕ и о поправке, а не о беде. Ни один отсчёт по
# ним не отбрасывается.
INFO_FLAGS = {
    DF_CAP_SKIP: ("cap_skip", "кадры между опросами пропускались (на 50 Гц это норма)"),
    DF_CAP_PREV: ("cap_prev", "импульс из предыдущего кадра, возраст уже поправлен"),
}
# В логах, снятых прошивкой ДО 21.08, битов 16 и 32 нет вовсе: они там всегда
# нули, и разбор таких логов не меняется.
DF = {b: n for b, (n, _) in list(BAD_FLAGS.items()) + list(INFO_FLAGS.items())}
BAD_MASK = DF_BAD_MASK


def frames_per_poll(rows):
    """Сколько кадров датчика укладывается между двумя опросами.

    ЗАЧЕМ. Это единственный способ сказать, НЕСЁТ ЛИ бит cap_skip информацию.
    Если между чтениями проходит меньше двух кадров, переполнения захвата и не
    должно быть, и снятый бит ни о чём не говорит; если больше двух — бит
    обязан стоять, и снятый означает, что кадры перестали идти.

    Обе величины ИЗМЕРЕНЫ в логе: шаг опроса по часам платы (t_us), период
    кадра по самому захвату. Ни одна не взята из даташита.
    """
    if len(rows) < 3 or "t_us" not in rows[0] or "cap_period" not in rows[0]:
        return float("nan")
    dts = [(float(b["t_us"]) - float(a["t_us"])) % 2 ** 32
           for a, b in zip(rows, rows[1:])]
    dts = [d for d in dts if 0.0 < d < 1e6]
    ps = [float(r["cap_period"]) for r in rows if float(r["cap_period"]) > 0]
    if not dts or not ps:
        return float("nan")
    dt_us = sorted(dts)[len(dts) // 2]
    p = sorted(ps)[len(ps) // 2]
    return dt_us * 1e-6 * TIM2_HZ / p


def isr_deg(row):
    """Формула боевого тракта — ровно та, что применяет MagneticSensorPWM."""
    return (float(row["isr_high"]) - SENS_MIN_US) / CPR_ISR * 360.0


def cap_frac(row):
    """Сырая скважность захвата, 0..1. Ни во что не переведена намеренно."""
    p = float(row["cap_period"])
    return float(row["cap_high"]) / p if p > 0 else float("nan")


def unwrap(xs, period=360.0):
    out, off = [], 0.0
    for i, x in enumerate(xs):
        if i:
            d = x + off - out[-1]
            if d > period / 2:
                off -= period
            elif d < -period / 2:
                off += period
        out.append(x + off)
    return out


def has_board_clock(rows):
    return bool(rows) and "t_us" in rows[0] and "cap_age" in rows[0]


def board_ts(rows):
    """Момент ОТСЧЁТА по часам ПЛАТЫ, секунды.

    ЗАЧЕМ ОТДЕЛЬНЫЕ ЧАСЫ. t_host ставится в момент, когда пакет вынут из
    сокета на ноутбуке: он один на всю пачку, и в нём сидит джиттер доставки
    Bluetooth (замерено: СКО 2.7 мс, размах 30 мс). Снятие хода по такому
    времени умножает джиттер на скорость вала и укладывает результат в
    остаток — на 17 град/с 30 мс превращаются в полградуса мнимого «шума
    тракта», на порядок больше настоящего.

    ПОЧЕМУ МИНУС cap_age. t_us — это micros() в момент СБОРКИ пакета, а
    захват произошёл раньше, cap_age тиков TIM2 назад. Без этой поправки
    остаётся дрожание в целый кадр датчика (921 мкс). Само поле cap_age до
    сих пор не читал никто: довезённая до ноутбука величина не использовалась
    ни разу — ровно та семья ошибок, которую этот проект и ловит.

    micros() 32-битный и заворачивается каждые 71.6 мин, поэтому шкала
    разворачивается по своему периоду, а не считается монотонной.
    """
    if not has_board_clock(rows):
        return None
    tus = unwrap([float(r["t_us"]) / 1e6 for r in rows], period=MICROS_WRAP_S)
    return [t - float(r["cap_age"]) / TIM2_HZ for t, r in zip(tus, rows)]


def sample_ts(rows, clock="board"):
    """Время отсчётов выбранной шкалой; host — запасной путь для старых CSV."""
    if clock == "board":
        tb = board_ts(rows)
        if tb is not None:
            return tb
    return [float(r["t_host"]) for r in rows]


def mad_sd(xs):
    """Робастная оценка СКО: MAD * 1.4826.

    ВЫРОЖДАЕТСЯ НА КВАНТОВАННЫХ ДАННЫХ и возвращает тогда nan, а не ноль.
    Если больше половины проб попали в один уровень — а на тихом стенде у
    micros-тракта это норма, — медиана отклонений равна нулю. Ноль здесь
    означает «мера неприменима», но выглядит как «шума нет», и дальше из него
    получается выигрыш «0.0x». Такое число обязано быть отмечено, а не
    напечатано наравне с измеренными.
    """
    if not xs:
        return float("nan")
    m = sorted(xs)[len(xs) // 2]
    d = sorted(abs(x - m) for x in xs)
    v = d[len(d) // 2] * 1.4826
    return v if v > 0 else float("nan")


def sd(xs):
    n = len(xs)
    if n < 2:
        return float("nan")
    mu = sum(xs) / n
    return math.sqrt(sum((x - mu) ** 2 for x in xs) / (n - 1))


def span_of(xs):
    return (max(xs) - min(xs)) if xs else float("nan")


def min_level_gap(xs, eps=1e-9):
    """Типичный интервал между соседними РАЗЛИЧНЫМИ уровнями.

    Медиана разностей, а не минимум: минимум ловит одну случайную близкую
    пару и занижает шаг. Для неквантованного тракта величина смысла не имеет
    — она тут именно чтобы квантованность было видно.
    """
    u = sorted(set(round(x, 9) for x in xs))
    if len(u) < 2:
        return float("nan")
    gaps = sorted(b - a for a, b in zip(u, u[1:]) if b - a > eps)
    return gaps[len(gaps) // 2] if gaps else float("nan")


def detrend(xs, ts):
    """Убрать линейный ход. Остаток — то, что не объясняется вращением.

    На вращении СКО меряет сам ход вала (сотни градусов) и о тракте не
    говорит ничего. После снятия прямой в остатке остаются шум тракта И
    настоящие неровности хода — зубцовый момент, неравномерность разгона.
    Вторые ОБЩИЕ для обоих трактов, поэтому по остатку тракты сравнивать
    можно, а называть остаток шумом датчика — нельзя.

    ts обязано быть часами ПЛАТЫ (см. board_ts): ошибка шкалы времени входит
    в остаток умноженной на скорость вала и притворяется шумом тракта.
    """
    n = len(xs)
    if n < 3:
        return xs
    mt = sum(ts) / n
    mx = sum(xs) / n
    stt = sum((t - mt) ** 2 for t in ts)
    if stt < 1e-12:
        return [x - mx for x in xs]
    k = sum((t - mt) * (x - mx) for t, x in zip(ts, xs)) / stt
    return [x - (mx + k * (t - mt)) for x, t in zip(xs, ts)]


def _lsq(frac, deg):
    n = len(frac)
    mx, my = sum(frac) / n, sum(deg) / n
    sxx = sum((x - mx) ** 2 for x in frac)
    if sxx < 1e-12:
        return None
    k = sum((x - mx) * (y - my) for x, y in zip(frac, deg)) / sxx
    b = my - k * mx
    return k, b, sd([y - (k * x + b) for x, y in zip(frac, deg)])


def split_runs(frac, deg, jump=0.5, minlen=50):
    """Разбить ход на участки БЕЗ ПЕРЕХОДА через шов кадра датчика.

    ЗАЧЕМ ЭТО НУЖНО. Скважность пробегает не всю единицу: часть кадра
    служебная. На переходе она падает с верхней границы диапазона сразу на
    нижнюю, и развёртка фазы этот мёртвый участок ПРОГЛАТЫВАЕТ — добавляет
    ровно 1.0 вместо настоящего размаха. Наклон, посчитанный сквозь переход,
    схлопывается к наивным 360 независимо от того, каков он на самом деле.

    Поймано подложкой: заложенные 371.5 восстанавливались как 359.5.

    РЕЗ ИДЁТ ПО ОБЕИМ ШКАЛАМ, а не только по скважности. Порог 0.5 по
    скважности — это 0.5*k градусов; при k=371.5 получается 185.8°, то есть
    скачок в 180..186° рез по скважности пропускает, а unwrap внутри участка
    его свернёт как переход через 360 — ровно та беда, ради которой функция
    и написана. Поэтому deg, который раньше принимался и не читался, теперь
    режет по своему порогу в 180°.
    """
    runs, cur = [], [0]
    for i in range(1, len(frac)):
        if abs(frac[i] - frac[i - 1]) > jump or abs(deg[i] - deg[i - 1]) > 180.0:
            runs.append(cur); cur = []
        cur.append(i)
    runs.append(cur)
    return [r for r in runs if len(r) >= minlen]


def fit_bridge(frac, deg, minlen=50):
    """СЫРЫЕ frac и deg -> (fit, info).

    fit = (наклон, смещение, остаток, участков, разброс) либо None.
    info — сколько участков и проб дошло до подгонки: без этого числа доля
    отброшенных данных остаётся невидимой, а наклон по одной десятой лога
    выглядит так же солидно, как по всему логу.

    Величины подаются НЕРАЗВЁРНУТЫМИ намеренно: разбиение ищет швы кадра
    именно по скачкам, а на развёрнутых данных швов уже нет — первая
    редакция получала один сплошной участок и тот же схлопнутый наклон.

    Наклон берётся МЕДИАНОЙ по участкам, а рядом печатается их разброс:
    если участки дают разные наклоны, мост не описывается прямой, и
    единственное число об этом бы умолчало.
    """
    runs = split_runs(frac, deg, minlen=minlen)
    info = dict(n_total=len(frac), n_runs=len(runs),
                n_in_runs=sum(len(r) for r in runs),
                n_flat=0, n_degen=0, n_fit_pts=0)
    fits = []
    for r in runs:
        # Внутри участка шва нет, но угол боевого тракта всё равно может
        # перевалить через 360 — его разворачиваем локально.
        d = unwrap([deg[i] for i in r])
        # УЧАСТОК БЕЗ ХОДА БОЕВОГО ТРАКТА В ПОДГОНКУ НЕ БЕРЁТСЯ. На мёртвом
        # тракте (isr_high застыл) подгонка формально удаётся: наклон 0,
        # остаток 0.0000° — и печатается как «тракты сошлись идеально».
        # Размах меньше трёх квантов означает, что боевой тракт по этому
        # участку не сказал ничего, и сравнивать с ним нечего.
        if span_of(d) < MIN_SPAN_DEG:
            info["n_flat"] += 1
            continue
        f = _lsq([frac[i] for i in r], d)
        if not f:
            info["n_degen"] += 1
            continue
        fits.append(f)
        info["n_fit_pts"] += len(r)
    if not fits:
        return None, info
    ks = sorted(f[0] for f in fits)
    k = ks[len(ks) // 2]
    bs = sorted(f[1] for f in fits)
    b = bs[len(bs) // 2]
    resid = sorted(f[2] for f in fits)[len(fits) // 2]
    spread = (ks[-1] - ks[0]) if len(ks) > 1 else 0.0
    return (k, b, resid, len(fits), spread), info


def load(path):
    with open(path) as f:
        return list(csv.DictReader(f))


def fmt(v):
    return "  вырожд." if v != v else f"{v:>8.4f}°"


def report_clock_bridge(rows):
    """МОСТ МЕЖДУ ЧАСАМИ ноутбука и платы — измеренный, а не принятый.

    Новый источник меток времени сначала сводится с уже имеющимися, и только
    потом на него переезжают. Ход обязан быть ~1 (обе шкалы считают одни и те
    же секунды), а СКО расхождения — это и есть джиттер доставки, который
    раньше молча уходил в «шум тракта».
    """
    tb = board_ts(rows)
    if tb is None or len(rows) < 3:
        print("\n  МОСТ МЕЖДУ ЧАСАМИ НЕ ИЗМЕРЕН: в логе нет t_us/cap_age,")
        print("  ход снимается по времени ПРИЁМА на ноутбуке — джиттер"
              " доставки войдёт в остаток.")
        return None
    th = [float(r["t_host"]) for r in rows]
    f = _lsq(tb, th)
    if not f:
        print("\n  МОСТ МЕЖДУ ЧАСАМИ НЕ ИЗМЕРЕН: часы платы стоят.")
        return None
    rate, b, res = f
    dev = [h - (rate * t + b) for t, h in zip(tb, th)]
    print(f"\n  МОСТ МЕЖДУ ЧАСАМИ ({len(rows)} проб)")
    print(f"    ход часов ноутбука к часам платы: {rate:.6f}"
          f"   (обязано быть ~1)")
    print(f"    расхождение (джиттер доставки): СКО {res * 1e3:.2f} мс,"
          f" размах {span_of(dev) * 1e3:.1f} мс")
    if abs(rate - 1.0) > CLOCK_TOL:
        print(f"    ВНИМАНИЕ: ход отличается от 1 на {(rate - 1) * 100:+.2f}%"
              f" (порог {CLOCK_TOL * 100:.0f}%) — шкалы времени не сходятся,")
        print("    одна из них врёт, и снятый по ней ход вала врёт вместе с ней.")
    return rate, res


def report_static(name, rows, gain, span=1.0, moving=False, clock="board"):
    """Шум тракта. gain — градусов на единицу скважности."""
    isr_raw = unwrap([isr_deg(r) for r in rows])
    # Захват разворачивается В ШКАЛЕ СКВАЖНОСТИ (период 1.0), и только потом
    # переводится в градусы. Разворот по 360 был бы разворотом в чужой шкале:
    # период захвата равен наклону моста, а не 360.
    cap_raw = [f * gain for f in unwrap([cap_frac(r) for r in rows], period=span)]
    ts = sample_ts(rows, clock)
    kind = "вал едет, ход снят" if moving else "вал стоит"
    isr, cap = isr_raw, cap_raw
    used = list(range(len(rows)))
    if moving:
        # ХОД СНИМАЕТСЯ ВНУТРИ УЧАСТКОВ БЕЗ ШВА, а не сквозь них. Разворот
        # через шов опирается на измеренный размах скважности, и его ошибка
        # даёт СТУПЕНЬКУ, которую снятие прямой размазывает по всему отрезку
        # как шум. На подложке это завышало шум захвата вдвое.
        raw = [cap_frac(r) for r in rows]
        deg0 = [isr_deg(r) for r in rows]
        runs = split_runs(raw, deg0, minlen=20) or [list(range(len(rows)))]
        isr_o, cap_o = [], []
        for r in runs:
            isr_o += detrend(unwrap([isr_raw[i] for i in r]), [ts[i] for i in r])
            cap_o += detrend([raw[i] * gain for i in r], [ts[i] for i in r])
        isr, cap = isr_o, cap_o
        used = [i for r in runs for i in r]
        rows = [rows[i] for i in used]
        print(f"\n  --- {name}: {len(rows)} проб из {len(raw)}"
              f" в {len(runs)} участках без шва, {kind} ---")
    else:
        print(f"\n  --- {name}: {len(rows)} проб, {kind} ---")
    # УРОВНИ И ИНТЕРВАЛ СЧИТАЮТСЯ ПО СЫРЫМ ЗНАЧЕНИЯМ. Обе колонки — про
    # КВАНТОВАНИЕ, а снятие хода квантование уничтожает: вычитаемая прямая
    # непрерывна, сетка уровней рассыпается, и по тракту с шагом 0.39258°
    # печаталось «интервал 0.0004°, уровней 1499». Сырые значения берутся
    # неразвёрнутыми: развёртка добавляет к части проб смещение, не кратное
    # кванту, и тоже размазывает сетку.
    lv_isr = [isr_deg(r) for r in rows]
    lv_cap = [cap_frac(r) * gain for r in rows]
    hdr = f"    {'тракт':<24}{'СКО':>10}{'робастно':>11}{'уровней':>9}{'интервал':>11}"
    print(hdr)
    for tag, xs, lv in (("micros(), сырой", isr, lv_isr),
                        ("аппаратный захват", cap, lv_cap)):
        print(f"    {tag:<24}{sd(xs):>9.4f}°{fmt(mad_sd(xs)):>11}"
              f"{len(set(round(x, 6) for x in lv)):>9}"
              f"{fmt(min_level_gap(lv)):>11}")
    r_isr, r_cap = mad_sd(isr), mad_sd(cap)
    span_isr = span_of([isr_raw[i] for i in used])
    if span_isr < MIN_SPAN_DEG:
        # ГЕЙТ ИЗ ЖУРНАЛА ВАЛИДАЦИИ. При размахе меньше трёх квантов боевая
        # колонка вырождена в один-два уровня; её «шум» — это шум округления,
        # а не тракта, и отношение к захвату даёт фантастику вроде 3900x.
        print(f"    ВЫИГРЫШ НЕ СЧИТАЕТСЯ: размах боевого тракта {span_isr:.4f}°"
              f" меньше {MIN_SPAN_QUANTS} квантов ({MIN_SPAN_DEG:.4f}°).")
        print("      При таком размахе разрешение не определяется: колонка"
              " micros() вырождена,")
        print("      и любое отношение к захвату будет числом про округление,"
              " а не про тракты.")
    elif r_cap == r_cap and r_isr == r_isr and r_cap > 0:
        print(f"    выигрыш робастно: {r_isr / r_cap:>6.1f}x     "
              f"по СКО: {sd(isr) / sd(cap):.1f}x")
    elif sd(cap) > 0 and sd(isr) > 0:
        print(f"    выигрыш по СКО: {sd(isr) / sd(cap):.1f}x"
              f"   (робастная оценка вырождена — сравнивать по СКО)")
    else:
        # Нулевое СКО — не «идеальный тракт», а замерший: значение не
        # меняется вовсе. Печатать бесконечный выигрыш было бы враньём.
        who = "захвата" if sd(cap) == 0 else "micros()"
        print(f"    ТРАКТ {who} НЕ МЕНЯЕТСЯ ВОВСЕ: СКО ровно ноль."
              f" Это признак замершего тракта, а не отсутствия шума.")
    if moving:
        # РАЗЛОЖЕНИЕ ДИСПЕРСИИ. Оба тракта читают ОДИН И ТОТ ЖЕ импульс
        # датчика, поэтому всё, что происходит до кодирования в ШИМ, входит в
        # оба одинаково, а способы чтения шумят независимо:
        #
        #   захват = общее + шум_захвата ;  micros = общее + шум_micros
        #   дисп(разности) = шум_захвата + шум_micros
        #   общее = (дисп(захв) + дисп(micros) - дисп(разности)) / 2
        #
        # ЧТО ТАКОЕ «ОБЩЕЕ» — важно не соврать. Это НЕ только движение вала:
        # туда же входит собственный шум и нелинейность самого датчика, всё
        # до момента кодирования. Разделить их этим замером нельзя, и называть
        # общую часть «дрожанием вала» было бы приписыванием.
        d = [c - i for c, i in zip(cap, isr)]
        vc, vi, vd = sd(cap) ** 2, sd(isr) ** 2, sd(d) ** 2
        vs = max((vc + vi - vd) / 2, 0.0)
        print(f"    разность трактов: СКО {sd(d):.4f}°")
        print(f"    общее (вал + сам датчик):  {math.sqrt(vs):>8.4f}°"
              f"   <- видят оба одинаково")
        print(f"    собственный шум ЗАХВАТА:   {math.sqrt(max(vc - vs, 0)):>8.4f}°")
        print(f"    собственный шум micros():  {math.sqrt(max(vi - vs, 0)):>8.4f}°"
              f"   (чистый квант дал бы {QUANT_ISR / math.sqrt(12):.4f}°)")
        if vc - vs <= 0:
            print("      у захвата вышло не больше нуля: собственный шум НЕ")
            print("      ОТЛИЧИМ от нуля на фоне общей части — тракт показывает")
            print("      датчик, а не себя")
    return dict(name=name, n=len(rows), sd_isr=sd(isr), sd_cap=sd(cap),
                mad_isr=r_isr, mad_cap=r_cap, span_isr=span_isr)


def report_flags(rows):
    c = defaultdict(int)
    for r in rows:
        fl = int(r["flags"])
        for bit, nm in DF.items():
            if fl & bit:
                c[nm] += 1
    n = len(rows)
    print(f"\n  признаки негодности на {n} пакетов:")
    bad = [(nm, c[nm]) for _, (nm, _t) in sorted(BAD_FLAGS.items()) if c[nm]]
    if not bad:
        print("    чисто: ни одного")
    for nm, k in bad:
        print(f"    {nm:<12}{k:>7}  ({100.0 * k / n:5.2f}%)")

    # ОПИСАТЕЛЬНЫЕ ПЕЧАТАЮТСЯ ОТДЕЛЬНО И С ПОЯСНЕНИЕМ. Иначе стопроцентный
    # cap_skip снова прочитается как постоянная авария — именно так его и
    # читали, пока он лежал в одном списке с негодностью.
    print("  темп и поправки (НЕ негодность):")
    for bit, (nm, txt) in sorted(INFO_FLAGS.items()):
        print(f"    {nm:<12}{c[nm]:>7}  ({100.0 * c[nm] / n:5.2f}%)  {txt}")

    # ВЕРДИКТ О ЖИВОСТИ ТРАКТА ЗАХВАТА. Считается по битам, а не по глазам:
    # «мёртвый датчик» и «неподвижный вал» в числах выглядят одинаково.
    exp = frames_per_poll(rows)
    if not (exp != exp):
        print(f"    на один опрос приходится ~{exp:.1f} кадров датчика")
    stall = c["cap_stall"]
    skip = c["cap_skip"]
    if stall:
        print(f"    ТРАКТ ЗАХВАТА ЗАМИРАЛ: cap_stall в {stall} пакетах"
              f" ({100.0 * stall / n:.2f}%) — фронтов не приходило")
    elif exp == exp and exp >= 2.0 and skip < 0.5 * n:
        print("    ПОДОЗРЕНИЕ: кадров на опрос больше двух, а пропуски"
              " отмечены меньше чем в половине пакетов —")
        print("    либо датчик отдаёт кадры реже, чем показывает период,"
              " либо лог снят прошивкой с другим смыслом бита")
    else:
        print("    тракт захвата жив: кадры шли между всеми опросами")
    return dict(c)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("csv")
    ap.add_argument("--gain", type=float, default=360.0,
                    help="градусов на единицу скважности; по умолчанию наивные 360")
    ap.add_argument("--clock", choices=("board", "host"), default="board",
                    help="по каким часам снимать ход: платы (t_us/cap_age)"
                         " или приёма на ноутбуке (t_host)")
    a = ap.parse_args()

    rows = load(a.csv)
    if not rows:
        sys.exit("пустой файл")
    print(f"файл: {a.csv}, строк {len(rows)}")

    # Годными считаем только те, где ОБА тракта дали годный отсчёт: иначе
    # тракты сравнивались бы на разных подмножествах.
    good = [r for r in rows if int(r["flags"]) & BAD_MASK == 0]
    print(f"годных (оба тракта): {len(good)}")
    report_flags(rows)

    # Мост между часами печатается ДО всего, что снимает ход: если шкалы
    # времени не сходятся, все остатки ниже посчитаны по кривой линейке.
    if good:
        report_clock_bridge(good)
    if a.clock == "host":
        print("\n  ХОД СНИМАЕТСЯ ПО ЧАСАМ НОУТБУКА (--clock host):"
              " джиттер доставки войдёт в остаток.")
    elif not has_board_clock(good):
        print("\n  часов платы в логе нет — ход снимается по t_host.")

    per = defaultdict(list)
    for r in good:
        per[r["label"]].append(r)

    # Период кадра — независимая проверка тактовой и константы кадра.
    ps = [float(r["cap_period"]) for r in good]
    mu = sum(ps) / len(ps) if ps else float("nan")
    if ps:
        print(f"\n  период кадра захвата: {mu / TIM2_HZ * 1e6:.2f} мкс "
              f"({mu:.0f} тиков), ожидалось ~921 мкс")

    # ---- МОСТ МЕЖДУ ШКАЛАМИ: только по отрезкам с ходом --------------------
    gain, span, bridge_ok = a.gain, 1.0, False
    moving = [r for r in good if r["mode"] == "spin"]
    if len(moving) > 50:
        frac_raw = [cap_frac(r) for r in moving]
        deg_raw = [isr_deg(r) for r in moving]
        fit, info = fit_bridge(frac_raw, deg_raw)
        # РАЗМАХ СКВАЖНОСТИ МЕРЯЕТСЯ, А НЕ ПРИНИМАЕТСЯ ЗА ЕДИНИЦУ. Часть кадра
        # служебная, скважность всю единицу не пробегает, и разворот по 1.0
        # оставлял бы на каждом шве разрыв величиной с мёртвый участок.
        # РАЗМАХ МЕРЯЕТСЯ ПО ВЕЛИЧИНЕ СКАЧКА НА ШВЕ, а не по краям выборки.
        # На шве скважность падает с верхней границы диапазона на нижнюю —
        # то есть скачок РАВЕН размаху, прямо и без предположений. Оценка по
        # процентилям занижала его на всё, что не покрыл ход вала, и сверка
        # «наклон x размах = 360» не сходилась на 5.5°.
        jumps = [abs(b - a) for a, b in zip(frac_raw, frac_raw[1:])
                 if abs(b - a) > 0.5]
        ss = sorted(frac_raw)
        lo, hi = ss[0], ss[-1]
        span_is_floor = not jumps
        if jumps:
            span = sorted(jumps)[len(jumps) // 2]
        else:
            # Швов не было — ход не покрыл оборота. Тогда размах по краям, и
            # это ОЦЕНКА СНИЗУ: непокрытая часть диапазона в неё не вошла.
            span = hi - lo
            print("\n  ВНИМАНИЕ: швов кадра в ходе нет, размах скважности —"
                  " оценка снизу по краям выборки")
        print(f"\n  МОСТ МЕЖДУ ШКАЛАМИ ({len(moving)} проб вращения,"
              f" {info['n_runs']} участков без шва кадра)")
        print(f"    в участки вошло {info['n_in_runs']} проб из"
              f" {info['n_total']}; в подгонку — {info['n_fit_pts']}"
              f" ({100.0 * info['n_fit_pts'] / max(info['n_total'], 1):.1f}%)")
        if info["n_flat"]:
            print(f"    отброшено участков без хода боевого тракта:"
                  f" {info['n_flat']} (размах меньше {MIN_SPAN_QUANTS} квантов"
                  f" = {MIN_SPAN_DEG:.4f}°)")
        if info["n_degen"]:
            print(f"    отброшено участков без хода скважности:"
                  f" {info['n_degen']}")
        if fit:
            k, b, resid, nruns, spread = fit
            print(f"    участков в подгонке: {nruns}")
            print(f"    наклон:  {k:9.3f} град на единицу скважности"
                  f"   (наивно ожидалось 360)")
            print(f"    смещение:{b:9.3f} град")
            # ПОРОГ, А НЕ ЭПИТЕТ. Раньше рядом с разбросом при любом его
            # значении печаталось «велик => мост не прямая», то есть вывод не
            # зависел от числа. Порог — доля от самого наклона: разброс 0.4
            # при наклоне 371 и при наклоне 4 означает разное.
            lim = BRIDGE_SPREAD_FRAC * abs(k)
            verdict = ("мост прямая" if spread <= lim else "МОСТ НЕ ПРЯМАЯ")
            print(f"    разброс наклона по участкам: {spread:.3f}"
                  f"  (порог {lim:.3f} = {BRIDGE_SPREAD_FRAC * 100:.0f}%"
                  f" наклона)  <- {verdict}")
            print(f"    СКО остатка: {resid:.4f}°  <- рассогласование трактов")
            print(f"    отличие наклона от наивного: {(k / 360.0 - 1) * 100:+.2f}%")
            print(f"    размах скважности: {span:.4f}"
                  f"   (края выборки {lo:.4f}..{hi:.4f})"
                  f"   (мёртвый участок кадра {100 * (1 - span):.1f}%)")
            # НЕЗАВИСИМАЯ СВЕРКА: наклон и размах измерены по-разному —
            # первый подгонкой к боевому тракту, второй просто краями. Их
            # произведение обязано дать полный оборот. Это ГЕЙТ: не сошлось —
            # значит одно из двух измерений врёт, и какое именно, отсюда не
            # видно, поэтому моста нет вовсе.
            miss = k * span - 360.0
            print(f"    сверка: наклон x размах = {k * span:.2f}°"
                  f"  (обязано быть 360°, расхождение {miss:+.2f}°)")
            if abs(miss) <= BRIDGE_TOL_DEG:
                gain, bridge_ok = k, True
            else:
                print(f"    МОСТ НЕ ИЗМЕРЕН: сверка не сошлась"
                      f" (допуск {BRIDGE_TOL_DEG:.0f}°).")
                if span_is_floor:
                    print("    Размах — оценка снизу (швов не было), так что"
                          " разойтись сверка могла и из-за него.")
                print("    Наклон дальше взят наивным (360) — это ДОПУЩЕНИЕ,")
                print("    и шум захвата в градусах ниже настолько же условен.")
        else:
            print("    МОСТ НЕ ИЗМЕРЕН: ни одного участка, годного в подгонку,")
            print("    не нашлось. Наклон взят наивным (360) — ДОПУЩЕНИЕ.")
            if info["n_flat"] and not info["n_degen"]:
                print("    Причина: БОЕВОЙ ТРАКТ НЕ ХОДИТ ни на одном участке"
                      " — сравнивать захват не с чем.")
    else:
        print("\n  МОСТ НЕ ИЗМЕРЕН: отрезков с вращением в логе нет.")
        print("  Наклон взят наивным (360 град на скважность) — это ДОПУЩЕНИЕ,")
        print("  и шум захвата в градусах ниже настолько же условен.")

    # КВАНТ ЗАХВАТА ПЕЧАТАЕТСЯ ПОСЛЕ МОСТА, а не до него: он равен наклону,
    # делённому на период кадра, и посчитанный по наивным 360 отличался бы от
    # правды на всю ошибку моста (3% на этом железе). Раньше эта строка стояла
    # выше подгонки и молча пользовалась допущением.
    if ps:
        note = "" if bridge_ok else "   [ПО ДОПУЩЕНИЮ 360, мост не измерен]"
        print(f"\n  квант захвата (1 тик TIM2): {gain / mu:.5f}°"
              f"   квант micros(): {QUANT_ISR:.5f}°"
              f"   отношение {QUANT_ISR / (gain / mu):.0f}x{note}")

    mark = "измерен" if bridge_ok else "ДОПУЩЕНИЕ, мост не измерен"
    print(f"\n  === шум по отрезкам (наклон {gain:.1f} град/скважность,"
          f" {mark}) ===")
    for label in per:
        if per[label]:
            report_static(label, per[label], gain, span,
                          moving=(per[label][0]["mode"] == "spin"),
                          clock=a.clock)


if __name__ == "__main__":
    main()
