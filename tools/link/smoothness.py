#!/usr/bin/env python3
"""Плавность хода по скоростям: контрольная кривая для замкнутого контура.

ЧТО МЕРЯЕТ. Остаток угла после снятия равномерного хода, в полосе 1-20 Гц.
Это и есть «плавность»: медленный увод в неё не попадает (его снимает ход и
режет нижняя граница), а шум датчика режет верхняя.

ПОЧЕМУ ИМЕННО ТРАКТ ЗАХВАТА. Собственный шум боевого тракта 0.72-0.91 град
шире всего, что мы ищем; мерить им плавность значило бы мерить прибор.
Тракт захвата шумит 0.037-0.069 и годится. Оба тракта считаются рядом
НАМЕРЕННО — разница показывает, что старый тракт вообще не способен увидеть.

ЧАСЫ БЕРУТСЯ С ПЛАТЫ И С ПОПРАВКОЙ НА ВОЗРАСТ ЗАХВАТА: t_us - cap_age/170e6.
Часы ноутбука дают джиттер доставки 3-5 мс, а он на скорости превращается в
фальшивый шум (при 0.5 рад/с это 0.14 град — больше измеряемого).
"""
import csv, math, sys, os
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from diag_metrics import (cap_frac, isr_deg, unwrap, sd, split_runs,
                          BAD_MASK, TIM2_HZ)

# ПОЛОСА ЗАДАЁТСЯ В ПОРЯДКАХ ОБОРОТА, А НЕ В ГЕРЦАХ.
#
# Помеха привода привязана к ОБОРОТУ, а не ко времени: зубцовый момент сидит на
# 22 циклах на оборот (удвоенная электрическая частота при 11 парах полюсов).
# В герцах он едет со скоростью, и фиксированная нижняя граница его теряет:
#
#     0.10 рад/с -> 22-й порядок = 0.350 Гц   \
#     0.20 рад/с -> 22-й порядок = 0.700 Гц    > НИЖЕ прежней границы 1 Гц
#     0.40 рад/с -> 22-й порядок = 1.401 Гц   /  попадает
#
# Цена ошибки измерена: ячейка ladder_load w020 в полосе 1-20 Гц дала 0.122
# град, а честный пересчёт — 0.723, из которых 0.444 несёт ОДНА зубцовая линия
# 0.700 Гц, выпавшая из полосы. То есть метрика теряла шесть седьмых мощности
# ровно на тех малых скоростях, ради которых всё и затевалось.
#
# Полоса Гц оставлена рядом НАМЕРЕННО: резонанс подвеса привязан ко времени, а
# не к обороту, и в шкале порядков он размазывается. Две шкалы разводят
# зубцы и резонанс — без этого их не различить.
ORDER_LO, ORDER_HI = 5.0, 300.0     # циклов на оборот: покрывает 11..132
BAND_LO, BAND_HI = 1.0, 20.0        # Гц: для резонансов, привязанных ко времени
NEBW_HANN = 1.5        # шумовая полоса окна Ханна
# НАКЛОН МОСТА — ОДИН ИСТОЧНИК НА ВЕСЬ ПИТОН. Число жило в двух местах
# (здесь 362.4 и CAPSENS_DEG_PER_DUTY = 362.7 в классе), расходясь на 0.083%.
# На плавность это влияет ничтожно, но это ровно тот класс дефекта, из-за
# которого правят мёртвую ветку.
# ВНИМАНИЕ: третья копия жила в stm/libraries/CaptureSensor/src/CaptureSensor.h (тег stm-era)
# и должна быть приведена к этому же значению вручную — межъязыковой границы
# импорт не пересекает.
GAIN = 362.07         # свежий замер v2_spin; прежние 362.4/362.7 отозваны


def sample_ts(r):
    """Точный момент отсчёта по часам ПЛАТЫ, секунды."""
    return int(r["t_us"]) / 1e6 - int(r["cap_age"]) / TIM2_HZ


def resample(ts, xs, fs):
    """На равномерную сетку линейной интерполяцией.

    Спектр требует равномерных отсчётов, а приходят они с джиттером канала.
    Интерполяция слегка душит верх полосы, но одинаково для ОБОИХ трактов,
    поэтому их сравнение она не искажает.
    """
    t0, t1 = ts[0], ts[-1]
    n = int((t1 - t0) * fs)
    out, j = [], 0
    for i in range(n):
        t = t0 + i / fs
        while j + 2 < len(ts) and ts[j + 1] < t:
            j += 1
        a, b = ts[j], ts[j + 1]
        w = 0.0 if b <= a else (t - a) / (b - a)
        out.append(xs[j] * (1 - w) + xs[j + 1] * w)
    return out


def detrend_line(xs):
    n = len(xs)
    mt = (n - 1) / 2.0
    mx = sum(xs) / n
    stt = sum((i - mt) ** 2 for i in range(n))
    k = sum((i - mt) * (x - mx) for i, x in enumerate(xs)) / stt
    return [x - (mx + k * (i - mt)) for i, x in enumerate(xs)]


def band_rms(xs, fs, lo=BAND_LO, hi=BAND_HI):
    """СКО в полосе. Прямым перебором частот — данных мало, скорость не важна,
    зато не нужен внешний БПФ и видно, что именно считается."""
    n = len(xs)
    if n < 64:
        return float("nan"), []
    w = [0.5 - 0.5 * math.cos(2 * math.pi * i / (n - 1)) for i in range(n)]
    # НОРМИРОВКА — КВАДРАТ СУММЫ ВЕСОВ, а не сумма квадратов.
    #
    # Для синуса амплитуды A взвешенная сумма даёт |X_k| = A*sum(w)/2, значит
    # мощность восстанавливается как 2*|X_k|^2 / sum(w)^2 = A^2/2. Деление на
    # sum(w*w) завышает результат в 2n/3 раз (для окна Ханна), то есть на
    # трёх тысячах проб — в сорок раз. Поймано подложкой: заложенный синус
    # 0.1768 град возвращался как 6.85.
    wsum = sum(w) ** 2
    xw = [x * wv for x, wv in zip(xs, w)]
    df = fs / n
    k_lo, k_hi = max(1, int(lo / df)), min(n // 2 - 1, int(hi / df))
    power, lines = 0.0, []
    for k in range(k_lo, k_hi + 1):
        c = s = 0.0
        for i, v in enumerate(xw):
            a = 2 * math.pi * k * i / n
            c += v * math.cos(a); s += v * math.sin(a)
        p = 2.0 * (c * c + s * s) / wsum      # средний квадрат в этом бине
        power += p
        lines.append((p, k * df))
    lines.sort(reverse=True)
    # ДОЛЯ СЧИТАЕТСЯ ОТ ВСЕЙ ПОЛОСЫ, а не от трёх сильнейших линий. Прежняя
    # редакция возвращала lines[:3], и делитель брался по этому же списку —
    # то есть доля была ограничена снизу третью ПО ПОСТРОЕНИЮ. Напечатанные
    # «39%» и «42%» на деле 7.5% и 17.2%, и первое из них ушло в документ,
    # по которому принимается решение о замкнутом контуре.
    lines = [(pw / power if power > 0 else 0.0, f) for pw, f in lines]
    # ДЕЛЕНИЕ НА ШУМОВУЮ ПОЛОСУ ОКНА. Окно Ханна размазывает энергию по
    # соседним бинам, и суммирование бинов её пересчитывает ровно в 1.5 раза.
    # Без этого деления метрика завышала на sqrt(1.5) = 1.225 — одинаково на
    # синусе любой амплитуды и частоты, поэтому по одной проверке ошибку было
    # бы не отличить от калибровки. То же деление стоит в tools/stand/jerk_metric.py.
    return math.sqrt(power / NEBW_HANN), lines[:3]   # доли уже нормированы


def main():
    path = sys.argv[1] if len(sys.argv) > 1 else "runs/ladder_open.csv"
    rows = [r for r in csv.DictReader(open(path)) if int(r["flags"]) & BAD_MASK == 0]
    seg = {}
    for r in rows:
        seg.setdefault(r["label"], []).append(r)

    print(f"файл: {path}, годных проб {len(rows)}")
    print(f"плавность = СКО остатка, ход снят, часы платы")
    print(f"  колонки «порядки»: полоса {ORDER_LO:.0f}-{ORDER_HI:.0f} циклов на"
          f" оборот — сюда попадают зубцы при ЛЮБОЙ скорости")
    print(f"  колонка «{BAND_LO:.0f}-{BAND_HI:.0f} Гц»: прежняя шкала, для"
          f" резонансов, привязанных ко времени\n")
    print(f"  {'скорость':>9}{'проб':>7}{'частота':>9}"
          f"{'ЗАХВАТ':>10}{'micros':>10}{'захват':>10}{'сильнейшая линия':>19}")
    print(f"  {'рад/с':>9}{'':>7}{'опроса':>9}"
          f"{'порядки':>10}{'порядки':>10}{'1-20 Гц':>10}{'Гц (доля)':>19}")
    out = []
    for lab in sorted(seg):
        rr = seg[lab]
        w = float(rr[0]["spin"])
        ts = [sample_ts(r) for r in rr]
        t0 = ts[0]
        ts = [t - t0 for t in ts]
        fs = len(ts) / (ts[-1] - ts[0])

        # Участки без шва кадра: развёртка через шов опирается на измеренный
        # размах, и его ошибка даёт ступеньку, которую снятие хода размажет
        # по всей записи как шум.
        raw = [cap_frac(r) for r in rr]
        # ВТОРЫМ АРГУМЕНТОМ — ГРАДУСЫ, А НЕ ТА ЖЕ СКВАЖНОСТЬ. split_runs режет
        # ещё и по скачку больше 180 град; при подаче raw (0..1) это условие
        # тождественно ложно, и защита, специально добавленная в diag_metrics,
        # в этой ветке была выключена.
        degs = [isr_deg(r) for r in rr]
        runs = split_runs(raw, degs, minlen=200) or [list(range(len(rr)))]
        best = max(runs, key=len)

        tt = [ts[i] for i in best]
        cap = [raw[i] * GAIN for i in best]
        isr = unwrap([isr_deg(rr[i]) for i in best])

        cu = resample(tt, cap, fs)
        iu = resample(tt, isr, fs)
        # ПОЛОСА В ПОРЯДКАХ пересчитывается в герцы по СКОРОСТИ ЭТОГО отрезка.
        rev_hz = abs(w) / (2.0 * math.pi)          # оборотов в секунду
        o_lo, o_hi = ORDER_LO * rev_hz, ORDER_HI * rev_hz
        rc, lines = band_rms(detrend_line(cu), fs, lo=o_lo, hi=o_hi)
        ri, _ = band_rms(detrend_line(iu), fs, lo=o_lo, hi=o_hi)
        # Та же запись в шкале ГЕРЦ — для резонанса подвеса.
        rc_hz, _ = band_rms(detrend_line(cu), fs)
        ri_hz, _ = band_rms(detrend_line(iu), fs)
        top = f"{lines[0][1]:.1f} ({lines[0][0]*100:.1f}%)" if lines else "-"
        print(f"  {w:>9.2f}{len(best):>7}{fs:>8.0f}Гц"
              f"{rc:>10.4f}{ri:>10.4f}{rc_hz:>10.4f}{top:>19}")
        out.append((w, rc, ri))

    print()
    worst = max(out, key=lambda x: x[1])
    best_w = min(out, key=lambda x: x[1])
    print(f"  хуже всего: {worst[0]:.2f} рад/с -> {worst[1]:.4f}°")
    print(f"  лучше всего: {best_w[0]:.2f} рад/с -> {best_w[1]:.4f}°")
    print(f"  размах по лестнице: {worst[1]/best_w[1]:.1f}x")
    print()
    print("  ЧТО ВИДИТ СТАРЫЙ ТРАКТ. Его собственный шум 0.72-0.91° шире всей")
    print("  измеряемой величины, поэтому колонка micros почти не зависит от")
    print("  скорости: она показывает прибор, а не вал.")


if __name__ == "__main__":
    main()
