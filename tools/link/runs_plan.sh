#!/bin/bash
# Подготовленные прогоны: каждый запускается ОДНОЙ командой и передаёт все
# параметры явно, включая --ez defaults true.
#
# Почему явно. Экран настроек до 28e1b5c не влиял ни на один прогон (писал в
# другой набор), и все прежние замеры шли на умолчаниях, что бы на нём ни
# стояло. Теперь он влияет — а значит, прогон, запущенный командой, обязан
# сказать «игнорируй сохранённое», иначе сравнивать два прогона будет нельзя:
# между ними мог измениться экран.
#
#   runs_plan.sh список
#   runs_plan.sh <имя>
set -eu
ROOT="$(cd "$(dirname "$0")/../.." && pwd)"
MAC=${MAC:-38:18:2B:30:7D:86}
COMMON="--es mac $MAC --ez defaults true --ez home false"

case "${1:-список}" in

# --- ГЛАВНЫЙ: рассудить правку синхронизации -------------------------------
# Прежняя приёмка сравнивала ХОДЬБУ без синхронизации со СТОЯНИЕМ с ней, то
# есть разные условия, и вывод был неверен. Однотипное сравнение на ходьбе
# улучшения не показало. Не хватает ровно одной клетки таблицы: СТОЯ, БЕЗ
# синхронизации. Её и снимаем — остальные три уже есть.
стоя-без-синхронизации)
    echo "ЧЕЛОВЕК СТОИТ НЕПОДВИЖНО в кадре, 60 с. Не ходить."
    echo "Это недостающая клетка: стоя + синхронизация ВЫКЛЮЧЕНА."
    set -- --ez sync false --ei seconds 60 --ez video false --es scen стоя --es tag стоя_без_sync
    ;;

# Повтор с включённой — тем же днём, тем же местом, чтобы сравнение было
# честным (прежний прогон стоя+sync снят при другом освещении и другой сцене).
стоя-с-синхронизацией)
    echo "ЧЕЛОВЕК СТОИТ НЕПОДВИЖНО в кадре, 60 с. Не ходить."
    echo "Пара к предыдущему: то же место, то же освещение, синхронизация ВКЛ."
    set -- --ez sync true --ei seconds 60 --ez video false --es scen стоя --es tag стоя_с_sync
    ;;

# --- ЕДИНСТВЕННЫЙ режим, где синхронизацию можно проверить --------------
# Пара «стоя с ней / без неё» показала поправку 0.041° при шуме рамки 0.2-0.6°:
# на устоявшейся цели вал не движется, вычитать нечего, механизм выключен по
# построению. Разница живёт в переходе «шёл — встал»: вал ещё идёт, цель уже
# стоит. Там же наблюдалось и затухающее качание.
проход-стоп-без-синхронизации)
    echo "ИДИТЕ и по команде РЕЗКО ОСТАНАВЛИВАЙТЕСЬ, три раза. 66 с."
    echo "Синхронизация ВЫКЛЮЧЕНА."
    set -- --ez sync false --ei seconds 66 --ez video false --es scen проход_стоп \
           --es tag проход_стоп_без_sync
    ;;

проход-стоп-с-синхронизацией)
    echo "То же самое, то же место. Синхронизация ВКЛЮЧЕНА."
    set -- --ez sync true --ei seconds 66 --ez video false --es scen проход_стоп \
           --es tag проход_стоп_с_sync
    ;;

# --- ПОЛНЫЙ ПРОГОН: проба изделия целиком ---------------------------------
# Не проверка механизма, а восемь минут работы: нагрев, расход заряда,
# удержание кадров при записи 4K, поведение на разных дистанциях. Запись
# обязательна — иначе нечего разбирать; возврат в исходное включён, как в
# боевом применении.
полный)
    echo "ПОЛНЫЙ ПРОГОН: 8 минут, с записью 4K и возвратом в исходное."
    echo "Телефон будет говорить, что делать. Ходите по его репликам."
    echo "Заряд и нагрев меряются сами; снимок батареи до и после — в отчёте."
    set -- --ez sync true --ei seconds 480 --ez video true --es quality 2160 \
           --ei fps 24 --ez home true --es scen полный --es tag полный
    ;;

# --- ТОЛЧОК: возмущение делает машина, режим чередуется внутри прогона -----
# Пара «проход и стоп» оказалась несравнимой: в одном прогоне человек шёл
# быстро, в другом медленно, а переход тем мягче, чем медленнее подход.
# Скорость ходьбы ничем не задать. Здесь стенд отклоняется сам на 0.35 рад/с
# в течение полусекунды каждые 10 с, а синхронизация чередуется от толчка к
# толчку — то есть оба режима меряются одним и тем же возмущением, в одном
# прогоне, без разницы в освещении, нагреве и положении.
толчок)
    echo "ВСТАНЬТЕ В КАДР И СТОЙТЕ НЕПОДВИЖНО 100 секунд. Ходить НЕ надо."
    echo "Стенд будет сам отклоняться каждые 10 секунд и возвращаться —"
    echo "так и задумано, это возмущение для замера. Просто стойте."
    # Чаще и дольше: на прогоне 260818_1026 разброс пиков внутри одного
    # режима вышел 4.3° при разнице медиан 1.2° — по три толчка на режим мало.
    # Каждые 6 с за 170 с даёт около 14 на режим.
    set -- --ez sync true --ef kick 0.35 --ei kick_ms 500 --ef kick_s 6 \
           --ei seconds 170 --ez video false --es scen стоя --es tag толчок
    ;;

# --- проверка правок C и D: окно на промахах и возврат после потери --------
# Нужны ПРОПУСКИ: человек должен уходить за препятствие или из кадра и
# возвращаться. Кадры модели обязательны — по ним видно, что именно видела
# сеть в раздутом окне.
потери)
    echo "ХОДИТЕ и ПРОПАДАЙТЕ: зайдите за препятствие или выйдите из кадра"
    echo "на 2-3 секунды и вернитесь. Повторите 4-5 раз за 90 секунд."
    echo "Проверяются: расширение окна на промахах и возврат после потери."
    set -- --ez sync true --ei seconds 90 --ez rec true --ez video true --es scen потери --es tag потери
    ;;

# --- масштаб детектором, а не потоком -------------------------------------
# Единственный способ, переживший опровержение: наведение по НЕПОДВИЖНОЙ
# цели, регрессия уровней bx против вал_при_захвате. Нужно, чтобы вал реально
# прошёл два десятка градусов — поэтому вставать НЕ в центре кадра.
масштаб-детектором)
    echo "ВСТАНЬТЕ У КРАЯ КАДРА и стойте неподвижно 40 с."
    echo "Наведение должно провернуть стенд на 15-25° — на этом участке и"
    echo "меряется масштаб. В центре кадра мерить нечем."
    set -- --ez sync true --ei seconds 40 --ez video false --es scen стоя --es tag масштаб_детектором
    ;;

# --- КАМЕРА: цена превью ----------------------------------------------------
# Фиктивная поверхность превью (SurfaceTexture 1920x1080, никуда не выводится)
# держится в сессии по утверждению «без неё не собирается», которое НИ РАЗУ не
# проверялось. У этого аппарата нестопорящих слотов ровно три
# (maxNumOutputStreams = [1,3,1]), и превью занимает один целиком.
#
# ЧЕЛОВЕК НЕ НУЖЕН, и это не упрощение, а условие чистоты: цена потока не
# зависит от того, есть ли в кадре цель, а вот такт зависит — поэтому сцена
# обязана быть НЕПОДВИЖНОЙ и одинаковой в обоих прогонах. Достаточно оставить
# телефон смотреть в пустую комнату и не ходить перед ним.
превью-есть)
    echo "СЦЕНА НЕПОДВИЖНА, в кадре никого. 90 с, запись 4K."
    echo "Пара к «превью-нет»: то же место, тот же свет, не переставлять телефон."
    set -- --ei seconds 90 --ez video true --es quality 2160 --ez preview true \
           --ez rec false --es tag превью_есть
    ;;

превью-нет)
    echo "То же самое, ТЕЛЕФОН НЕ ТРОГАТЬ между прогонами. Превью отключено."
    echo "Если сессия не соберётся — так и будет сказано, это тоже ответ."
    set -- --ei seconds 90 --ez video true --es quality 2160 --ez preview false \
           --ez rec false --es tag превью_нет
    ;;

# --- КАМЕРА: аспект потока анализа -----------------------------------------
# 4:3 достался случайностью: отбор шёл по одной ширине. 16:9 это на треть
# меньше пикселей ISP, но потолок окна трекера падает с 1440 до 1080, а в
# прогоне 260818_1059 окно упиралось в потолок медианно. Значит меряем ОБА
# следствия сразу — и цену, и удержание, поэтому человек нужен.
аспект-4-3)
    echo "СТОЙТЕ В КАДРЕ и медленно ходите поперёк, 60 с. Запись 4K."
    set -- --ei seconds 60 --ez video true --es quality 2160 --es aspect 4:3 \
           --es scen стоя --es tag аспект_4_3
    ;;

аспект-16-9)
    echo "То же самое, то же место. Поток анализа 16:9."
    set -- --ei seconds 60 --ez video true --es quality 2160 --es aspect 16:9 \
           --es scen стоя --es tag аспект_16_9
    ;;

# --- КАМЕРА: аппаратный зум ------------------------------------------------
# 2.125 — предел, на котором FullHD ещё берётся с матрицы пиксель в пиксель
# (4080/1920). Выше него ISP интерполирует, и запись 4K перестаёт нести хоть
# что-то, чего нет в FullHD.
#
# Проверяется НЕ качество картинки, а то, что масштаб петли остался верен:
# зум умножает фокус в пикселях, и если это не учтено, K раздувается ровно во
# столько же раз. Меряется тем же способом, что «масштаб-детектором» —
# регрессией уровней bx против вал_при_захвате, наклон обязан выйти около 1.00.
зум-масштаб)
    echo "ВСТАНЬТЕ У КРАЯ КАДРА и стойте неподвижно 40 с. Зум 2.125."
    echo "Поле зрения сузится вдвое (72.9° -> 38.3°), встать надо ближе к центру,"
    echo "чем в прошлый раз, иначе цель окажется вне кадра."
    set -- --ez sync true --ei seconds 40 --ez video false --ef zoom 2.125 \
           --es scen стоя --es tag зум2_масштаб
    ;;

список|*)
    cat <<'TXT'
Подготовленные прогоны:

  полный                   проба изделия: 8 мин, запись 4K, заряд и нагрев
  толчок                   ГЛАВНЫЙ: возмущение машиной, режим чередуется внутри
                           одного прогона; человек просто стоит
  проход-стоп-без-синхронизации  (снято; оказалось несравнимо: скорость ходьбы)
  проход-стоп-с-синхронизацией   (снято; то же)
  стоя-без-синхронизации   устоявшийся режим (снято: разницы нет и быть не могло)
  стоя-с-синхронизацией    пара к ней
  потери                   пропадания и возвраты: правки C и D
  масштаб-детектором       наведение от края кадра: масштаб без потока

  превью-есть / превью-нет цена фиктивного потока превью. ЧЕЛОВЕК НЕ НУЖЕН:
                           неподвижная сцена, телефон между прогонами не трогать
  аспект-4-3 / аспект-16-9 цена лишней вертикали против потолка окна трекера
  зум-масштаб              аппаратный зум 2.125: остался ли верен масштаб петли

Каждый передаёт все параметры явно и --ez defaults true, поэтому экран
настроек на него не влияет.
TXT
    exit 0
    ;;
esac

echo
"$ROOT/tools/link/run_track.sh" $COMMON "$@"
