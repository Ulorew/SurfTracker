#!/bin/bash
# Стянуть прогон с телефона целиком и показать итог.
#
# Раньше это делалось руками по трём путям, и каждый раз надо было следить,
# от одного ли запуска взяты видео, лог и конфигурация. Теперь прогон —
# папка, и забирается она одной командой.
#
#   pull_run.sh            — последний прогон
#   pull_run.sh <имя>      — названный
#   pull_run.sh --список   — что вообще есть на телефоне
set -eu
. ~/Android/env.sh 2>/dev/null || true
ROOT="$(cd "$(dirname "$0")/../.." && pwd)"
C=com.surftracker.camfps
REMOTE=/sdcard/Android/data/$C/files/track
DEST="$ROOT/runs/phone"

# ТОЛЬКО папки прогонов, как их видит экран приложения: каталог полон файлов
# старого, плоского именования, и «последний по алфавиту» брал именно их —
# имена папок начинаются с цифр и сортируются ПЕРЕД буквами.
runs() {
    adb shell "for d in $REMOTE/*/; do [ -f \"\$d/прогон.json\" ] && basename \"\$d\"; done" \
        2>/dev/null | tr -d '\r' | grep -v '^$' | sort
}

if [ "${1:-}" = "--список" ] || [ "${1:-}" = "--list" ]; then
    runs
    exit 0
fi

NAME="${1:-}"
if [ -z "$NAME" ]; then
    NAME=$(runs | tail -1)
    [ -n "$NAME" ] || { echo "На телефоне нет ни одного прогона"; exit 1; }
    echo "последний прогон: $NAME"
fi

mkdir -p "$DEST"
adb pull "$REMOTE/$NAME" "$DEST/" >/dev/null || {
    echo "ОТКАЗ: не удалось забрать $NAME"; exit 1; }

LOCAL="$DEST/$NAME"
echo "забрано в $LOCAL"
echo
# Итог печатается ЗДЕСЬ ЖЕ. Прогон, после которого надо ещё что-то запускать,
# чтобы узнать результат, на практике остаётся неразобранным.
if [ -f "$LOCAL/прогон.json" ]; then
    "$ROOT/.venv/bin/python" - "$LOCAL/прогон.json" <<'PY'
import json, sys
d = json.load(open(sys.argv[1]))
it = d.get('итог')
if not it:
    print('ИТОГА НЕТ — прогон не дошёл до конца.')
    if 'ошибка' in d: print('ошибка:', d['ошибка'])
    sys.exit(0)
print(f"тактов {it['тактов']}, на цели {it['доля_на_цели']*100:.0f}%, "
      f"потерь {it['потерь']}, возвратов {it['повторных_захватов']}")
print(f"длительность {it['длительность_с']:.0f} с, "
      f"такт {it['такт_мс_медиана']:.0f} мс ({1000/max(it['такт_мс_медиана'],1e-9):.1f} Гц), "
      f"инференс {it['инференс_мс_медиана']:.0f} мс")
print(f"окно медианно {it['окно_медиана']:.0f} px, "
      f"промахов подряд макс {it['промахов_подряд_макс']}, "
      f"батарея {it['батарея_нагрев']:.1f}°C")
if not d.get('ok'): print('ЗАВЕРШИЛСЯ С ОШИБКОЙ:', d.get('ошибка'))
PY
else
    echo "прогон.json не найден — папка неполная"
fi
echo
ls -la "$LOCAL"
