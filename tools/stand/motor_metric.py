#!/usr/bin/env python3
"""Метрика стандартного протокола сравнения конфигураций мотора.

    tools/stand/motor_metric.py runs/base_2v5.txt [ещё файлы...]
    tools/stand/motor_metric.py --самопроверка

ЗАЧЕМ ОТДЕЛЬНО ОТ jerk_metric.py. Та меряет в полосе 1..20 Гц с вычетом
шумового пола и годится для сравнения ТРАКТОВ. Для сравнения КОНФИГУРАЦИЙ
мотора она слепа: на рабочих скоростях значительная часть мощности остатка
лежит НИЖЕ 1 Гц. Здесь полосы разделены явно, главным числом идёт ПОЛНОЕ СКО,
а зубцовая помеха меряется ПРОЕКЦИЕЙ НА ПОРЯДОК — она не зависит от того, в
какую полосу линия попала на данной скорости.

ЧТО СЧИТАЕТСЯ И ПОЧЕМУ ИМЕННО ТАК

  ход/команда   наклон фактического хода к заданному. Отдельным числом, а не
                внутри плавности: «не та скорость» и «не гладко» — разные
                дефекты с разными причинами, и смешивать их в одно число
                значит получить величину, которая растёт с длиной записи.

  полное СКО    остаток после снятия ФАКТИЧЕСКОГО тренда. Главное число.
                Фактического, а не командного: иначе рассинхрон втекает в
                плавность пилой.

  0.33..1 Гц    медленная часть. Нижняя граница именно 0.33, см. обоснование
                у LO: ниже на 12-секундной записи меряется остаток снятия
                тренда, а не вал.

  1..20 Гц      рябь. Верхняя граница — там, где начинается широкополосный
                шум датчика.

  дрейф         часть полного СКО, которую НЕ объясняют обе полосы. Это уход
                скорости внутри записи: ход/команда его не видит (это наклон
                прямой), а полное СКО молча считало бы шероховатостью. До 45%
                дисперсии главного числа на реальных прогонах.

  порядок 66    проекция остатка на 66-й порядок вала (6-я гармоника
                электрического периода при 11 парах полюсов) — главная
                периодическая помеха здорового мотора.

  Uq            среднее, размах и доля клампа берутся ИЗ ЗАГОЛОВКА прогона:
                их знает только прошивка. Среднее Uq — прокси нагрева.

САМОПРОВЕРКА ОБЯЗАТЕЛЬНА, пять пунктов, каждый может провалиться отдельно.
Два последних добавлены после проверки, которая нашла, что прежние три были
слабее, чем выглядели: все они строились на СТРОГО ЛИНЕЙНОМ тренде, поэтому
расхождение полного СКО с полосами в них не могло проявиться по построению, а
вдвое неверная нормировка полос проходила молча — её сверяли неравенствами, а
не точным ответом.
"""
import sys, math
import numpy as np

R = 57.2957795
F_PX = 1299.256      # фокус в пикселях при ширине кадра 1920
W_PX = 1920
# ГРАНИЦЫ ПОЛОС. Нижняя начинается с 0.33 Гц, а не с 0.15.
#
# Проверка на записи 12 с показала: в бинах 2 и 3 (0.167 и 0.25 Гц) сидит
# 57–88% энергии полосы 0.15..1, и при смене степени снимаемого тренда с 1 на 3
# полоса 0.15..1 плывёт на 20%, а полоса 0.33..1 совпадает до третьего знака.
# То есть ниже 0.33 Гц на такой длине меряется остаток снятия тренда, а не вал.
#
# ЦЕНА ЭТОГО РЕШЕНИЯ ЗАПИСАНА ЗДЕСЬ ЖЕ: на 0.05 рад/с зубцовая линия (порядок
# 66) приходится на 0.175 Гц и в полосу НЕ ПОПАДАЕТ — там нужна запись от 23 с.
# А на 0.35 и 0.50 рад/с она уходит на 1.23 и 1.75 Гц, то есть в ВЕРХНЮЮ полосу.
# Поэтому полосы сами по себе про зубцы не говорят, и рядом всегда печатается
# ПРОЕКЦИЯ НА ПОРЯДОК — она от скорости не зависит по построению.
LO = (0.33, 1.0)
HI = (1.0001, 20.0)   # граница не делится с нижней: иначе бин считался дважды
ORDER_COG = 66        # 6-я гармоника электрического периода при 11 парах полюсов
NEBW_HANN = 1.5


def load(path):
    """Читает дампы прошивки closed_loop_g431. Заголовок разбирается целиком:
    поля, которых нет, просто отсутствуют в словаре."""
    runs, cur = [], None
    for line in open(path, errors="replace"):
        line = line.strip()
        if line.startswith("#НАЧАЛО"):
            m = {}
            for kv in line.split()[1:]:
                if "=" in kv:
                    k, v = kv.split("=", 1)
                    m[k] = v
            cur = {"hdr": m, "data": []}
        elif line.startswith("#КОНЕЦ"):
            if cur and len(cur["data"]) > 100:
                runs.append(cur)
            cur = None
        elif cur is not None:
            try:
                cur["data"].append(float(line))
            except ValueError:
                pass
    return runs


def band_rms(res_rad, fs, lo, hi):
    """СКО в полосе, градусы. Остаток подаётся в РАДИАНАХ, тренд уже снят."""
    n = len(res_rad)
    sp = np.abs(np.fft.rfft(res_rad * np.hanning(n))) * 2.0 / (n * 0.5)
    f = np.fft.rfftfreq(n, 1.0 / fs)
    sel = (f >= lo) & (f <= hi)
    return math.sqrt(float((sp[sel] ** 2).sum()) / 2.0 / NEBW_HANN) * R


def order_amp(res_rad, ang_rad, order):
    """Проекция остатка на ПОРЯДОК ВАЛА по фактическому углу.

    Не зависит ни от разрешения по частоте, ни от того, в какую полосу линия
    попала на этой скорости, ни от дрейфа скорости внутри записи. Для сравнения
    конфигураций это надёжнее полос."""
    z = 2.0 * np.mean(np.asarray(res_rad) * np.exp(-1j * order * np.asarray(ang_rad)))
    return abs(z) * R


def measure(run):
    d = np.asarray(run["data"], float)
    hdr = run["hdr"]
    fs = int(hdr.get("fs", 200))
    w = float(hdr.get("w", 0.0))
    t = np.arange(len(d)) / fs
    k, b = np.polyfit(t, d, 1)
    res = d - (k * t + b)
    out = {
        "w": w,
        "порядок": order_amp(res, d, ORDER_COG),
        "n": len(d),
        "T": len(d) / fs,
        "ход": (abs(k) / abs(w)) if abs(w) > 1e-9 else float("nan"),
        "скo": res.std() * R,
        "низ": band_rms(res, fs, *LO),
        "верх": band_rms(res, fs, *HI),
        "режим": hdr.get("режим", "?"),
    }
    # ДРЕЙФ, КОТОРЫЙ НЕ ВИДЯТ НИ ПОЛОСЫ, НИ ход/команда.
    #
    # Проверка нашла, что нелинейный уход скорости внутри записи втекает в
    # полное СКО и составляет до 45% его дисперсии, а ход/команда его не видит
    # по определению (это наклон прямой). Печатаем его отдельным числом, чтобы
    # он был виден, а не молча объявлялся шероховатостью: это остаток полного
    # СКО сверх того, что объясняют обе полосы.
    expl = out["низ"] ** 2 + out["верх"] ** 2
    out["дрейф"] = math.sqrt(max(0.0, out["скo"] ** 2 - expl))
    out["кадр"] = out["скo"] / R * F_PX / W_PX
    for key, src in (("Uq_сред", "Uq_сред"), ("упор", "упор")):
        if src in hdr:
            try:
                out[key] = float(hdr[src].rstrip("%"))
            except ValueError:
                pass
    if "Uq" in hdr:
        out["Uq_разм"] = hdr["Uq"]
    return out


def report(paths):
    rows = []
    for p in paths:
        for r in load(p):
            m = measure(r)
            m["файл"] = p.split("/")[-1]
            rows.append(m)
    if not rows:
        print("нет прогонов")
        return 2
    print(f"{'режим':<12}{'рад/с':>7}{'ход/ком':>9}{'СКО,°':>8}"
          f"{'0.33-1':>8}{'1-20':>7}{'дрейф':>7}{'пор.66':>8}{'Uq_ср':>7}{'упор%':>7}")
    for m in rows:
        print(f"{m['режим']:<12}{m['w']:>7.2f}{m['ход']:>9.3f}{m['скo']:>8.3f}"
              f"{m['низ']:>8.3f}{m['верх']:>7.3f}{m['дрейф']:>7.3f}{m['порядок']:>8.4f}"
              f"{m.get('Uq_сред', float('nan')):>7.3f}{m.get('упор', float('nan')):>7.0f}")
    # свод по модулю скорости: обе стороны в одну строку
    print()
    speeds = sorted({round(abs(m["w"]), 3) for m in rows})
    print(f"{'|рад/с|':>8}{'сторон':>8}{'СКО,°':>8}{'0.33-1':>8}{'1-20':>7}"
          f"{'дрейф':>7}{'пор.66':>8}{'Uq_ср':>7}")
    for sp in speeds:
        sel = [m for m in rows if abs(round(abs(m["w"]), 3) - sp) < 1e-9]
        f = lambda k: np.mean([m[k] for m in sel if not math.isnan(m.get(k, float("nan")))])
        print(f"{sp:>8.2f}{len(sel):>8d}{f('скo'):>8.3f}{f('низ'):>8.3f}"
              f"{f('верх'):>7.3f}{f('дрейф'):>7.3f}{f('порядок'):>8.4f}{f('Uq_сред'):>7.3f}")
    return 0


def selftest():
    """Известный ответ: линия 0.7 Гц заданной амплитуды.

    Проверяются три вещи, и каждая может провалиться отдельно:
      1. линия попадает в НИЖНЮЮ полосу, а не в верхнюю;
      2. её амплитуда восстанавливается (СКО синусоиды = A/sqrt(2));
      3. на чистом ходе без ряби метрика читает около нуля.
    """
    fs, T = 200, 12.0
    t = np.arange(int(fs * T)) / fs
    A_deg, f0 = 0.30, 0.70
    ok = True

    y = (0.20 * t) + (A_deg / R) * np.sin(2 * np.pi * f0 * t)
    run = {"hdr": {"fs": str(fs), "w": "0.20", "режим": "тест"}, "data": list(y)}
    m = measure(run)
    want = A_deg / math.sqrt(2)
    print(f"1. линия {f0} Гц амплитудой {A_deg}°: СКО {m['скo']:.4f}° (ждём {want:.4f})")
    if abs(m["скo"] - want) > 0.05 * want:
        print("   ПРОВАЛ: амплитуда не восстановилась"); ok = False
    print(f"   низ {m['низ']:.4f}°  верх {m['верх']:.4f}°")
    if not (m["низ"] > 0.9 * want and m["верх"] < 0.1 * want):
        print("   ПРОВАЛ: линия попала не в ту полосу"); ok = False

    y2 = 0.20 * t
    m2 = measure({"hdr": {"fs": str(fs), "w": "0.20", "режим": "тест"}, "data": list(y2)})
    print(f"2. чистый ход без ряби: СКО {m2['скo']:.6f}° (ждём около нуля)")
    if m2["скo"] > 1e-6:
        print("   ПРОВАЛ: на гладком ходе метрика не нуль"); ok = False

    y3 = 0.10 * t + (A_deg / R) * np.sin(2 * np.pi * f0 * t)
    m3 = measure({"hdr": {"fs": str(fs), "w": "0.20", "режим": "тест"}, "data": list(y3)})
    print(f"3. ход вдвое ниже команды: ход/ком {m3['ход']:.3f} (ждём 0.5), "
          f"СКО {m3['скo']:.4f}° (ждём {want:.4f}, рассинхрон НЕ течёт в плавность)")
    if abs(m3["ход"] - 0.5) > 0.01 or abs(m3["скo"] - want) > 0.05 * want:
        print("   ПРОВАЛ: рассинхрон и плавность перепутаны"); ok = False

    # 4. КРИВОЙ ХОД БЕЗ ВСЯКОЙ РЯБИ. Три пункта выше построены на строго
    #    линейном тренде, поэтому расхождение полного СКО с полосами в них
    #    проявиться не может по построению. Парабола ловит именно это.
    y4 = 0.20 * t + 0.001 * t * t
    m4 = measure({"hdr": {"fs": str(fs), "w": "0.20", "режим": "тест"}, "data": list(y4)})
    print(f"4. кривой ход без ряби: СКО {m4['скo']:.4f}°  низ {m4['низ']:.4f}°  "
          f"дрейф {m4['дрейф']:.4f}° (дрейф обязан забрать почти всё)")
    if m4["дрейф"] < 0.7 * m4["скo"]:
        print("   ПРОВАЛ: уход скорости объявлен шероховатостью"); ok = False

    # 5. НОРМИРОВКА ПОЛОС СВЕРЯЕТСЯ С ТОЧНЫМ ОТВЕТОМ, а не неравенствами:
    #    прежняя редакция пропускала вдвое неверный множитель.
    A2, f2 = 0.40, 3.0
    y5 = 0.20 * t + (A2 / R) * np.sin(2 * np.pi * f2 * t)
    m5 = measure({"hdr": {"fs": str(fs), "w": "0.20", "режим": "тест"}, "data": list(y5)})
    want5 = A2 / math.sqrt(2)
    print(f"5. линия {f2} Гц в верхней полосе: верх {m5['верх']:.4f}° (ждём {want5:.4f})")
    if abs(m5["верх"] - want5) > 0.05 * want5:
        print("   ПРОВАЛ: нормировка полосы неверна"); ok = False

    print("\nСАМОПРОВЕРКА:", "всё сошлось" if ok else "ЕСТЬ ПРОВАЛЫ")
    return 0 if ok else 1


if __name__ == "__main__":
    args = sys.argv[1:]
    if not args or args[0] == "--самопроверка":
        sys.exit(selftest())
    sys.exit(report(args))
