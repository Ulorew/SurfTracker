#!/usr/bin/env python3
"""Смаз кадра: угловая СКОРОСТЬ вала выше порога, с ВЫЧЕТОМ шумового пола.

ЗАЧЕМ ОТДЕЛЬНО ОТ jerk_metric. Тот меряет ОТКЛОНЕНИЕ угла — это увод кадра:
композиция уехала, но картинка резкая. Смаз портит иначе: он размывает кадр
движением за время выдержки, и зависит не от отклонения, а от СКОРОСТИ.
Владелец назвал это прямо: запаздывание для съёмки лучше колебания.

ПОЧЕМУ НЕ ПРОСТО ДИФФЕРЕНЦИРОВАТЬ СПЕКТР. Первая редакция так и делала, и
мерила датчик, а не вал: белый шум угла при дифференцировании растёт как
частота, и на верхнем краю полосы забивает сигнал. Проверено прямо —
пол метрики вышел 10.6 град/с при рабочем числе 11.10, то есть превышение
1.05x. Все сравнения на ней были бессмысленны, а постоянство числа
(10.3-11.9 при любых настройках) выглядело как стабильность прибора.

ПОЭТОМУ ПОЛ ВЫЧИТАЕТСЯ СО ЗНАКОМ, как в jerk_metric: положительные и
отрицательные отклонения от пола гасят друг друга, остаётся когерентная
часть. Пол оценивается медианой мощности бинов полосы и делится на ln2
(медиана мощности рэлеевского шума занижена).
"""
import math
import numpy as np

NEBW_HANN = 1.5
BLUR_LO, BLUR_HI = 5.0, 60.0      # выше 60 Гц у нас только шум датчика


def blur(y_rad, fs, lo=BLUR_LO, hi=BLUR_HI):
    """-> (смаз град/с, пол град/с). y_rad — угол в радианах."""
    y = np.asarray(y_rad, float)
    n = len(y)
    x = np.arange(n)
    res = (y - np.polyval(np.polyfit(x, y, 1), x)) * 180.0 / math.pi
    w = np.hanning(n)
    sp = np.fft.rfft(res * w)
    f = np.fft.rfftfreq(n, 1.0 / fs)
    # мощность УГЛА на бин
    p = 2.0 * np.abs(sp) ** 2 / (w.sum() ** 2)
    sel = (f >= lo) & (f <= min(hi, fs / 2))
    if sel.sum() < 8:
        return float("nan"), float("nan")
    pa, fa = p[sel], f[sel]
    # Пол УГЛА: медиана мощности, поправленная на ln2. Он плоский (белый шум),
    # поэтому оценивается один раз по всей полосе.
    p_noise = float(np.median(pa)) / math.log(2.0)
    # В скорость переводим ПОСЛЕ вычета: (2*pi*f)^2 — коэффициент бина.
    k = (2.0 * math.pi * fa) ** 2
    coh = float(((pa - p_noise) * k).sum()) / NEBW_HANN
    пол = math.sqrt(float((p_noise * k).sum()) / NEBW_HANN)
    return math.sqrt(max(coh, 0.0)), пол


def selftest(n=4000, fs=200.0, sigma_deg=0.0294, trials=20, seed=0):
    """На ЧИСТОМ ШУМЕ метрика обязана вернуть около нуля.

    Прибор, не проверенный на отсутствии сигнала, меряет себя — это в проекте
    уже случалось трижды.
    """
    rng = np.random.default_rng(seed)
    s = sigma_deg * math.pi / 180.0
    out = [blur(rng.normal(0, s, n), fs)[0] for _ in range(trials)]
    return float(np.mean(out)), float(np.max(out))


def selftest_signal(amp_deg=0.05, f0=12.0, n=4000, fs=200.0, sigma_deg=0.0294, seed=1):
    """И обязана НАЙТИ заложенный сигнал поверх того же шума."""
    rng = np.random.default_rng(seed)
    t = np.arange(n) / fs
    y = (amp_deg * np.sin(2 * math.pi * f0 * t) + rng.normal(0, sigma_deg, n))
    ожид = 2 * math.pi * f0 * amp_deg / math.sqrt(2)      # град/с
    получ, _ = blur(y * math.pi / 180.0, fs)
    return ожид, получ


if __name__ == "__main__":
    ср, мак = selftest()
    print(f"на чистом шуме: среднее {ср:.4f}, максимум {мак:.4f} град/с")
    for amp, f0 in ((0.05, 12.0), (0.02, 8.0), (0.10, 25.0)):
        о, п = selftest_signal(amp, f0)
        print(f"синус {amp}° на {f0} Гц: заложено {о:.3f}, получено {п:.3f} "
              f"град/с  (x{п/о:.3f})")
