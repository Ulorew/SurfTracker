#!/usr/bin/env python3
"""Живой график энкодера прямо в терминале: то же, что Arduino Serial Plotter.

ЗАЧЕМ СВОЙ. Плоттер Arduino IDE рисует только окно графика и ничего не
считает. Для стенда важнее не картинка, а три числа рядом с ней:

  ШАГ КВАНТОВАНИЯ — минимальная ненулевая разница соседних отсчётов. Это
  прямая проверка, что тракт действительно 14-битный: у AS5048A по SPI шаг
  обязан быть 360/16384 = 0.0220°. Прежний тракт (PWM + micros() на STM32)
  давал 0.3930°, и это ловилось ровно так же — по интервалу между уровнями, а
  не по СКО (см. tools/link/encoder_noise.py). Если после перехода на SPI шаг
  остался прежним, значит читается не то, что думали.

  ЧАСТОТА ОТСЧЁТОВ — считается по приходу строк. Отличие от заявленных в
  прошивке 50 Гц означает, что канал или цикл не успевают.

  СЧЁТЧИКИ ОШИБОК — perr/ef приходят из прошивки нарастающим итогом. Здесь
  показывается ПРИРАЩЕНИЕ за сеанс: одиночный сбой на дюпонах иначе
  теряется среди бегущих строк.

ФОРМАТ ВХОДА — «label:value,label:value» от esp/as5048a_probe. Строки на '#'
это не данные, а диагностика прошивки; они идут в отдельную панель, а не в
график. Тот же поток без изменений читает и Arduino Serial Plotter.

РИСУЕТСЯ БРАЙЛЕМ (2x4 точки на знакоместо). Не украшение: на 80 колонках это
даёт 160 точек по горизонтали и 4-кратное разрешение по вертикали, чего
хватает, чтобы увидеть дрожание вала, а не только его вращение.

ШКАЛА ПО УМОЛЧАНИЮ АВТОМАТИЧЕСКАЯ, с минимальным размахом 0.5°. Фиксированные
0..360 прячут именно то, ради чего смотрят на неподвижный вал, — шум в сотые
доли градуса. Для вращения есть --full.

    tools/stand/enc_plot.py                    # порт найдётся сам
    tools/stand/enc_plot.py --поле mag         # смотреть амплитуду поля
    tools/stand/enc_plot.py --лог enc.csv      # писать сырое рядом с графиком
"""
import argparse, glob, os, re, shutil, sys, time
from collections import deque

try:
    import serial
except ImportError:
    sys.exit("нет pyserial: .venv/bin/pip install pyserial")

DOTS = [[0x01, 0x02, 0x04, 0x40],      # колонка 0, ряды сверху вниз
        [0x08, 0x10, 0x20, 0x80]]      # колонка 1


def найти_порт():
    """Порт ищется по by-id, а не по /dev/ttyUSB0: номер уезжает при каждом
    перетыкании, и слушать можно не ту плату."""
    for шаблон in ("/dev/serial/by-id/*CP2102*", "/dev/serial/by-id/*CH340*",
                   "/dev/ttyUSB*", "/dev/ttyACM*"):
        найдено = sorted(glob.glob(шаблон))
        if найдено:
            return найдено[0]
    return None


def брайль(точки, w, h):
    """точки: множество (x, y) в пикселях, y — вниз. Возвращает список строк."""
    сетка = [[0] * w for _ in range(h)]
    for x, y in точки:
        cx, cy = x // 2, y // 4
        if 0 <= cx < w and 0 <= cy < h:
            сетка[cy][cx] |= DOTS[x % 2][y % 4]
    return ["".join(chr(0x2800 + c) for c in ряд) for ряд in сетка]


def отрисовать(окно, поле, стат, диаг, ширина, высота, авто, лог_путь):
    w = max(20, ширина - 12)              # слева место под подписи оси
    h = max(4, высота)
    px, py = w * 2, h * 4

    значения = [з for _, з in окно]
    if not значения:
        return ["(ждём данных…)"]
    lo, hi = min(значения), max(значения)
    if not авто:
        lo, hi = 0.0, 360.0
    if hi - lo < 0.5:                     # минимальный размах: см. шапку
        центр = (hi + lo) / 2
        lo, hi = центр - 0.25, центр + 0.25

    t0, t1 = окно[0][0], окно[-1][0]
    span = max(1e-6, t1 - t0)
    точки = set()
    for t, з in окно:
        x = int((t - t0) / span * (px - 1))
        y = int((hi - з) / (hi - lo) * (py - 1))
        точки.add((x, max(0, min(py - 1, y))))

    строки = брайль(точки, w, h)
    вывод = []
    for i, s in enumerate(строки):
        доля = i / max(1, h - 1)
        метка = f"{hi - доля * (hi - lo):9.3f}" if i in (0, h // 2, h - 1) else " " * 9
        вывод.append(f"{метка} │{s}")
    вывод.append(" " * 9 + " └" + "─" * w)
    вывод.append(" " * 11 + f"{span:.1f} с окна, поле «{поле}»"
                 + ("" if авто else "  [шкала 0..360]")
                 + (f"  лог → {log_имя(лог_путь)}" if лог_путь else ""))
    return вывод


def log_имя(путь):
    return os.path.basename(путь) if путь else ""


def main():
    p = argparse.ArgumentParser(description="живой график энкодера в терминале")
    p.add_argument("--порт", default=None, help="по умолчанию ищется по by-id")
    p.add_argument("--скорость", type=int, default=115200)
    p.add_argument("--поле", default="angle", help="angle | mag | agc")
    p.add_argument("--окно", type=float, default=10.0, help="секунд на экране")
    p.add_argument("--лог", default=None, help="писать сырые отсчёты в CSV")
    p.add_argument("--full", action="store_true", help="шкала 0..360 вместо авто")
    a = p.parse_args()

    порт = a.порт or найти_порт()
    if not порт:
        sys.exit("плата не найдена: подключите ESP32 или укажите --порт")

    # Сброса по DTR/RTS здесь НЕТ намеренно. Открытие порта с подтяжкой этих
    # линий перезапускает ESP32, и каждый запуск графика ронял бы прогон,
    # который как раз идёт. Прошивка печатает свою шапку и так — при её
    # собственном старте.
    s = serial.Serial()
    s.port, s.baudrate, s.timeout = порт, a.скорость, 0.05
    s.dtr = False
    s.rts = False
    s.open()

    окно = deque()
    диаг = deque(maxlen=3)
    лог = open(a.лог, "w", buffering=1) if a.лог else None
    if лог:
        лог.write("t_host,t_board,angle,mag,agc,perr,ef\n")

    t_старт = time.time()
    n = 0
    шаги = set()
    прош = None
    perr0 = ef0 = None
    perr = ef = 0
    последняя = {}
    последний_кадр = 0.0
    буфер = b""

    print("\033[?25l", end="")            # курсор прячется: он мигает поверх графика
    try:
        while True:
            буфер += s.read(4096)
            *строки, буфер = буфер.split(b"\n")
            for сырая in строки:
                текст = сырая.decode("utf-8", "replace").strip()
                if not текст:
                    continue
                if текст.startswith("#"):
                    диаг.append(текст)
                    continue
                поля = dict(re.findall(r"([A-Za-z_]+):(-?[\d.]+)", текст))
                if a.поле not in поля:
                    continue
                try:
                    значение = float(поля[a.поле])
                except ValueError:
                    continue
                # ВРЕМЯ БЕРЁТСЯ У ПЛАТЫ, если она его шлёт (поле t, мс). Метка
                # приёма на хосте врёт: строки приходят пачками по мере
                # опустошения буфера USB, и соседние отсчёты слипаются в один
                # момент. Хостовое время остаётся только как запасное.
                t_хост = time.time()
                t = float(поля["t"]) / 1000.0 if "t" in поля else t_хост
                окно.append((t, значение))
                последняя = поля
                n += 1
                if лог:
                    лог.write("{:.6f},{:.6f},{},{},{},{},{}\n".format(
                        t_хост, t, поля.get("angle", ""), поля.get("mag", ""),
                        поля.get("agc", ""), поля.get("perr", ""), поля.get("ef", "")))
                # Шаг квантования: минимальная НЕНУЛЕВАЯ разница соседних
                # отсчётов. Нулевые пропускаются — вал часто стоит, и они
                # ничего не говорят о разрешении.
                if прош is not None:
                    d = abs(значение - прош)
                    if d > 1e-9:
                        шаги.add(round(d, 6))
                прош = значение
                if "perr" in поля:
                    v = int(float(поля["perr"]))
                    perr0 = v if perr0 is None else perr0
                    perr = v - perr0
                if "ef" in поля:
                    v = int(float(поля["ef"]))
                    ef0 = v if ef0 is None else ef0
                    ef = v - ef0

            граница = (окно[-1][0] if окно else time.time()) - a.окно
            while окно and окно[0][0] < граница:
                окно.popleft()

            # Перерисовка ~15 Гц, а не на каждую строку: при 50 Гц отсчётов
            # экран иначе мерцает и жрёт процессор на отрисовку, которой никто
            # не успевает увидеть.
            if time.time() - последний_кадр < 1 / 15:
                continue
            последний_кадр = time.time()

            cols, rows = shutil.get_terminal_size((100, 30))
            высота = max(4, rows - 12)
            картинка = отрисовать(окно, a.поле, None, list(диаг), cols, высота,
                                  not a.full, a.лог)

            зн = [з for _, з in окно]
            частота = ((len(окно) - 1) / max(1e-6, окно[-1][0] - окно[0][0])
                       if len(окно) > 1 else 0.0)
            шаг = min(шаги) if шаги else float("nan")
            размах = (max(зн) - min(зн)) if зн else float("nan")
            ско = 0.0
            if len(зн) > 1:
                m = sum(зн) / len(зн)
                ско = (sum((з - m) ** 2 for з in зн) / (len(зн) - 1)) ** 0.5

            панель = [
                f"порт {порт}  {a.скорость} бод   отсчётов {n}   {частота:6.1f} Гц",
                f"angle {последняя.get('angle','—'):>9}°   mag {последняя.get('mag','—'):>6}"
                f"   AGC {последняя.get('agc','—'):>4}",
                f"окно: размах {размах:8.4f}   СКО {ско:8.4f}"
                f"   шаг квантования {шаг:.4f}°  (14 бит = 0.0220°)",
                f"ошибки за сеанс: чётность {perr}   EF {ef}"
                + ("   ← провода/частота SPI" if (perr or ef) else "   — чисто"),
            ]
            хвост = list(диаг)[-3:]

            sys.stdout.write("\033[H\033[2J")
            sys.stdout.write("\n".join(картинка) + "\n\n")
            sys.stdout.write("\n".join(панель) + "\n")
            if хвост:
                sys.stdout.write("\n" + "\n".join(хвост) + "\n")
            sys.stdout.write("\nCtrl-C — выход\n")
            sys.stdout.flush()
    except KeyboardInterrupt:
        pass
    finally:
        print("\033[?25h", end="")        # курсор возвращается ВСЕГДА, даже по исключению
        s.close()
        if лог:
            лог.close()
            print(f"лог записан: {a.лог}")


if __name__ == "__main__":
    main()
