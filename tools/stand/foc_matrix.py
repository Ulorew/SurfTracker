#!/usr/bin/env python3
"""Матрица коэффициентов контура: отставание и дрожание на разных скоростях.

Гоняет стенд esp/foc_bench по сетке «набор коэффициентов x скорость», пишет
записи в формате стенда STM32 и считает по ним ДВА объявленных заранее числа:

  ОТСТАВАНИЕ = истинная скорость / уставка. Истинная берётся НАКЛОНОМ УГЛА, а
  не оценкой самого регулятора. Разница между этими двумя величинами уже
  стоила проекту одного разбора: контур держал свою оценку ровно на уставке,
  а вал шёл на 17% медленнее (см. шапку esp/foc_closed_probe). Меряя
  регулятор его же оценкой, эту ошибку увидеть невозможно в принципе.

  ДРОЖАНИЕ = СКО остатка угла в полосе 1..20 Гц за вычетом шумового пола,
  в градусах. Критерий и его реализация НЕ ПЕРЕПИСЫВАЮТСЯ ЗДЕСЬ, а берутся
  из tools/stand/jerk_metric.py: в августе в этой формуле нашли три ошибки
  сразу (клиппинг, заниженный пол, шумовая полоса окна), и вторая копия
  означала бы, что где-то живёт неисправленная.

СПЕКТР СЧИТАЕТСЯ В ДВУХ ШКАЛАХ, и в этом весь смысл сетки по скоростям:

  в ГЕРЦАХ            — резонанс стоит на месте, зубцовый момент уезжает;
  в ЦИКЛАХ НА ОБОРОТ  — наоборот, зубцы стоят, резонанс уезжает.

Пик, который не движется в циклах на оборот, привязан к механике вала
(зубцы, дисбаланс, огрехи магнита). Пик, стоящий в герцах, — свойство
контура или подвеса. По одной скорости их не различить вовсе.

    tools/stand/foc_matrix.py                  # полная сетка, ~9 минут
    tools/stand/foc_matrix.py --быстро         # 4x4, ~4 минуты
"""
import argparse, math, os, sys, time
import numpy as np

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from jerk_metric import jitter, BAND_LO, BAND_HI

try:
    import serial
except ImportError:
    sys.exit("нет pyserial: .venv/bin/pip install pyserial")

R = 57.2957795

# Сетка. P и I — то, что реально решает, догоняет ли контур уставку; Tf
# фиксирован: его влияние проверялось отдельно и он меняет не отставание, а
# шум оценки.
SETS_FULL = [{"P": p, "I": i, "Tf": 0.05, "PA": 6}
             for p in (0.2, 0.5, 1.0) for i in (5, 10, 20)]
SPEEDS_FULL = (0.1, 0.2, 0.4, 0.7, 1.0)

SETS_FAST = [{"P": p, "I": i, "Tf": 0.05, "PA": 6}
             for p in (0.2, 1.0) for i in (5, 20)]
SPEEDS_FAST = (0.2, 0.4, 0.7, 1.0)

# ПРОДОЛЖЕНИЕ СЕТКИ. Первый прогон дал дрожание, монотонно падающее по обоим
# параметрам до самого угла (P=1.0, I=20 -> 0.554°), при Uq 0.9 В из
# разрешённых 2.0. Оптимум за краем, и «лучший набор» первой сетки — это
# просто её граница, а не минимум. Продлевать надо там, где есть запас по
# напряжению: упрёмся в потолок — увидим это по Uq_max.
SETS_WIDE = [{"P": p, "I": i, "Tf": 0.05, "PA": 6}
             for p in (1.0, 2.0, 3.0) for i in (20, 40)]

# ДОБИВАНИЕ. Продолжение сетки зажало оптимум по P (2.0 лучше и 1.0, и 3.0:
# на 3.0 Uq упирается в потолок 2.00 В и дрожание подскакивает вчетверо), но
# I=40 снова оказалось КРАЕМ. Здесь I зажимается тоже, а заодно у победителя
# перебирается Tf.
#
# Tf проверяется только у победителя и намеренно: постоянная фильтра задаёт,
# сколько шума оценки скорости доедет до напряжения, и без большого P она почти
# ни на что не влияет. Мешать её в общую сетку значило бы вчетверо удлинить
# прогон ради параметра, который решает лишь в одном её углу.
#
# Скоростей три, а не пять: сравниваются НАБОРЫ между собой, и для этого важна
# не подробность спектра, а одинаковость условий. Спектры уже сняты полной
# сеткой.
SETS_TUNE = ([{"P": p, "I": i, "Tf": 0.05, "PA": 6}
              for p in (1.5, 2.0, 2.5) for i in (40, 80)]
             + [{"P": 2.0, "I": 40, "Tf": tf, "PA": 6} for tf in (0.01, 0.02, 0.1)])
SPEEDS_TUNE = (0.2, 0.4, 1.0)

# ПРЕДЕЛ ПО I. Победитель добивания (P=2.0, I=80) снова оказался краем, но
# рядом обрыв: P=2.5 с I=80 разваливается (Uq в потолке, отставание 0.94).
# Значит граница устойчивости близко, и продлевать надо осторожно.
#
# ПОВТОР ПОБЕДИТЕЛЯ включён в сетку намеренно, первой и последней ячейкой.
# Без цены повторения нельзя сказать, реальна ли разница 0.163 против 0.193 —
# а весь выбор набора состоит из таких сравнений. Заодно повтор в конце ловит
# уход от нагрева: если к концу прогона та же ячейка мерится хуже, дело не в
# коэффициентах.
SETS_LIMIT = [{"P": 2.0, "I": i, "Tf": 0.05, "PA": 6} for i in (80, 120, 160, 80)]


def найти_порт():
    import glob
    for шаблон in ("/dev/serial/by-id/*CP2102*", "/dev/ttyUSB*"):
        f = sorted(glob.glob(шаблон))
        if f:
            return f[0]
    return None


def ждать(s, признак, таймаут=20.0):
    """Читает строки до появления признака. Возвращает всё прочитанное."""
    из = []
    край = time.time() + таймаут
    while time.time() < край:
        b = s.readline()
        if not b:
            continue
        t = b.decode("utf-8", "replace").rstrip()
        из.append(t)
        if признак in t:
            return из
    raise TimeoutError(f"не дождались «{признак}»; последнее: {из[-3:]}")


def прогон(s, v, t_ms, settle_ms, путь):
    """Одна ячейка. Возвращает (углы в радианах, fs, хвост #КОНЕЦ)."""
    s.write(f"RUN v={v} t={t_ms} s={settle_ms}\n".encode())
    строки = ждать(s, "#НАЧАЛО", таймаут=settle_ms / 1000 + 15)
    шапка = [x for x in строки if x.startswith("#НАЧАЛО")][-1]
    fs = int(dict(kv.split("=") for kv in шапка.split()[1:])["fs"])
    данные, конец = [], None
    край = time.time() + t_ms / 1000 + 20
    while time.time() < край:
        b = s.readline()
        if not b:
            continue
        t = b.decode("utf-8", "replace").strip()
        if t.startswith("#КОНЕЦ"):
            конец = t
            break
        try:
            данные.append(float(t))
        except ValueError:
            pass
    if конец is None:
        raise TimeoutError("запись не закрылась #КОНЕЦ")
    with open(путь, "w") as f:
        f.write(шапка + "\n")
        f.write("\n".join(f"{x:.6f}" for x in данные) + "\n")
        f.write(конец + "\n")
    return np.array(данные), fs, конец


def пики(y, fs, v_true, сколько=3):
    """Сильнейшие пики остатка в полосе, в герцах И в циклах на оборот."""
    n = len(y)
    x = np.arange(n)
    a, b = np.polyfit(x, y, 1)
    res = y - (a * x + b)
    sp = np.abs(np.fft.rfft(res * np.hanning(n)))
    freq = np.fft.rfftfreq(n, 1.0 / fs)
    sel = (freq >= BAND_LO) & (freq <= BAND_HI)
    f, amp = freq[sel], sp[sel]
    if len(f) == 0:
        return []
    idx = np.argsort(amp)[::-1][:сколько]
    об_в_сек = abs(v_true) / (2 * math.pi)
    return [(float(f[i]), float(f[i] / об_в_сек) if об_в_сек > 1e-6 else float("nan"))
            for i in sorted(idx, key=lambda k: -amp[k])]


def main():
    p = argparse.ArgumentParser(description="матрица коэффициентов контура")
    p.add_argument("--порт", default=None)
    p.add_argument("--быстро", action="store_true")
    p.add_argument("--шире", action="store_true", help="продолжение сетки за P=1 I=20")
    p.add_argument("--добить", action="store_true", help="зажать I и перебрать Tf")
    p.add_argument("--предел", action="store_true", help="предел по I + повтор победителя")
    p.add_argument("--замер", type=int, default=8000, help="мс записи на ячейку")
    p.add_argument("--разгон", type=int, default=2000, help="мс до начала записи")
    p.add_argument("--каталог", default=None)
    a = p.parse_args()

    if a.предел:
        наборы, скорости = SETS_LIMIT, SPEEDS_TUNE
    elif a.добить:
        наборы, скорости = SETS_TUNE, SPEEDS_TUNE
    elif a.шире:
        наборы, скорости = SETS_WIDE, SPEEDS_FULL
    elif a.быстро:
        наборы, скорости = SETS_FAST, SPEEDS_FAST
    else:
        наборы, скорости = SETS_FULL, SPEEDS_FULL
    порт = a.порт or найти_порт()
    if not порт:
        sys.exit("плата не найдена")

    кат = a.каталог or time.strftime("runs/foc_matrix_%Y-%m-%d_%H%M")
    os.makedirs(кат, exist_ok=True)

    s = serial.Serial()
    s.port, s.baudrate, s.timeout = порт, 115200, 1.0
    s.dtr = False
    s.rts = False
    s.open()
    # Сброс подаётся ОДИН раз на всю матрицу: выравнивание initFOC гуляет от
    # запуска к запуску (zero_electric_angle 3.778..3.826), и перезапуск на
    # каждой ячейке подмешал бы этот разброс к разбросу коэффициентов.
    s.dtr = False; s.rts = True; time.sleep(0.2); s.rts = False
    шапка = ждать(s, "# ГОТОВ", таймаут=30)
    for x in шапка:
        if "initFOC" in x or "ГОТОВ" in x:
            print(x)

    всего = len(наборы) * len(скорости)
    сек = всего * (a.замер + a.разгон + 900) / 1000
    print(f"\nячеек {всего}, примерно {сек/60:.1f} минут. Вал крутится всё это время.")
    print(f"записи -> {кат}\n")

    итоги = []
    try:
        for ин, набор in enumerate(наборы):
            метка = f"#{ин}"
            s.write(("SET " + " ".join(f"{k}={v}" for k, v in набор.items()) + "\n").encode())
            ждать(s, "# STATE")
            for v in скорости:
                имя = f"n{ин}_P{набор['P']}_I{набор['I']}_Tf{набор['Tf']}_v{v}".replace(".", "p")
                путь = os.path.join(кат, имя + ".txt")
                y, fs, конец = прогон(s, v, a.замер, a.разгон, путь)
                дрож, пол, пик_f, v_ист = jitter(y, fs)
                хв = dict(kv.split("=") for kv in конец.split()[1:])
                отн = v_ист / v if v else float("nan")
                итоги.append({"ин": ин, "P": набор["P"], "I": набор["I"],
                              "Tf": набор["Tf"], "v": v,
                              "v_ист": v_ист, "отн": отн, "дрож": дрож, "пол": пол,
                              "uq": float(хв.get("uq_avg", 0)),
                              "uq_max": float(хв.get("uq_max", 0)),
                              "пики": пики(y, fs, v_ист)})
                print(f"  P={набор['P']:<4} I={набор['I']:<4} v={v:<4} | "
                      f"истинная {v_ист:+.4f} отн {отн:.3f} | "
                      f"дрожание {дрож:.3f}° (пол {пол:.3f}) | "
                      f"Uq {хв.get('uq_avg','?')}/{хв.get('uq_max','?')} В")
    finally:
        # Поле снимается ВСЕГДА: и по Ctrl-C, и по исключению. Забытый под
        # напряжением вал держит постоянный ток в одной паре обмоток.
        s.write(b"OFF\n"); s.flush(); time.sleep(0.3); s.close()
        print("\nполе снято")

    if not итоги:
        return

    # ---- сводка по коэффициентам ----
    print("\n=== ПО НАБОРАМ (усреднено по скоростям) ===")
    print(f"{'P':>5} {'I':>5} | {'отставание':>11} | {'дрожание, °':>12} | {'Uq макс':>8}")
    ключи = sorted({(r["ин"], r["P"], r["I"], r["Tf"]) for r in итоги})
    сводка = []
    for ин, P, I, Tf in ключи:
        г = [r for r in итоги if r["ин"] == ин]
        отн = float(np.mean([r["отн"] for r in г]))
        дрож = float(np.mean([r["дрож"] for r in г]))
        uq = max(r["uq_max"] for r in г)
        сводка.append((P, I, отн, дрож, uq, Tf, ин))
        print(f"{P:>5} {I:>5} | {отн:>11.3f} | {дрож:>12.3f} | {uq:>8.2f}   Tf={Tf}")

    # Лучший — по дрожанию среди тех, кто НЕ отстаёт. Порядок критериев
    # объявлен здесь и не меняется по результату: сначала догоняет уставку,
    # потом уже ровность. Набор, который тише всех, но не доезжает до
    # скорости, стендy не годится.
    годные = [c for c in сводка if 0.97 <= c[2] <= 1.03]
    if годные:
        л = min(годные, key=lambda c: c[3])
        print(f"\nЛУЧШИЙ: P={л[0]} I={л[1]} Tf={л[5]} — отставание {л[2]:.3f}, "
              f"дрожание {л[3]:.3f}°, Uq макс {л[4]:.2f} из 2.0")
        if л[4] > 1.8:
            print("  ВНИМАНИЕ: Uq у потолка — набор ограничен напряжением, а не найден")
    else:
        print("\nни один набор не удержал отставание в 3%: смотреть Uq и потолок")

    # ---- спектры: зубцы или резонанс ----
    print("\n=== СПЕКТР: где стоят пики ===")
    print("пик, неподвижный в ЦИКЛАХ НА ОБОРОТ -> механика вала (зубцы, магнит)")
    print("пик, неподвижный в ГЕРЦАХ           -> контур или подвес\n")
    ин0 = л[6] if годные else ключи[0][0]
    print(f"(набор #{ин0})")
    print(f"{'v, рад/с':>9} | {'пик1 Гц':>8} {'ц/об':>8} | {'пик2 Гц':>8} {'ц/об':>8}")
    for r in [x for x in итоги if x["ин"] == ин0]:
        ч = r["пики"]
        s1 = f"{ч[0][0]:>8.2f} {ч[0][1]:>8.1f}" if len(ч) > 0 else " " * 17
        s2 = f"{ч[1][0]:>8.2f} {ч[1][1]:>8.1f}" if len(ч) > 1 else ""
        print(f"{r['v']:>9.2f} | {s1} | {s2}")

    import csv
    сп = os.path.join(кат, "сводка.csv")
    with open(сп, "w", newline="") as f:
        w = csv.writer(f)
        w.writerow(["P", "I", "Tf", "v_cmd", "v_true", "ratio", "jitter_deg", "floor_deg",
                    "uq_avg", "uq_max", "peak1_hz", "peak1_cpr"])
        for r in итоги:
            п = r["пики"][0] if r["пики"] else (float("nan"), float("nan"))
            w.writerow([r["P"], r["I"], r["Tf"], r["v"], f"{r['v_ист']:.5f}", f"{r['отн']:.4f}",
                        f"{r['дрож']:.4f}", f"{r['пол']:.4f}", r["uq"], r["uq_max"],
                        f"{п[0]:.3f}", f"{п[1]:.2f}"])
    print(f"\nсводка: {сп}")


if __name__ == "__main__":
    main()
