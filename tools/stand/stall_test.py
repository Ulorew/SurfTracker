#!/usr/bin/env python3
"""Срывается ли контур на рабочей скорости. Пишет в runs/.

ЗАЧЕМ. 18 сентября видеозапись на P=1.0 показала пять секунд полной
остановки посреди 18-секундного прогона: панорама в кадре падала до нуля,
потом ход возобновлялся. Дублей кадров и сбоев тайминга в файле нет
(шаг 33.6+-0.4 мс, mpdecimate молчит), значит стоял вал, а не запись.
Один прогон - не доказательство, поэтому здесь прямая проверка на стенде.

ЧТО СЧИТАЕТСЯ СРЫВОМ. Окно 0.5 с, в котором средняя скорость вала ниже
20% заданной. Порог низкий намеренно: нас интересует остановка, а не
неровность хода - её меряют другие инструменты.

КОНФИГ - ГЕЙТ, А НЕ ПЕЧАТЬ. Плата отвечает STATE, и расхождение с тем, что
мы собирались мерить, отменяет прогон. Печать конфига этого не ловит:
её никто не читает.
"""
import argparse, math, os, re, sys, time
import numpy as np

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from tf_met_sweep import открыть, команда, прогон

ОКНО_С = 0.5
ДОЛЯ = 0.20          # ниже этой доли заданной скорости - стоим


def срывы(ys, fs, v):
    """-> (доля времени в срыве, число срывов, самый долгий срыв в с, ряд скорости)."""
    y = np.array(ys, dtype=float)
    w = max(4, int(round(ОКНО_С * fs)))
    if len(y) < 3 * w:
        return None
    # скорость как наклон в скользящем окне: разность концов окна
    v_лок = (y[w:] - y[:-w]) / (w / fs)
    стоим = np.abs(v_лок) < ДОЛЯ * abs(v)
    доля = float(стоим.mean())
    # группы подряд идущих
    гр, длины = 0, []
    i = 0
    while i < len(стоим):
        if стоим[i]:
            j = i
            while j < len(стоим) and стоим[j]:
                j += 1
            длины.append((j - i) / fs); гр += 1; i = j
        else:
            i += 1
    return доля, гр, (max(длины) if длины else 0.0), v_лок


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--скорость", type=float, default=0.11)
    ap.add_argument("--секунд", type=float, default=20.0)
    ap.add_argument("--повторов", type=int, default=3)
    ap.add_argument("--каталог", default=None)
    a = ap.parse_args()

    настройки = [
        ("P40_cog1", "P=4.0 I=5 D=0 Tf=0.01 MET=0.002 FFA=0 FFB=0 COGK=1",
         [("P", 4.0), ("Tf", 0.01), ("COGK", 1.0)]),
        ("P10_cog1", "P=1.0 I=5 D=0 Tf=0.01 MET=0.002 FFA=0 FFB=0 COGK=1",
         [("P", 1.0), ("Tf", 0.01), ("COGK", 1.0)]),
        ("P40_cog0", "P=4.0 I=5 D=0 Tf=0.01 MET=0.002 FFA=0 FFB=0 COGK=0",
         [("P", 4.0), ("Tf", 0.01), ("COGK", 0.0)]),
        ("P10_cog0", "P=1.0 I=5 D=0 Tf=0.01 MET=0.002 FFA=0 FFB=0 COGK=0",
         [("P", 1.0), ("Tf", 0.01), ("COGK", 0.0)]),
    ]
    кат = a.каталог or f"runs/stall_{time.strftime('%Y-%m-%d_%H%M')}"
    os.makedirs(кат, exist_ok=True)

    print(f"СРЫВ НА РАБОЧЕЙ СКОРОСТИ v={a.скорость} рад/с -> {кат}")
    print(f"окно {ОКНО_С} с, порог {ДОЛЯ:.0%} от заданной; {a.повторов} повтора, вперемешку")
    print("вал не трогать\n")

    s = открыть()
    итог = {имя: [] for имя, _, _ in настройки}
    try:
        for п in range(a.повторов):
            for имя, конф, сверка in настройки:
                команда(s, f"SET {конф}", 0.8)
                ответ = команда(s, "STATE", 0.8)
                плохо = False
                for поле, ждём in сверка:
                    m = re.search(rf"{поле}=([\d.]+)", ответ)
                    if not m or abs(float(m.group(1)) - ждём) > 1e-3:
                        print(f"  ОТКАЗ {имя}: плата отвечает {поле}="
                              f"{m.group(1) if m else '?'}, нужно {ждём}")
                        плохо = True
                if плохо:
                    continue
                ys, fs = прогон(s, a.скорость, int(a.секунд * 1000), 2000)
                r = срывы(ys, fs, a.скорость)
                if r is None:
                    print(f"  {имя} повтор {п}: ряд короткий ({len(ys)}), пропуск")
                    continue
                доля, гр, макс, v_лок = r
                np.save(os.path.join(кат, f"{имя}_{п}.npy"), np.array(ys))
                ср = float(np.mean(np.abs(v_лок)))
                итог[имя].append((доля, гр, макс, ср))
                print(f"  {имя} повтор {п}: стоим {доля:6.1%} времени, "
                      f"{гр} остановок, дольше всего {макс:.2f} с, "
                      f"средняя скорость {ср:.4f} рад/с ({ср/a.скорость:.0%} от заданной)")
                time.sleep(2.0)
    finally:
        команда(s, "OFF", 0.5); s.close(); print("\nполе снято")

    print("\nСВОД")
    for имя, _, _ in настройки:
        v = итог[имя]
        if not v:
            print(f"  {имя}: нет годных прогонов"); continue
        д = np.array([x[0] for x in v]); м = np.array([x[2] for x in v])
        с = np.array([x[3] for x in v])
        print(f"  {имя}: в срыве {д.mean():.1%} времени (разброс {д.min():.1%}..{д.max():.1%}), "
              f"самая долгая остановка {м.max():.2f} с, "
              f"держит {с.mean()/a.скорость:.0%} заданной скорости")


if __name__ == "__main__":
    main()
