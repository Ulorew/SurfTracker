#!/usr/bin/env python3
"""Сравнение трёх режимов из ОДНОГО прогона closed_loop_g431.

    tools/stand/loop_compare.py runs/closed_first.txt

ПРАВИЛО РЕШЕНИЯ ОБЪЯВЛЕНО ДО ПРОГОНА (23.08.2026). Записано здесь, а не в
голове, потому что «улучшение» без заранее названного порога всегда находится:
любые два числа отличаются.

  ВЫИГРЫШ ЗАСЧИТЫВАЕТСЯ, если выполнено ВСЁ:

    1. ДВЕ проверки прибора, а не одна:
       1а. На отрезке «пол» (мотор выключен, вал стоит, груз висит) метрика
           обязана читаться около нуля — не больше 20% от разомкнутого. Это
           единственная проверка, которая ловит НАВОДКУ: если что-то
           когерентное затекает в тракт помимо вала, оно видно здесь.
       1б. Разомкнутый замер обязан быть хотя бы вдвое выше ШУМОВОГО ПОЛА
           прибора. Если базовая линия сама лежит внутри шума, улучшать
           нечего и сравнивать нечего: нижняя половина прежней лестницы на
           72% мощности была полом, и это приняли за дрожание вала.

       ПОЧЕМУ НЕ «пол вдвое ниже рабочих», как было написано сперва: у отрезка
       «пол» когерентная метрика близка к нулю ПО ПОСТРОЕНИЮ (она и обязана
       быть нулём на отсутствии сигнала), поэтому такое условие выполнялось бы
       почти всегда и не проверяло бы ничего.
    2. Замкнутый ниже разомкнутого НЕ МЕНЕЕ ЧЕМ НА 20% по СКО. Пять процентов
       не стоят дня настройки: владелец сказал «лучшее — враг хорошего».
    3. Разница превышает разброс ВНУТРИ прогонов: каждая запись режется на
       четыре отрезка по 3 с, метрика считается по каждому, и разница средних
       обязана быть больше 2 сигм объединённого разброса. Без этого пункта мы
       приняли бы за эффект обычное гуляние одного замера.
    4. Синхронизм не потерян: факт/команда в обоих режимах в пределах
       0.9..1.1. Замкнутый контур, отставший по скорости, «плавнее» тривиально.

  ОТДЕЛЬНО И ОБЯЗАТЕЛЬНО СМОТРИМ ПОЛОСУ 5.5..6.5 Гц. Это названная мишень —
  резонанс подвеса, добротность ~5, подтверждённый отношением спектров
  с грузом/без груза x5.5..8.4 при контроле «груз висит, вал стоит» ровно
  x1.00. Демпфирование обязано сесть ИМЕННО ТУДА. Если общая метрика упала, а
  горб на месте — упало что-то другое, и объяснение придётся искать заново.

МЕТРИКА ИМПОРТИРУЕТСЯ, А НЕ ПОВТОРЯЕТСЯ. jitter() берётся из jerk_metric.py:
две копии одной формулы разъезжаются молча, и мы это уже проходили с наклоном
моста, жившим в трёх местах.
"""
import sys, os, math
import numpy as np

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from jerk_metric import jitter, R, BAND_LO, BAND_HI

RES_LO, RES_HI = 5.5, 6.5      # мишень: резонанс подвеса
N_SEG = 4                      # отрезков на режим для оценки разброса
MIN_GAIN = 0.20                # порог 2 правила
SYNC_LO, SYNC_HI = 0.9, 1.1    # порог 4 правила


def load(path):
    """Читает дамп скетча. Режим берётся из заголовка, а не угадывается.

    ПОЧЕМУ НЕ jerk_metric.load(): та ключует прогоны по (напряжение, скорость),
    а здесь разомкнутый и замкнутый идут на ОДНИХ И ТЕХ ЖЕ напряжении и
    скорости — в том и смысл сравнения. Ключ по (В, рад/с) затёр бы один
    режим другим и показал бы один замер дважды.
    """
    runs, cur = [], None
    for line in open(path, errors="replace"):
        line = line.strip()
        if line.startswith("#НАЧАЛО"):
            m = {}
            for kv in line.split()[1:]:
                if "=" in kv:
                    k, v = kv.split("=", 1)
                    m[k] = v
            cur = {"w": float(m["w"]), "volts": float(m["volts"]),
                   "fs": int(m["fs"]), "mode": m.get("режим", "?"), "data": []}
        elif line.startswith("#КОНЕЦ"):
            if cur and len(cur["data"]) > 100:
                runs.append(cur)
            cur = None
        elif cur is not None:
            try:
                cur["data"].append(float(line))
            except ValueError:
                pass
    return runs


def band_rms(y, fs, lo, hi):
    """СКО в узкой полосе за вычетом пола, градусы. Тем же способом, что
    jitter(), но на своей полосе — чтобы мишень мерилась так же, как всё."""
    y = np.asarray(y, float)
    n = len(y)
    x = np.arange(n)
    a, b = np.polyfit(x, y, 1)
    res = y - (a * x + b)
    sp = np.fft.rfft(res * np.hanning(n))
    amp = 2.0 * np.abs(sp) / (n * 0.5)
    freq = np.fft.rfftfreq(n, 1.0 / fs)
    wide = (freq >= BAND_LO) & (freq <= BAND_HI)
    p_noise = float(np.median(amp[wide] ** 2)) / math.log(2.0)
    sel = (freq >= lo) & (freq <= hi)
    coh = float((amp[sel] ** 2 - p_noise).sum()) / 1.5
    return math.sqrt(max(0.0, coh) / 2.0) * R


def segments(r):
    """Метрика по N_SEG непересекающимся отрезкам -> оценка разброса ВНУТРИ
    прогона. Повторных включений у нас нет, а без разброса любая разница
    выглядит значимой."""
    d = np.asarray(r["data"], float)
    k = len(d) // N_SEG
    return np.array([jitter(d[i * k:(i + 1) * k], r["fs"])[0]
                     for i in range(N_SEG)])


def main(path):
    runs = {r["mode"]: r for r in load(path)}
    need = ["пол", "разомкнутый", "замкнутый"]
    missing = [m for m in need if m not in runs]
    if missing:
        print("НЕТ РЕЖИМОВ:", ", ".join(missing))
        print("Сравнивать нечего: правило требует все три из ОДНОГО прогона.")
        return 2

    print(f"полоса метрики {BAND_LO}..{BAND_HI} Гц, мишень {RES_LO}..{RES_HI} Гц, "
          f"отрезков на режим {N_SEG}\n")
    print(f"{'режим':<14}{'дрожание':>10}{'пол':>9}{'мишень':>9}"
          f"{'пик,Гц':>9}{'факт/ком':>10}")
    st = {}
    for m in need:
        r = runs[m]
        j, fl, pf, sp = jitter(r["data"], r["fs"])
        tgt = band_rms(r["data"], r["fs"], RES_LO, RES_HI)
        seg = segments(r)
        st[m] = dict(j=j, fl=fl, pf=pf, sp=sp, tgt=tgt,
                     mean=seg.mean(), sd=seg.std(ddof=1))
        ratio = (sp / r["w"]) if r["w"] > 1e-9 else float("nan")
        print(f"{m:<14}{j:>10.4f}{fl:>9.4f}{tgt:>9.4f}{pf:>9.2f}{ratio:>10.3f}")
    print()
    for m in need:
        s = st[m]
        print(f"  {m:<14} по отрезкам: {s['mean']:.4f} ± {s['sd']:.4f}°")

    o, c, f = st["разомкнутый"], st["замкнутый"], st["пол"]
    d = o["mean"] - c["mean"]
    sigma = math.hypot(o["sd"], c["sd"])
    gain = d / o["mean"] if o["mean"] > 0 else 0.0

    print("\nПРОВЕРКА ПО ОБЪЯВЛЕННОМУ ПРАВИЛУ")
    p1a = f["j"] <= 0.2 * o["j"]
    print(f"  1а. на полу метрика ~нуль:      {'да' if p1a else 'НЕТ'} "
          f"(пол читает {f['j']:.4f}, порог {0.2 * o['j']:.4f})")
    p1b = o["j"] >= 2.0 * f["fl"]
    print(f"  1б. база выше шума прибора:     {'да' if p1b else 'НЕТ'} "
          f"(база {o['j']:.4f}, шум прибора {f['fl']:.4f})")
    p1 = p1a and p1b
    p2 = gain >= MIN_GAIN
    print(f"  2. выигрыш >= {MIN_GAIN:.0%}:              "
          f"{'да' if p2 else 'НЕТ'} ({gain:+.1%})")
    p3 = d > 2 * sigma
    print(f"  3. больше разброса (2 сигмы):   {'да' if p3 else 'НЕТ'} "
          f"(разница {d:+.4f}°, 2 сигмы {2*sigma:.4f}°)")
    rs = [st[m]["sp"] / runs[m]["w"] for m in ("разомкнутый", "замкнутый")]
    p4 = all(SYNC_LO <= x <= SYNC_HI for x in rs)
    print(f"  4. синхронизм цел:              {'да' if p4 else 'НЕТ'} "
          f"({rs[0]:.3f} и {rs[1]:.3f})")

    tg = (o["tgt"] - c["tgt"]) / o["tgt"] if o["tgt"] > 0 else 0.0
    print(f"\n  мишень {RES_LO}..{RES_HI} Гц: {o['tgt']:.4f}° -> {c['tgt']:.4f}° "
          f"({tg:+.1%})")

    print()
    if p1 and p2 and p3 and p4:
        print("ВЫВОД: замыкание даёт выигрыш по объявленному правилу.")
        if tg < 0.10:
            print("  ОГОВОРКА: общая метрика упала, а горб резонанса — нет.")
            print("  Значит упало не то, ради чего замыкали, и объяснение надо")
            print("  искать заново, а не записывать успех.")
        return 0
    print("ВЫВОД: выигрыш НЕ засчитан. Разомкнутый контур остаётся.")
    if not p1a:
        print("  Первым делом пункт 1а: на неподвижном вале прибор видит")
        print("  когерентный сигнал. Это наводка, и все остальные числа —")
        print("  измерение наводки, а не вала.")
    elif not p1b:
        print("  Первым делом пункт 1б: базовая линия внутри шума прибора.")
        print("  Улучшать нечего, и разница режимов тут неотличима от нуля.")
    return 1


if __name__ == "__main__":
    sys.exit(main(sys.argv[1] if len(sys.argv) > 1 else "runs/closed_first.txt"))
