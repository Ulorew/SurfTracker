#!/bin/bash
# Снять поток с VCP платы в файл, до маркера #ВСЁ.
#
#   tools/stand/grab_vcp.sh runs/closed_first.txt [/dev/ttyACM0]
#
# ЧИСТЫМ BASH, А НЕ PYSERIAL. pyserial в системном питоне нет, а ставить его
# ради чтения строкового потока — лишняя зависимость там, где хватает stty.
#
# ЧТО ЗДЕСЬ ЛЕГКО СЛОМАТЬ И ПОЧЕМУ ЭТО ВАЖНО:
#
#  1. БЕЗ `raw -echo` терминальная дисциплина превращает \n в \r\n, глотает
#     символы по Ctrl-кодам и ЭХОМ ШЛЁТ ПРИНЯТОЕ ОБРАТНО В ПЛАТУ. Последнее
#     хуже всего: плата в это время крутит вал.
#  2. БЕЗ `-hupcl` закрытие файла дёргает DTR и ПЕРЕЗАГРУЖАЕТ плату — то есть
#     попытка перечитать хвост убивает прогон.
#  3. Порт открывается ДО прошивки: первые строки (шапка, состояние тракта,
#     результат выравнивания) идут в первые же миллисекунды, и опоздавший
#     захват теряет ровно ту часть, ради которой всё печатается.
set -u
OUT="${1:?куда писать}"
PORT="${2:-/dev/ttyACM0}"
[ -e "$PORT" ] || { echo "нет порта $PORT"; exit 1; }
stty -F "$PORT" 115200 raw -echo -hupcl
echo "слушаю $PORT -> $OUT   (Ctrl-C чтобы прервать)"
: > "$OUT"
# СТАРТОВЫЙ БАЙТ, И НЕ ОДИН РАЗ. Скетч closed_loop_g431 намеренно не двигает
# вал, пока не получит его: прошивка сбрасывает плату, и без этого шапка с
# проверкой тракта ушла бы в пустоту до открытия порта.
#
# ПОВТОРНО, ПОТОМУ ЧТО ОДНОКРАТНАЯ ОТПРАВКА УЖЕ ПРОПАЛА. Между сбросом платы и
# готовностью её приёмника есть окно, и байт, посланный в него, теряется молча:
# плата ждёт вечно, а захват выглядит зависшим. Шлём раз в секунду первые 15
# секунд; лишние байты скетч сбрасывает сам, а скетчам, которые байта не ждут,
# он безразличен.
( for _ in $(seq 15); do printf 'S' > "$PORT" 2>/dev/null; sleep 1; done ) &
SENDER=$!
trap 'kill $SENDER 2>/dev/null' EXIT
while IFS= read -r line; do
    printf '%s\n' "$line" >> "$OUT"
    # ВИДНЫ ВСЕ НЕЧИСЛОВЫЕ СТРОКИ, а не только начинающиеся с #: отладочный
    # вывод SimpleFOC («sensor dir: CW», «PP check: est. pp») идёт без
    # префикса, и именно по нему видно, был ли замер выравнивания уверенным.
    case "$line" in
        ''|*[!0-9.eE+-]*) printf '%s\n' "$line" ;;
    esac
    case "$line" in
        '#ВСЁ'*) break ;;
    esac
done < "$PORT"
echo "снято: $(wc -l < "$OUT") строк -> $OUT"
