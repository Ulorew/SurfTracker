#!/bin/bash
# Гонять опыты на плате БЕЗ ПЕРЕПРОШИВКИ.
#
#   tools/stand/stand.sh runs/out.txt "?" "V2.0" "O0.20" "C0.20"
#
# ЗАЧЕМ. Прежде каждый вопрос к железу стоил сборки, заливки и сброса — около
# сорока секунд, и за два часа разбора это съело больше времени, чем сами
# замеры. Прошивка closed_loop_g431 теперь принимает команды строкой, а этот
# скрипт их шлёт и собирает ответы в один файл.
#
# ОТБИВКА, А НЕ ТАЙМАУТ. Каждая команда кончается строкой #ГОТОВ, и чтение
# ждёт именно её. Таймаут, подобранный под короткую команду, обрезал бы
# длинную; подобранный под длинную — простаивал бы на каждой короткой.
set -u
OUT="${1:?куда писать}"; shift
PORT="${PORT:-/dev/ttyACM0}"
[ -e "$PORT" ] || { echo "нет порта $PORT"; exit 1; }
stty -F "$PORT" 115200 raw -echo -hupcl
exec 3<>"$PORT"
: > "$OUT"
# ХВОСТ ПРОШЛОГО ОБМЕНА ВЫЧИТЫВАЕТСЯ. Иначе первая же команда получит в ответ
# чужие строки и решит, что уже дождалась своего #ГОТОВ.
while IFS= read -r -t 0.4 _ <&3; do :; done
for c in "$@"; do
    echo "== $c"
    printf '%s\n' "$c" >&3
    printf '\n>>> %s\n' "$c" >> "$OUT"
    while IFS= read -r -t 300 line <&3; do
        line="${line%$'\r'}"
        printf '%s\n' "$line" >> "$OUT"
        case "$line" in ''|*[!0-9.eE+-]*) printf '   %s\n' "$line" ;; esac
        case "$line" in '#ГОТОВ'*) break ;; esac
    done
done
echo "снято: $(wc -l < "$OUT") строк -> $OUT"
