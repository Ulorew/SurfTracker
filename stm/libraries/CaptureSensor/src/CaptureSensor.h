#ifndef CAPTURE_SENSOR_H
#define CAPTURE_SENSOR_H

/*
 * CaptureSensor — датчик SimpleFOC поверх аппаратного захвата TIM2 (PA15).
 *
 * ОТКУДА ВЗЯТ КОД. Логика инициализации и чтения перенесена из
 * stm/phone_link/phone_link.ino (функции captureBegin() и captureRead()), где
 * захват жил только в диагностике и вызывался из sendDiag(). Здесь он стал
 * классом, наследующим Sensor, то есть им можно ЗАМКНУТЬ КОНТУР. Все
 * объяснения «почему именно так» перенесены дословно — они добыты на железе,
 * и потерять их дороже, чем переписать код.
 *
 * ЗАЧЕМ ВООБЩЕ ЗАХВАТ (reports/ЭНКОДЕР_PWM.md, замер 21.08.2026):
 *   боевой тракт micros() в прерывании   собственный шум 0.72 .. 0.91 град
 *   аппаратный захват TIM2               собственный шум 0.037 .. 0.069 град
 * Выигрыш 11..22 раза, и берётся он не разрешением, а тем, что фронты
 * защёлкивает железо: задержка входа в обработчик прерывания на результат не
 * влияет вовсе.
 *
 * ГЛАВНОЕ ОТЛИЧИЕ ОТ ИСХОДНИКА — ПРИЗНАК ГОДНОСТИ (isHealthy()).
 * В разомкнутом контуре замерший датчик безвреден: вал крутится по счёту
 * фаз, а негодные показания идут только в лог. В ЗАМКНУТОМ контуре замерший
 * датчик — авария: регулятор видит неподвижный вал при ненулевой уставке и
 * упирает напряжение в потолок. Поэтому класс обязан уметь сказать «мой
 * отсчёт негоден», и вызывающий обязан это спрашивать ДО того, как отдать
 * число регулятору. См. isHealthy(), lastStatus(), badStreak().
 *
 * ЖДАТЬ В ЦИКЛЕ НЕЛЬЗЯ. getSensorAngle() зовётся из loopFOC() сотни-тысячи
 * раз в секунду. Любое ожидание «сейчас придёт хороший захват» — это
 * остановка цикла управления с включёнными ключами, то есть худшая из бед,
 * которую мы тут лечим. Поэтому чтение здесь строго ОДНОПРОХОДНОЕ: четыре
 * регистра, никаких while, никаких delay. Негодный отсчёт не «дожидается» —
 * он НАЗЫВАЕТСЯ негодным и уходит в счётчик.
 *
 * МУТАЦИИ ДЛЯ СТЕНДА (tools/windowing/capture_sensor_check). Тест, который
 * проходит и на исправном коде, и на сломанном, различающей силы не имеет.
 * Поэтому класс умеет ломаться по флагу компиляции, и стенд требует, чтобы
 * каждая поломка уронила СВОЙ названный тест:
 *   CAPSENS_MUT_NO_PAIR_CHECK    — проверка согласованности пары снята
 *   CAPSENS_MUT_NO_PERIOD_CHECK  — границы периода сняты
 *   CAPSENS_MUT_NO_EDGE_CHECK    — «фронтов нет» не распознаётся
 *   CAPSENS_MUT_NAIVE_SLOPE      — наклон взят наивным (360 вместо замера)
 *   CAPSENS_MUT_HEALTH_ALWAYS_OK — isHealthy() тождественно истинна
 * В боевой сборке ни один из них не определён, и код от них не зависит.
 *
 * ХОСТОВАЯ СБОРКА. При CAPSENS_HOST регистры таймера и базовый класс Sensor
 * подменяются заглушкой стенда (capture_sensor_host.h): тот же .cpp
 * компилируется обычным g++ и проверяется на подложных данных без железа.
 */

#include <stdint.h>

#if defined(CAPSENS_HOST)
  #include "capture_sensor_host.h"
#else
  #include <Arduino.h>
  #include <SimpleFOC.h>
  // Захват возможен ТОЛЬКО на TIM2/PA15, см. init(). Параметром конструктора
  // таймер оставлен ради стенда, а не ради выбора: другого годного нет.
  #define CAPSENS_DEFAULT_TIM TIM2
#endif

// ---------------------------------------------------------------------------
// МОСТ МЕЖДУ СКВАЖНОСТЬЮ И ГРАДУСАМИ — ИЗМЕРЕН, А НЕ ВЗЯТ ИЗ ДАТАШИТА
// ---------------------------------------------------------------------------
//
// Захват даёт скважность high/period. Во что она переводится — ВОПРОС, а не
// данность: часть кадра AS5048A служебная, поэтому скважность пробегает не
// всю единицу, и наивные «360 градусов на единицу скважности» неверны.
//
// Замер на живом железе 21.08.2026 (reports/ЭНКОДЕР_PWM.md, раздел «Замер
// обоих трактов»), подгонка к боевому тракту по участкам вращения:
//
//   наклон                362.6 .. 362.8 град на единицу скважности
//                         (два независимых прогона)
//   размах скважности     0.989 .. 0.993
//   мёртвый участок кадра 0.7 .. 1.1 %
//   СВЕРКА: наклон x размах = 358.96 .. 360.03 при обязательных 360
//
// Сверка независима: наклон получен подгонкой к боевому тракту, размах — по
// величине скачка на шве кадра. Сходятся в пределах градуса, значит мост
// измерен, а не подогнан.
//
// КАК ПЕРЕМЕРИТЬ. Снять лог DIAG с вращением вала и прогнать
//   tools/link/diag_metrics.py <лог>
// Раздел «МОСТ МЕЖДУ ШКАЛАМИ» напечатает наклон, размах и сверку
// «наклон x размах = 360». Сверка там — ГЕЙТ: не сошлась, значит одно из двух
// измерений врёт, и подставлять полученный наклон сюда нельзя.
//
// МОСТ НЕЛЬЗЯ МЕРИТЬ СКВОЗЬ ШОВ КАДРА. На шве скважность падает с верхней
// границы на нижнюю, и развёртка фазы мёртвый участок ПРОГЛАТЫВАЕТ —
// добавляет ровно 1.0 вместо настоящего размаха. Наклон, посчитанный сквозь
// шов, схлопывается к наивным 360 при любом истинном значении: на подложке
// заложенные 371.5 восстанавливались как 359.5. Поэтому diag_metrics.py режет
// ход на участки без шва, и перемерять надо только так.
#ifdef CAPSENS_MUT_NAIVE_SLOPE
static const float CAPSENS_DEG_PER_DUTY = 360.0f;   // МУТАЦИЯ: наивный наклон
#else
static const float CAPSENS_DEG_PER_DUTY = 362.7f;   // середина замера 362.6..362.8
#endif

// Размах НЕ задаётся отдельным числом, а ВЫВОДИТСЯ из наклона. Так шов кадра
// сходится ТОЧНО: угол считается как (скважность - низ) * наклон по модулю
// 360, и чтобы на шве не было разрыва, произведение наклон x размах обязано
// равняться ровно 360. Два независимо измеренных числа так не совпадут
// никогда (замер дал 358.96..360.03), поэтому свободным оставлено ОДНО, а
// второе получено из требования непрерывности. Стенд проверяет, что
// выведенный размах попадает в измеренную полосу 0.989..0.993 — это и есть
// та же сверка, только в обратную сторону.
static const float CAPSENS_DUTY_SPAN = 360.0f / CAPSENS_DEG_PER_DUTY;

// ГДЕ НОЛЬ. Нижняя граница живой части кадра: у боевого тракта ей отвечает
// SENS_MIN_US = 3 мкс при кадре 921 мкс (phone_link.ino), то есть 0.00326.
// Это ТОЛЬКО СМЕЩЕНИЕ: сдвиг нуля поворачивает всю шкалу на постоянную и на
// непрерывность шва не влияет вовсе (сдвиг под модулем 360 сокращается).
// Для замкнутого контура он безразличен — электрический ноль всё равно
// находит motor.initFOC(). Держится здесь ради того, чтобы ноль датчика
// совпадал с нулём сырого кода энкодера, а не был случайным.
static const float CAPSENS_DUTY_MIN = 3.0f / 921.0f;

// ГРАНИЦЫ ПЕРИОДА В ТИКАХ TIM2 — ровно те, что стояли в captureRead().
// TIM2 тактуется 170 МГц без предделителя, кадр AS5048A измерен как
// 922.1..922.8 мкс = ~156700 тиков. Границы 136000..212500 тиков это
// 800..1250 мкс: заведомо шире разброса экземпляров датчика и заведомо уже
// любого мусора от наводки или обрыва.
static const uint32_t CAPSENS_PERIOD_MIN_TICKS = 136000UL;
static const uint32_t CAPSENS_PERIOD_MAX_TICKS = 212500UL;

// ПОТОЛОК ВОЗРАСТА: два максимальных периода. Больше этого — нарастающего
// фронта не было дольше двух кадров, то есть сигнала НЕТ (обрыв, севший
// датчик, снятое питание). Отдельный признак нужен для РАЗЛИЧЕНИЯ: без него
// замерший датчик неотличим от разового попадания в мёртвый участок кадра.
static const uint32_t CAPSENS_AGE_MAX_TICKS = 2UL * CAPSENS_PERIOD_MAX_TICKS;

/** Разбор одного чтения захвата. Все поля сырые, ни одно не сглажено. */
struct CaptureStatus {
  uint32_t period;    //!< CCR1: период кадра в тиках TIM2
  uint32_t high;      //!< CCR2: ширина импульса в тиках TIM2
  uint32_t age;       //!< CNT: тиков с последнего нарастающего фронта
  bool paired;        //!< период и импульс из ОДНОГО кадра
  bool period_ok;     //!< период в границах CAPSENS_PERIOD_MIN/MAX
  bool width_ok;      //!< 0 < high < period
  bool edges;         //!< фронты есть (возраст не превысил потолок)
  bool lost;          //!< CC1OF: кадр был пропущен между чтениями
  bool cc2if;         //!< снимок CC2IF — ТОЛЬКО диагностика, см. readRaw()
  bool ok;            //!< отсчёт годен: всё перечисленное сошлось
};

/**
 * Датчик SimpleFOC на аппаратном захвате TIM2.
 *
 * Применение:
 *   CaptureSensor sensor;
 *   sensor.init();
 *   motor.linkSensor(&sensor);
 *   ...
 *   motor.loopFOC();
 *   if (!sensor.isHealthy()) { motor.disable(); }   // ОБЯЗАТЕЛЬНО
 */
class CaptureSensor : public Sensor {
 public:
  explicit CaptureSensor(TIM_TypeDef *tim = CAPSENS_DEFAULT_TIM) : tim_(tim) {}

  /** Пины, тактирование и таймер. На хосте не собирается — только железо. */
  void init();

  /** Только регистры таймера. Отделено от init(), чтобы стенд мог сверить
   *  настроечные слова, не имея ни GPIO, ни HAL. */
  void configureTimer();

  /** Одно чтение захвата без ожидания. Возвращает st.ok. */
  bool readRaw(CaptureStatus &st);

  // ---- признак годности ---------------------------------------------------
  //
  // Устроен как СЧЁТЧИК ПОДРЯД ИДУЩИХ НЕГОДНЫХ ЧТЕНИЙ, а не как «последнее
  // чтение негодно». Причина: при частом опросе примерно 1% чтений
  // приходится на мёртвый участок кадра и законно отбраковывается (см.
  // readRaw()). Если ронять годность по одному такому чтению, контур будет
  // выключаться десятки раз в секунду на исправном железе — то есть признак
  // окажется бесполезным и его отключат.
  //
  // ВОЗВРАТ ГОДНОСТИ ТРЕБУЕТ НЕСКОЛЬКИХ ПОДРЯД ГОДНЫХ ЧТЕНИЙ, а не одного.
  // Это лечит мерцание на границе и одну редкую беду: CNT 32-битный, при
  // 170 МГц он оборачивается за 25.3 с. У полностью молчащего датчика
  // возраст растёт, упирается в потолок — и раз в 25 с, проходя через ноль,
  // на одно чтение выглядит правдоподобным. Одиночное такое чтение годность
  // не вернёт.

  /** Годен ли датчик для замыкания контура. ДО первого годного чтения — нет. */
  bool isHealthy() const;

  /** Сколько негодных чтений подряд насчитано (насыщается на 255). */
  uint8_t badStreak() const { return bad_streak_; }

  /** Разбор последнего чтения — для телеметрии и разбора полётов. */
  const CaptureStatus &lastStatus() const { return last_; }

  /** Было ли вообще хоть одно годное чтение с момента init(). */
  bool hasAngle() const { return has_angle_; }

  /** Порог негодности: столько подряд негодных чтений роняют isHealthy(). */
  uint8_t max_bad_reads = 8;
  /** Столько подряд годных чтений нужно, чтобы годность вернулась. */
  uint8_t good_reads_to_recover = 3;

  int needsSearch() override { return 0; }   // датчик абсолютный

 protected:
  /**
   * Угол вала в радианах, [0, 2*PI).
   *
   * НА НЕГОДНОМ ЧТЕНИИ ВОЗВРАЩАЕТСЯ ПОСЛЕДНИЙ ГОДНЫЙ УГОЛ, а не ноль и не
   * мусор: подстановка нуля дала бы регулятору скачок на пол-оборота, что
   * опаснее, чем подержать микросекунду старое значение. Именно поэтому
   * вызывающий ОБЯЗАН спрашивать isHealthy(): по самому числу отличить
   * удержание от движения нельзя.
   */
  float getSensorAngle() override;

 private:
  TIM_TypeDef *tim_;
  CaptureStatus last_ = {};
  float angle_ = 0.0f;
  bool has_angle_ = false;
  bool healthy_ = false;
  uint8_t bad_streak_ = 255;   // до первого чтения датчик негоден
  uint8_t good_streak_ = 0;
};

#endif  // CAPTURE_SENSOR_H
