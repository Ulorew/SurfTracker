float CaptureSensor::getSensorAngle() {
  CaptureStatus st;
  // ОДИН ПРОХОД, БЕЗ ОЖИДАНИЯ. Здесь нельзя ни while, ни повторного чтения
  // «а вдруг теперь сойдётся»: эта функция стоит внутри loopFOC().
  if (!readRaw(st)) {
    good_streak_ = 0;
    if (bad_streak_ < 255) bad_streak_++;
    if (bad_streak_ >= max_bad_reads) healthy_ = false;
    return angle_;   // удержание последнего годного, см. объяснение в .h
  }

  const float duty = (float)st.high / (float)st.period;
  // Скважность -> радианы. Смещение CAPSENS_DUTY_MIN задаёт только положение
  // нуля; масштаб задаёт измеренный наклон.
  float a = (duty - CAPSENS_DUTY_MIN) * CAPSENS_DEG_PER_DUTY
            * (3.14159265358979f / 180.0f);
  // Свёртка в [0, 2*PI). Циклом, а не fmodf: аргумент здесь всегда в пределах
  // одного оборота от диапазона, так что это один-два вычитания, и оно
  // дешевле деления. Границы шва сходятся ТОЧНО, потому что размах выведен из
  // наклона, а не измерен отдельно (см. CAPSENS_DUTY_SPAN).
  const float two_pi = 6.28318530717959f;
  while (a < 0.0f) a += two_pi;
  while (a >= two_pi) a -= two_pi;

  angle_ = a;
  has_angle_ = true;
  bad_streak_ = 0;
  if (good_streak_ < 255) good_streak_++;
  if (good_streak_ >= good_reads_to_recover) healthy_ = true;
  return angle_;
}

bool CaptureSensor::isHealthy() const {
#ifdef CAPSENS_MUT_HEALTH_ALWAYS_OK
  return true;                           // МУТАЦИЯ: признак годности бесполезен
#else
  return healthy_ && has_angle_;
#endif
}
