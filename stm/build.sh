#!/bin/bash
# Сборка и прошивка скетчей платы, одной командой.
#
#   build.sh phone_link          — собрать
#   build.sh phone_link --прошить — собрать и залить через ST-LINK
#   build.sh --список            — какие скетчи есть
#
# ЗАЧЕМ ФАЙЛОМ. Три вещи здесь стоили поиска, и каждая ломает сборку молча:
#
#  1. FQBN. Плата B-G431B-ESC1 лежит под «Disco», а НЕ под «ESC_board» —
#     хотя последнее называется «Electronic speed controllers» и выглядит
#     единственно правильным. Под ESC_board есть только Wraith V1 и STorM32,
#     и попытка собрать туда падает с «invalid value for option pnum».
#
#  2. ВЕРСИЯ ЯДРА 2.10.1, не 3.0.0. На 3.0.0 HardwareSerial стал абстрактным,
#     конструктор с пинами исчез, и канал к ESP32 не собирается вовсе.
#     Автообновление ядра уже ломало сборку дважды (см. шапку phone_link.ino).
#
#  3. ВЕРСИЯ SimpleFOC 2.4.0. Здесь стояло «2.3.5, не 2.4.0» — я неверно
#     прочитал шапку phone_link.ino: там сказано, что 2.3.5 несовместим с
#     ЯДРОМ 3.0.0, а 2.4.0 совместим. Это про ядро, а не про выбор версии
#     библиотеки.
#
#     ДОКАЗАНО ДАМПОМ ФЛЕША: прошивка на плате собирается ПОБАЙТОВО из
#     коммита 4b9dd8d только с 2.4.0 (0 расхождений на 46408 байтах); с 2.3.5
#     расходится на 92%. Отличаются даже отладочные строки библиотеки —
#     в 2.3.5 префикс внутри строки («MOT: Align sensor.»), в 2.4.0 отдельно
#     («ERR-MOT:»), по ним версия и опозналась.
#
#     Это не косметика: сам код написан под 2.4.0. В нём стоит комментарий
#     «loopFOC() ОБЯЗАТЕЛЕН и в разомкнутом контуре — в 2.4.0 именно он
#     подаёт напряжение на фазы, а в 2.3.x оно подавалось внутри
#     velocityOpenloop». Сборка с 2.3.5 дала бы тихо другое поведение вала.
#
# Библиотека SurfProtoV2 подключается симлинком из stm/libraries: держать её
# копию в ~/Arduino значило бы иметь две правды об одном протоколе.
# pipefail ОБЯЗАТЕЛЕН. Без него статус конвейера берётся у ПОСЛЕДНЕЙ команды,
# то есть у `tail`, и он всегда 0 — провалившаяся компиляция выглядела бы
# удачной, а `upload` без --input-dir залил бы на плату ПРЕДЫДУЩИЙ бинарник из
# кэша. Проверка воркфлоу это воспроизвела.
set -euo pipefail
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
# arduino-cli ИЩЕТСЯ, А НЕ ПОДРАЗУМЕВАЕТСЯ. Здесь стоял путь ~/Android/arduino,
# которого нет ни на ноутбуке, ни на lm: скетчи собирались бы ровно на той
# машине, где я его когда-то распаковал, а на остальных отказ выглядел бы как
# «нет arduino-cli» — то есть как отсутствие инструмента, а не как неверный путь.
CLI="${ARDUINO_CLI:-$(command -v arduino-cli || true)}"
if [ -z "$CLI" ]; then
    for c in "$HOME/.local/bin/arduino-cli" "$HOME/Android/arduino/arduino-cli" \
             "$HOME/bin/arduino-cli"; do
        [ -x "$c" ] && { CLI="$c"; break; }
    done
fi
FQBN="STMicroelectronics:stm32:Disco:pnum=B_G431B_ESC1"

[ -x "$CLI" ] || { echo "нет arduino-cli в $CLI"; exit 1; }

if [ "${1:-}" = "--список" ] || [ $# -eq 0 ]; then
    echo "скетчи в stm/:"
    for d in "$ROOT"/stm/*/; do
        n=$(basename "$d")
        [ -f "$d/$n.ino" ] && echo "  $n"
    done
    exit 0
fi

SKETCH="$ROOT/stm/$1"
[ -f "$SKETCH/$(basename "$SKETCH").ino" ] || { echo "нет скетча $1"; exit 1; }

# Симлинки на СВОИ библиотеки — идемпотентно, чтобы работало на любой машине.
# Цикл, а не поимённо: библиотек в stm/libraries стало больше одной, и
# забытый симлинк ломает сборку сообщением «нет такого заголовка», по которому
# причину не угадать.
SB=$("$CLI" config get directories.user)
mkdir -p "$SB/libraries"
for L in "$ROOT"/stm/libraries/*/; do
    ln -sfn "${L%/}" "$SB/libraries/$(basename "${L%/}")"
done

# ВЕРСИЯ БИБЛИОТЕКИ ПРОВЕРЯЕТСЯ, А НЕ ПОДРАЗУМЕВАЕТСЯ. Расхождение версии
# меняет поведение вала молча: собранная не тем SimpleFOC прошивка ставится,
# запускается и отвечает по протоколу — а фазы ведёт иначе.
FOCV=$("$CLI" lib list 2>/dev/null | awk '/Simple FOC/{print $3}')
if [ "$FOCV" != "2.4.0" ]; then
    echo "ОТКАЗ: SimpleFOC $FOCV, а нужен 2.4.0 (доказано дампом флеша)."
    echo "       поставить: arduino-cli lib install \"Simple FOC\"@2.4.0"
    exit 1
fi

echo "== сборка $1 (SimpleFOC $FOCV) =="
# Бинарь кладётся в ЯВНЫЙ каталог, и заливается потом ровно он: без
# --input-dir upload берёт файл из кэша arduino-cli, который может быть от
# прошлой удачной сборки.
OUT="$SKETCH/build"
rm -rf "$OUT"
# КОММИТ ЗАШИВАЕТСЯ В ПРОШИВКУ. Манифест прогона обязан называть код, которым
# он снят; иначе через день не отличить, какой сборкой получено число.
COMMIT=$(git -C "$ROOT" rev-parse --short HEAD 2>/dev/null || echo "нет")
DIRTY=$(git -C "$ROOT" diff --quiet 2>/dev/null && echo "" || echo "+грязь")
"$CLI" compile -b "$FQBN" --output-dir "$OUT" \
    --build-property "compiler.cpp.extra_flags=-DFW_COMMIT=\"$COMMIT$DIRTY\"" \
    "$SKETCH" 2>&1 \
    | grep -vE "^$|pragma message|note:|\^" | tail -6
# ОШИБКА КОМПИЛЯЦИИ ОБЯЗАНА БЫТЬ ВИДНА. Фильтр выше режет шум, но вместе с ним
# резал и строки error: — сборка падала, а причина не печаталась вовсе, и
# приходилось компилировать вручную, чтобы её увидеть.
if [ ! -s "$OUT/$(basename "$SKETCH").ino.bin" ]; then
    echo "--- ошибки компиляции ---"
    "$CLI" compile -b "$FQBN" "$SKETCH" 2>&1 | grep -E "error:" | head -10
fi
BIN="$OUT/$(basename "$SKETCH").ino.bin"
[ -s "$BIN" ] || { echo "ОТКАЗ: бинарь не собрался ($BIN)"; exit 1; }
echo "  бинарь: $BIN ($(stat -c %s "$BIN") байт)"

if [ "${2:-}" = "--прошить" ]; then
    # ПРОШИВКА — ДЕЙСТВИЕ С ЖЕЛЕЗОМ. Плата под напряжением, на валу мотор;
    # заливка обрывает текущую прошивку и на секунды оставляет выходы в
    # неопределённом состоянии. Поэтому подтверждение спрашивается здесь, а не
    # подразумевается флагом.
    echo
    echo "ВНИМАНИЕ: заливка перезапишет прошивку на плате."
    echo "Убедитесь, что это согласовано и вал никому не мешает."
    printf "продолжить? [да/нет] "
    # ИМЯ ПЕРЕМЕННОЙ ЛАТИНИЦЕЙ. Здесь стояло `read -r ответ`, и bash отвечал
    # «not a valid identifier»: идентификаторы у него только ASCII. То есть
    # ветка --прошить не работала ВООБЩЕ ни разу — заливка молча падала на
    # подтверждении, а сообщение выглядело как ошибка ввода пользователя.
    read -r answer
    [ "$answer" = "да" ] || { echo "отменено"; exit 1; }
    # ДВА ПУТИ ЗАЛИВКИ. Штатный идёт через массовое хранилище DIS_G431CB, и он
    # ломается молча, когда автомонтирование не сработало: «Failed uploading,
    # exit status 3», а на плате остаётся ПРЕЖНЯЯ прошивка. Это опаснее, чем
    # отказ: следующий прогон выглядит нормальным, но снят другим кодом.
    # Поэтому при неудаче пробуем ST-LINK, а если и он не смог — падаем.
    if ! "$CLI" upload -b "$FQBN" --input-dir "$OUT" "$SKETCH" 2>&1 | tail -4; then :; fi
    if ! mountpoint -q /media/*/DIS_G431CB 2>/dev/null; then
        OCD=$(ls "$HOME"/.arduino15/packages/STMicroelectronics/tools/xpack-openocd/*/bin/openocd 2>/dev/null | head -1)
        if [ -x "$OCD" ]; then
            echo "== массовое хранилище не смонтировано, заливаю через ST-LINK =="
            SCR="$(dirname "$(dirname "$OCD")")/openocd/scripts"
            "$OCD" -s "$SCR" -f interface/stlink.cfg -f target/stm32g4x.cfg \
                -c "program $OUT/$(basename "$SKETCH").ino.elf verify reset exit" 2>&1 \
                | grep -E "Verified|Error|error" | tail -3
        fi
    fi
fi
